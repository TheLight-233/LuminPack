using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace LuminPack.Code.Core;

internal sealed partial class StaticSerializerBinding
{
    /// <summary>Emits one concrete interceptor per distinct constructed signature.</summary>
    /// <param name="available">Payloads whose concrete operations were emitted.</param>
    /// <returns>Shared static entries with compiler locations or build-only IL mappings.</returns>
    internal string Emit(IEnumerable<ITypeSymbol> available)
    {
        var types = new HashSet<string>(available.Select(FormatterTypeName.Get), StringComparer.Ordinal);
        var selected = _operations.Where(pair => types.Contains(FormatterTypeName.Get(Payload(pair.Value)))).ToArray();
        var operations = new HashSet<string>(selected.Select(pair => pair.Key), StringComparer.Ordinal);
        foreach (var wrapper in _wrappers.Values)
            if (wrapper.Operations.Any(operation => !operations.Contains(operation)))
                wrapper.Valid = false;
        RemoveInvalidWrappers();
        var locations = _calls.GroupBy(call => Signature(call.Method), StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Select(call => call.Attribute).Distinct(StringComparer.Ordinal).ToArray(), StringComparer.Ordinal);
        if (selected.Length == 0 && _wrapperCalls.Count == 0)
            return string.Empty;
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0436, CS1591\n");
        foreach (string name in new[] { "System", "System.Buffers", "System.IO", "System.Threading", "System.Threading.Tasks", "LuminPack.Core", "LuminPack.Option", "LuminPack.Utility" })
            text.Append("using global::").Append(name).AppendLine(";");
        text.AppendLine();
        bool il = InterceptionSupport.UsesIlRewriting((CSharpParseOptions)_input.SyntaxTrees.First().Options);
        if (il)
            AppendIlAttribute(text);
        else
        {
            text.AppendLine("namespace System.Runtime.CompilerServices\n{");
            text.AppendLine("    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
            text.AppendLine("    file sealed class InterceptsLocationAttribute : global::System.Attribute\n    {");
            text.AppendLine("        public InterceptsLocationAttribute(int version, string data) { }\n    }\n}\n");
        }
        text.AppendLine("namespace LuminPack\n{\n    public static partial class LuminPackSerializer\n    {");
        foreach (var operation in selected)
        {
            var method = operation.Value;
            if (il)
                AppendIlMapping(text, method, GenericDeclaration(method).Length != 0 ? method.TypeArguments.Length - 1 : -1);
            if (locations.TryGetValue(operation.Key, out var attributes))
                foreach (var location in attributes)
                    text.Append("        ").AppendLine(location);
            text.Append("        internal static ").Append(TypeName(method.ReturnType)).Append(" Intercept_")
                .Append(RootContainerProjection.Hash(operation.Key)).Append(GenericDeclaration(method)).Append('(')
                .Append(string.Join(", ", method.Parameters.Select(Parameter))).Append(')').AppendLine(GenericConstraints(method));
            text.AppendLine("        {");
            AppendCall(text, method, Payload(method));
            text.AppendLine("        }\n");
        }
        EmitWrappers(text);
        text.AppendLine("    }\n}");
        return text.ToString();
    }

    /// <summary>Writes a concrete invocation while retaining value-returning read convenience semantics.</summary>
    /// <param name="text">The interceptor body.</param>
    /// <param name="method">The constructed generic facade signature.</param>
    /// <param name="payload">The concrete payload.</param>
    private void AppendCall(StringBuilder text, IMethodSymbol method, ITypeSymbol payload)
    {
        bool state = method.Parameters.Length != 0 && method.Parameters[0].Type.ContainingNamespace?.ToDisplayString() == "LuminPack.Core" &&
            method.Parameters[0].Type.Name is "LuminPackWriter" or "LuminPackReader" or "LuminPackJsonWriter" or "LuminPackJsonReader" or "LuminPackEvaluator";
        string owner = "global::LuminPack.LuminPackSerializer" + (state ? "" : "." + EntryName(FormatterTypeName.Get(payload)));
        string profile = method.TypeArguments.Length > 1 ? "<" + TypeName(method.TypeArguments.Last()) + ">" : string.Empty;
        if (!state && profile.Length == 0)
        {
            var declaration = LuminPack.SourceGenerator.CompiledOptions.Resolve(payload, _binding);
            profile = "<" + (method.Name == "DeserializeJson" ? declaration.JsonInput : declaration).TypeName + ">";
        }
        var arguments = method.Parameters.Select(parameter => Passing(parameter.RefKind) + Escape(parameter.Name)).ToList();
        bool valueRead = method.Name is "Deserialize" or "DeserializeJson" &&
            !method.Parameters.Any(parameter => parameter.Name == "value") && !method.ReturnsVoid;
        if (valueRead)
        {
            text.Append("            ").Append(TypeName(payload)).AppendLine(" result = default!;");
            arguments.Add("ref result");
        }
        if (method.Name == "DeserializeAsync" && !method.Parameters.Any(parameter => parameter.Name == "value"))
            arguments.Insert(1, "default(" + TypeName(payload) + ")");
        text.Append("            ");
        if (!method.ReturnsVoid && !valueRead)
            text.Append("return ");
        string operation = state ? UniqueStateEntries.Name(method.Name, FormatterTypeName.Get(payload)) : method.Name;
        text.Append(owner).Append('.').Append(operation).Append(profile).Append('(')
            .Append(string.Join(", ", arguments)).AppendLine(");");
        if (valueRead)
            text.AppendLine("            return result;");
    }

    /// <summary>Builds an exact stable signature key with concrete argument and profile identities.</summary>
    /// <param name="method">The constructed operation.</param>
    /// <returns>The value-only sharing key.</returns>
    private static string Signature(IMethodSymbol method)
        => method.Name + "|" + TypeName(method.ReturnType) + "|" + string.Join("|", method.TypeArguments.Select(TypeName)) + "|" +
            string.Join("|", method.Parameters.Select(parameter => parameter.RefKind + ":" + TypeName(parameter.Type)));

    /// <summary>Renders a parameter with its original reference-safety contract.</summary>
    /// <param name="parameter">The constructed operation parameter.</param>
    /// <returns>The interceptor parameter declaration.</returns>
    private static string Parameter(IParameterSymbol parameter)
    {
        bool scoped = parameter.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax() is ParameterSyntax syntax &&
            syntax.Modifiers.Any(token => token.ValueText == "scoped");
        return (scoped ? "scoped " : "") + Passing(parameter.RefKind) + TypeName(parameter.Type) + " " + Escape(parameter.Name);
    }

    /// <summary>Renders an exact by-reference passing modifier.</summary>
    /// <param name="kind">The parameter's passing convention.</param>
    /// <returns>The C# modifier and trailing space, or an empty string.</returns>
    private static string Passing(RefKind kind) => kind switch
    {
        RefKind.Ref => "ref ",
        RefKind.Out => "out ",
        RefKind.In => "in ",
        _ => "",
    };

    /// <summary>Formats an exact compiler type for generated code.</summary>
    /// <param name="type">The constructed type.</param>
    /// <returns>A globally qualified spelling.</returns>
    private static string TypeName(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    /// <summary>Escapes a parameter whose name is a C# keyword.</summary>
    /// <param name="name">The compiler identifier.</param>
    /// <returns>A valid source identifier.</returns>
    private static string Escape(string name) => SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;

    /// <summary>Retains open stateless profile parameters on a direct interceptor.</summary>
    /// <param name="method">The selected profile construction.</param>
    /// <returns>The type parameter declaration, or an empty string for a closed entry.</returns>
    private static string GenericDeclaration(IMethodSymbol method)
        => method.TypeArguments.Any(LuminPackExtensionGenerator.ContainsTypeParameter)
            ? "<" + string.Join(", ", method.TypeParameters.Select(parameter => Escape(parameter.Name))) + ">" : string.Empty;

    /// <summary>Retains the constraints of an open stateless profile.</summary>
    /// <param name="method">The selected profile construction.</param>
    /// <returns>The stateless profile constraint, or an empty string.</returns>
    private static string GenericConstraints(IMethodSymbol method)
        => GenericDeclaration(method).Length != 0
            ? " where " + Escape(method.TypeParameters.Last().Name) + " : struct, global::LuminPack.Option.ILuminPackOptions" : string.Empty;
}
