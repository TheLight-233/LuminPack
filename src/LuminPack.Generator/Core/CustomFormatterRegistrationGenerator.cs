using System.Collections.Generic;
using System.Linq;
using System.Text;
using LuminPack.SourceGenerator;
using Microsoft.CodeAnalysis;

namespace LuminPack.Code.Core;

/// <summary>Emits the module initializer that registers every valid Custom formatter type.</summary>
internal static class CustomFormatterRegistrationGenerator
{
    /// <summary>
    /// Generates the registration source for the valid Custom models, or an empty string when
    /// there is nothing to register.
    /// </summary>
    /// <param name="models">The models used by this operation.</param>
    /// <param name="compilation">The compilation whose symbols and referenced types are analyzed.</param>
    /// <param name="metaInfo">The language, framework, and generation settings.</param>
    /// <param name="isUnity">The is unity used by this operation.</param>
    /// <returns>The result of the operation.</returns>
    internal static string Generate(
        IReadOnlyList<CustomFormatterModel> models,
        Compilation compilation,
        MetaInfo metaInfo,
        bool isUnity)
    {
        return GenerateBlocks(models.Where(static model => !model.HasErrors && model.RegisterTier > 0)
            .Select(model => GenerateRegistrationBlock(model.TypeName, model.RegisterTier)).ToArray(), compilation, metaInfo, isUnity);
    }

    /// <summary>Assembles the unchanged registry wrapper around cached registration contributions.</summary>
    /// <param name="blocks">Valid registration blocks in legacy declared-type order.</param>
    /// <param name="compilation">The compilation supplying assembly identity.</param>
    /// <param name="metaInfo">The current generation settings.</param>
    /// <param name="isUnity">Whether Unity registration attributes are required.</param>
    /// <returns>The exact legacy registry, or an empty string for no registrations.</returns>
    internal static string GenerateBlocks(IReadOnlyList<string> blocks, Compilation compilation, MetaInfo metaInfo, bool isUnity)
    {
        if (blocks.Count == 0) return string.Empty;
        string asmRaw = compilation.AssemblyName ?? "Unknown";
        string asmSafe = SanitizeId(asmRaw);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// LuminPack Custom formatter registration — do not modify");
        sb.AppendLine("#nullable enable annotations\n#pragma warning disable CS0162, CS0168, CS0219, CS0436, CS0649");
        sb.AppendLine();
        sb.AppendLine("using global::System;");
        sb.AppendLine("using global::System.Runtime.CompilerServices;");
        sb.AppendLine("using global::LuminPack;");
        sb.AppendLine();

        bool hasNs = asmSafe != "Unknown";
        if (hasNs) { sb.AppendLine($"namespace LuminPackRegisters.{asmSafe}"); sb.AppendLine("{"); }

        sb.AppendLine("    internal static unsafe class LuminPackCustomFormatterRegistry");
        sb.AppendLine("    {");

        if (isUnity)
        {
            sb.AppendLine("#if UNITY_EDITOR");
            sb.AppendLine("        [global::UnityEditor.InitializeOnLoadMethod]");
            sb.AppendLine("#endif");
            sb.AppendLine("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.BeforeSceneLoad)]");
        }
        else
        {
            sb.AppendLine("#if NET5_0_OR_GREATER");
            sb.AppendLine("        [System.Runtime.CompilerServices.ModuleInitializerAttribute]");
            sb.AppendLine("#else");
            sb.AppendLine("        // Initialization must be invoked explicitly.");
            sb.AppendLine($"        // Call from the application entry point: LuminPackRegisters.{asmSafe}.LuminPackCustomFormatterRegistry.Initialize()");
            sb.AppendLine("#endif");
        }
        sb.AppendLine("        internal static void Initialize()");
        sb.AppendLine("        {");

        foreach (string block in blocks) sb.Append(block);

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        if (hasNs) sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>Builds one exact legacy registration block from validated symbol-free facts.</summary>
    /// <param name="type">The fully qualified formatter type name.</param>
    /// <param name="tier">The original validated registration overload tier.</param>
    /// <returns>The complete registration statements with original whitespace.</returns>
    internal static string GenerateRegistrationBlock(string type, int tier)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"            global::LuminPack.LuminPackSerializer.Register<{type}>(");
        sb.AppendLine($"                &{type}.{CustomFormatterAnalyzer.SerializeName},");
        sb.AppendLine($"                &{type}.{CustomFormatterAnalyzer.DeserializeName}");
        if (tier >= 2)
        {
            sb.AppendLine($"                , &{type}.{CustomFormatterAnalyzer.SerializeJsonName}");
            sb.AppendLine($"                , &{type}.{CustomFormatterAnalyzer.DeserializeJsonName}");
        }
        if (tier >= 3) sb.AppendLine($"                , &{type}.{CustomFormatterAnalyzer.CalculateOffsetName}");
        sb.AppendLine("            );");
        return sb.ToString();
    }

    /// <summary>Performs the sanitize id step for the current operation.</summary>
    /// <param name="name">The name used by this operation.</param>
    /// <returns>The result of the operation.</returns>
    private static string SanitizeId(string name)
    {
        if (string.IsNullOrEmpty(name)) return "Unknown";
        var sb = new StringBuilder(name.Length);
        for (int i = 0; i < name.Length; i++)
        {
            char c = name[i];
            if (i == 0) sb.Append(char.IsLetter(c) || c == '_' ? c : '_');
            else sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
        }
        return sb.ToString();
    }
}
