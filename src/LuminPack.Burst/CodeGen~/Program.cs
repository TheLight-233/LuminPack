using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

string repository = Path.GetFullPath(args.Length == 0 ? "../../.." : args[0]);
string output = Path.Combine(repository, "src/LuminPack.Burst/Runtime/Generated/CoreAlgorithms.g.cs");
bool verify = args.Contains("--verify", StringComparer.Ordinal);
string coreRoot = Path.Combine(repository, "src/LuminPack.Core");
int sourceArgument = Array.IndexOf(args, "--core-source-root");
if (sourceArgument >= 0) coreRoot = Path.GetFullPath(args[sourceArgument + 1]);
bool textOnly = args.Contains("--text-only", StringComparer.Ordinal);
bool textMatches = CoreTextProjection.Generate(coreRoot, Path.GetDirectoryName(output)!, verify);
if (!textMatches) return 1;
if (textOnly) return textMatches ? 0 : 1;
var inputs = new (string File, string[] Methods)[]
{
    ("Utility/Memory/Simd/LuminPackMarshal.Copy.cs", ["CopyScalarBlock", "CopyVector128Block", "CopyVector256Block", "CopyShortBlock"]),
    ("Utility/Memory/Simd/LuminPackMarshal.Copy.Vectors.cs", ["CopyVector512Block"]),
    ("Utility/Compression/LuminCompressor.cs", ["CopyMatch", "CopyMatchCore8", "CopyMatch512", "CopyMatch256", "CopyMatch128", "ExtendMatch", "ExtendMatch512", "ExtendMatch256", "ExtendMatch128", "ExtendMatchScalar", "ReadU64", "TrailingZeroBytes"]),
    ("Cryptography/LuminChaCha20Poly1305.cs", ["XorKeystream"])
};
var builder = new StringBuilder("// <auto-generated/>\n// Projected from Core; edit the Core algorithms, never this generated file.\n#if LUMINPACK_BURST\nusing System;\nusing System.Runtime.CompilerServices;\nusing Unsafe = LuminPack.Burst.KernelMemory;\nusing BitOperations = LuminPack.Burst.KernelBits;\nnamespace LuminPack.Burst\n{\n    internal static unsafe class CoreAlgorithms\n    {\n");
var options = new CSharpParseOptions(LanguageVersion.Preview, preprocessorSymbols: ["NET8_0_OR_GREATER", "NET6_0_OR_GREATER"]);
foreach (var input in inputs)
{
    string path = Path.Combine(coreRoot, input.File);
    string source = File.ReadAllText(path);
    builder.Append("// Core source SHA256: ").Append(input.File).Append(' ').Append(Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(source)))).Append('\n');
    var root = CSharpSyntaxTree.ParseText(source, options).GetRoot();
    foreach (string name in input.Methods)
    {
        var method = root.DescendantNodes().OfType<MethodDeclarationSyntax>().Single(m => m.Identifier.ValueText == name);
        method = (MethodDeclarationSyntax)new RemoveInactiveBranches().Visit(method)!;
        method = method.WithModifiers(SyntaxFactory.TokenList(SyntaxFactory.Token(SyntaxKind.InternalKeyword), SyntaxFactory.Token(SyntaxKind.StaticKeyword)));
        string body = method.NormalizeWhitespace().ToFullString()
            .Replace("global::LuminPack.Code.LuminPackMarshal.CopyBlockUnaligned", "KernelMemory.CopyBlockUnaligned", StringComparison.Ordinal)
            .Replace("Unsafe.CopyBlockUnaligned", "KernelMemory.CopyBlockUnaligned", StringComparison.Ordinal)
            .Replace("Environment.Is64BitProcess", "KernelMemory.Is64Bit", StringComparison.Ordinal);
        builder.AppendLine(body);
    }
}
builder.Append("    }\n}\n#endif\n");
string generated = builder.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
if (verify)
{
    if (!File.Exists(output) || File.ReadAllText(output).Replace("\r\n", "\n", StringComparison.Ordinal) != generated)
        return 1;
    Console.WriteLine("Burst algorithms exactly match the current projected Core methods.");
    return textMatches ? 0 : 1;
}
Directory.CreateDirectory(Path.GetDirectoryName(output)!);
if (!File.Exists(output) || File.ReadAllText(output) != generated) File.WriteAllText(output, generated, new UTF8Encoding(false));
Console.WriteLine("Projected Core copy, compression and XOR methods; Burst contains no separately maintained algorithms.");
return 0;

/// <summary>Removes disabled text and directives after Roslyn has selected the modern Core algorithm branches.</summary>
internal sealed class RemoveInactiveBranches : CSharpSyntaxRewriter
{
    /// <summary>Preserves active algorithm syntax and documentation while dropping preprocessing trivia.</summary>
    /// <param name="trivia">The source trivia.</param>
    /// <returns>The active trivia, or an empty trivia for a disabled branch/directive.</returns>
    public override SyntaxTrivia VisitTrivia(SyntaxTrivia trivia)
        => trivia.IsDirective || trivia.IsKind(SyntaxKind.DisabledTextTrivia) ? default : base.VisitTrivia(trivia);
}
