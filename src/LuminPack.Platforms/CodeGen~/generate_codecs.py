"""Generate explicit scalar codecs from reviewed platform schemas; never inspect Core or generator sources."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[3]
WIDTHS = {'byte': 1, 'int': 4, 'float': 4, 'double': 8}


def emit_module(schema):
    """Render public codecs, explicit registrations, and focused fixture cases for one schema."""
    module = schema['module']
    owner = 'Lumin' + module
    lines = ['// <auto-generated />', '#nullable enable', 'using LuminPack.Code;', 'using LuminPack.Core;',
             'using LuminPack.Platforms;', '', f'namespace LuminPack.{module};', '',
             '/// <summary>Provides explicit public-component binary codecs for platform values.</summary>',
             f'public static unsafe partial class {owner}', '{']
    test = ['// <auto-generated />', '#nullable enable', 'using LuminPack.Platforms.Tests;', f'using LuminPack.{module};', '',
            f'{owner}.Register();', f'{owner}.Register();']
    for item in schema['types']:
        full = 'global::' + item['type']
        name = item['type'].split('.')[-1]
        width = sum(WIDTHS[f['kind']] for f in item['fields']) + (1 if item['empty'] else 0)
        members = ', '.join(f['member'].replace('(int)value.', '') for f in item['fields'])
        lines += [f'    /// <summary>Gets the explicit {name} codec.</summary>',
                  f'    public static LuminPackCodec<{full}> {name}Codec {{ get; }} = new(Write, Read, Size);', '',
                  f'    /// <summary>Writes {members} in order{", preceded by the empty marker" if item["empty"] else ""}.</summary>',
                  '    /// <param name="writer">The Core output cursor.</param><param name="value">The platform value.</param>',
                  f'    public static void Write(ref LuminPackWriter writer, in {full} value)', '    {',
                  f'        writer.EnsureAdditionalCapacity({width});']
        if item['empty']: lines += ['        writer.Write((byte)(value.IsEmpty ? 1 : 0));']
        for field in item['fields']:
            expression = field['member'] if field['member'].startswith('(') else 'value.' + field['member']
            if item['empty']: expression = f'value.IsEmpty ? ({field["kind"]})0 : {expression}'
            lines += [f'        writer.Write({expression});']
        lines += ['    }', '', '    /// <summary>Checks the complete input and constructs the value before publishing either cursor or destination.</summary>',
                  '    /// <param name="reader">The bounded Core input cursor.</param><param name="value">The destination.</param>',
                  f'    public static void Read(ref LuminPackReader reader, ref {full} value)', '    {',
                  f'        reader.EnsureReadable(reader.Position, {width});', '        var pending = reader;']
        if item['empty']:
            lines += ['        byte empty = default;', '        pending.Read(ref empty);',
                      '        if (empty > 1) LuminPackExceptionHelper.ThrowInvalidDataException("Invalid platform empty marker.");']
        variables=[]
        for i,field in enumerate(item['fields']):
            variable = 'field' + re.sub(r'[^A-Za-z0-9]', '', field['member'].replace('(int)value.', ''))
            if variable in variables: variable += str(i)
            variables.append(variable)
            lines += [f'        {field["kind"]} {variable} = default;', f'        pending.Read(ref {variable});']
        factory = item['factory'].format(*variables)
        if item['empty']: factory = f'empty == 1 ? {item["empty"]} : {factory}'
        lines += [f'        {full} candidate = {factory};', '        value = candidate;', '        reader = pending;', '    }', '',
                  f'    /// <summary>Adds the exact {width}-byte record size.</summary>',
                  '    /// <param name="evaluator">The Core size accumulator.</param><param name="value">The platform value.</param>',
                  f'    public static void Size(ref LuminPackEvaluator evaluator, in {full} value) => evaluator.Add({width});', '']
        for sample in item['samples']:
            test += [f'CodecContract.Check({owner}.{name}Codec, ({full})({sample}), "{module}.{name}");']
        if item['empty']:
            test += [f'CodecContract.RejectMarker({owner}.{name}Codec, ({full})default, "{module}.{name}");']
    lines += ['    /// <summary>Registers these binary/size codecs for existing Core generic fallback paths, preserving explicit application entries.</summary>',
              '    /// <remarks>Ordinary generated nested and raw unmanaged operations retain their original contracts.</remarks>',
              '    public static void Register()', '    {']
    for item in schema['types']:
        lines += [f'        PlatformRegistration.Add<global::{item["type"]}>(&Write, &Read, &Size, {item["type"].split(".")[-1]}Codec);']
    lines += ['        RegisterAdditional();', '    }', '', '    /// <summary>Registers module-specific variable records when supplied by another partial file.</summary>',
              '    static partial void RegisterAdditional();', '}']
    test += ['PlatformAdditionalTests.Run();', f'Console.WriteLine("Passed {module} platform contracts.");']
    return '\n'.join(lines)+'\n', '\n'.join(test)+'\n'


def main():
    """Write deterministic source or verify that checked-in projections match reviewed schemas."""
    parser=argparse.ArgumentParser()
    parser.add_argument('--verify', action='store_true')
    args=parser.parse_args()
    count=0
    for path in sorted((ROOT/'src').glob('LuminPack.*/Codecs.json')):
        schema=json.loads(path.read_text(encoding='utf-8'))
        source,test=emit_module(schema)
        outputs={path.parent/'Runtime'/('Lumin'+schema['module']+'.Values.g.cs'):source,
                 path.parent/'Tests~'/'Program.g.cs':test}
        for output,content in outputs.items():
            if args.verify:
                if not output.exists() or output.read_text(encoding='utf-8') != content:
                    raise SystemExit('Stale platform projection: '+str(output.relative_to(ROOT)))
            else:
                output.parent.mkdir(exist_ok=True)
                output.write_text(content,encoding='utf-8')
        count+=len(schema['types'])
    print(('Verified' if args.verify else 'Generated')+f' {count} explicit scalar codecs from platform schemas.')


if __name__=='__main__':
    main()
