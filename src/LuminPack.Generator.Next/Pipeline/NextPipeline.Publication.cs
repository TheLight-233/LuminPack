    /// <summary>Publishes binary, JSON and formatter folders from one normalized graph.</summary>
    /// <param name="context">The incremental generator context.</param>
    /// <param name="requests">The normalized publication inputs.</param>
    /// <param name="report">Whether the consuming build requested output accounting.</param>
    private static void InitializePublication(IncrementalGeneratorInitializationContext context,
        IncrementalValueProvider<PublicationRequest> requests, IncrementalValueProvider<bool> report)
    {
        context.RegisterPostInitializationOutput(static production =>
        {
            production.AddSource(PublicationHint("Binary/LuminPackGen.LuminPackSerializer.g.cs"), FixedSources.Binary);
            production.AddSource(PublicationHint("Json/LuminPackGen.LuminPackSerializer.g.cs"), FixedSources.Json);
            production.AddSource(PublicationHint("Formatters/LuminPackGen.FormatterDispatch.g.cs"), FixedSources.Dispatch);
            production.AddSource(PublicationHint("Formatters/LuminPackGen.Generated.g.cs"), GeneratedNamespace);
        });
        var cache = new PublicationCache();
        var publication = requests.Combine(report).Select((input, token) => input.Left.Render(cache, token, input.Right))
            .SelectMany(static (files, _) => files);
        context.RegisterSourceOutput(publication, (production, source) =>
        {
            string folder = source.Kind == GenerationKind.Binary ? "Binary/" : source.Kind == GenerationKind.Json ? "Json/" : "Formatters/";
            production.AddSource(PublicationHint(folder + source.Hint), source.Text);
        });
    }

    // Roslyn 4.3 rejects separators in AddSource. Keep the folder spelling on the modern host used for publication checks.
    private static readonly bool DirectoryHints = typeof(Compilation).Assembly.GetName().Version is { } version &&
        (version.Major > 4 || version.Major == 4 && version.Minor >= 14);

    /// <summary>Uses directory hints on modern compiler hosts and an equivalent flat name on older hosts.</summary>
    private static string PublicationHint(string hint) => DirectoryHints ? hint : hint.Replace('/', '.');

    private const string GeneratedNamespace = "// <auto-generated/>\nnamespace LuminPack.Generated { }\n";

    /// <summary>Retains compiler-independent target spellings across drivers in the same host.</summary>
    private static class FixedSources
    {
        internal static readonly string Binary = ScopedForTarget(SerializerDocumentation.BinaryFacade);
        internal static readonly string Json = ScopedForTarget(SerializerDocumentation.JsonFacade);
        internal static readonly string Dispatch = ScopedForTarget(SerializerFacadeSource.Dispatch);
    }

    /// <summary>Publishes the facade's compatibility-target spelling beside the .NET 8 one, as payload files are spelled.</summary>
    /// <param name="text">The fixed facade text.</param>
    /// <returns>The text, with a copy for targets without .NET 8: no <c>scoped</c> parameters, and readers over a stationary
    /// pooled copy of managed input, which the pointer cursor of those targets requires.</returns>
    /// <remarks>Post-initialization output cannot see the language version or the unsafe setting, so the target symbol
    /// selects the spelling and the copy uses the input pinning that needs no unsafe code.</remarks>
    private static string ScopedForTarget(string text)
    {
        string compatible = PointerCursorProjection.PinReaders(ScopedModifier.Replace(text, string.Empty));
        return string.Equals(compatible, text, StringComparison.Ordinal) ? text :
            "#if NET8_0_OR_GREATER\n" + text + "\n#else\n" + compatible + "\n#endif\n";
    }

    private static readonly Regex ScopedModifier = new(@"\bscoped\s+(?=(?:ref|in)\b)", RegexOptions.Compiled | RegexOptions.CultureInvariant);

    /// <summary>A value-equal publication input containing only normalized analysis facts.</summary>
    private sealed class PublicationRequest : IEquatable<PublicationRequest>
    {
        private readonly ImmutableArray<ModeledPayload> _payloads;
        private readonly ImmutableArray<SerializerCallModel> _calls;
        private readonly GeneratorOptions _options;
        private readonly WirePolicy _policy;
        private readonly GeneratedOperations _whole;
        private GeneratedSource[]? _sources;
        private GeneratedSource[]? _reportedSources;
        private PublicationSnapshot? _snapshot;
        internal readonly DiagnosticInfo[] Diagnostics;

        /// <summary>Captures compilation-independent facts shared by the three output families.</summary>
        /// <param name="calls">The bound serializer calls.</param>
        /// <param name="diagnostics">The normalized declaration and assembly diagnostics.</param>
        /// <param name="options">The normalized project settings.</param>
        /// <param name="payloads">The normalized declaration results.</param>
        /// <param name="policy">The assembly wire policy.</param>
        /// <param name="whole">The operations every payload keeps regardless of calls.</param>
        internal PublicationRequest(ImmutableArray<ModeledPayload> payloads, ImmutableArray<SerializerCallModel> calls,
            GeneratorOptions options, WirePolicy policy, DiagnosticInfo[] diagnostics,
            GeneratedOperations whole)
        {
            _whole = whole;
            _payloads = payloads;
            _calls = calls;
            _options = options;
            _policy = policy;
            Diagnostics = diagnostics;
        }

        /// <summary>Renders the shared operation catalog once per changed normalized input.</summary>
        /// <param name="cache">The driver-owned publication cache.</param>
        /// <param name="token">Cancels publication.</param>
        /// <param name="report">Whether to include output accounting.</param>
        /// <returns>The rendered source contributions or statement representation.</returns>
        internal GeneratedSource[] Render(PublicationCache cache, CancellationToken token, bool report)
        {
            // Every owner and alias name spelled below keeps the namespace of a simple name the compilation declares twice.
            using var names = ReadableTypeName.Use(_options.AmbiguousNames);
            lock (this)
            {
                if (_sources != null)
                {
                    cache.Snapshot = _snapshot!;
                    return report ? WithReport(_sources, _snapshot!) : _sources;
                }
                var snapshot = new PublicationSnapshot(cache.Snapshot);
                var plan = OperationPlan.Create(_payloads, _calls, _whole, _options);
                var retained = new List<TypeModel>(_payloads.Length);
                foreach (ModeledPayload payload in _payloads)
                    if (payload.Result.IsComplete && payload.Result.Model is { } model && plan.For(model) != GeneratedOperations.None)
                        retained.Add(model);
                var roots = new List<MemberModel>();
                var seenRoots = new HashSet<MemberModel>();
                foreach (SerializerCallModel call in _calls)
                    if (call.Root != null && seenRoots.Add(call.Root))
                        roots.Add(call.Root);
                if (snapshot.SharedInputs == null || !snapshot.SharedInputs.Matches(retained, roots, _options))
                    snapshot.SharedInputs = new SharedFormatterInputs(retained, roots, _options);
                SharedFormatterSet formatters = snapshot.SharedInputs.Set;
                var sources = NextPipeline.Render(_payloads, formatters, _options, _policy, snapshot, plan);
                bool register = _options.RegisterMode != RegisterMode.Disabled;
                bool intercept = _options.Interceptors && !_calls.IsEmpty;
                var sharedRoots = register || intercept ? snapshot.SharedInputs.PublishedRoots : null;
                if (register)
                    AddFormatterRegistration(sources, _payloads, _calls, formatters, sharedRoots!, plan, _options, _policy);
                // Compiler interception needs the host's location API; the IL rewriter binds the same entries after compilation.
                if (intercept)
                {
                    string interceptors = InterceptorRenderer.Render(_calls, Catalog(_payloads, formatters, sharedRoots!, snapshot.SharedSources), _options.IlRewrite);
                    if (interceptors.Length != 0)
                        sources.Add(new GeneratedSource("LuminPackGen.Interceptors.g.cs", interceptors, GenerationKind.Binary));
                }
                token.ThrowIfCancellationRequested();
                _sources = CompactPublication.Create(sources, token, snapshot.Compact);
                // Compatibility targets advance a pointer cursor; the projection leaves other targets' text untouched.
                if (_options.PointerCursor)
                    for (int index = 0; index < _sources.Length; index++)
                    {
                        GeneratedSource source = _sources[index];
                        string projected = PointerCursorProjection.Apply(source.Text, _options.Unsafe, numericIntPtr: false);
                        if (!ReferenceEquals(projected, source.Text))
                            _sources[index] = new GeneratedSource(source.Hint, projected, source.Kind);
                    }
                _snapshot = snapshot;
                cache.Snapshot = snapshot;
                return report ? WithReport(_sources, snapshot, plan) : _sources;
            }
        }

        /// <summary>Appends the report without changing the normal source snapshot.</summary>
        /// <param name="sources">The compacted and target-projected files.</param>
        /// <param name="snapshot">The retained dependencies and owner operations.</param>
        /// <param name="plan">The current plan, when publication just computed it.</param>
        /// <returns>The source files followed by the report.</returns>
        private GeneratedSource[] WithReport(GeneratedSource[] sources, PublicationSnapshot snapshot, OperationPlan? plan = null)
        {
            if (_reportedSources != null)
                return _reportedSources;
            plan ??= OperationPlan.Create(_payloads, _calls, _whole, _options);
            var counts = new PublicationCounts();
            foreach (ModeledPayload payload in _payloads)
                if (payload.Result.IsComplete && payload.Result.Model is { } model)
                    counts.AddPayload(plan.For(model));
            foreach (string root in snapshot.SharedInputs!.PublishedRoots)
                counts.AddOwner(plan.Owners.For(root));
            foreach (GeneratedSource source in sources)
                counts.AddSource(source.Kind, source.Text);
            counts.AddSource(GenerationKind.Binary, FixedSources.Binary);
            counts.AddSource(GenerationKind.Json, FixedSources.Json);
            counts.AddSource(GenerationKind.Formatter, FixedSources.Dispatch);
            counts.AddSource(GenerationKind.Formatter, GeneratedNamespace);
            var reported = new GeneratedSource[sources.Length + 1];
            sources.CopyTo(reported, 0);
            reported[sources.Length] = new GeneratedSource("LuminPackGen.OutputReport.g.cs", counts.Render(), GenerationKind.Formatter);
            return _reportedSources = reported;
        }

        /// <inheritdoc/>
        public bool Equals(PublicationRequest? other) => other != null && _whole == other._whole && _options.Equals(other._options) && _policy.Equals(other._policy) &&
            Same(_payloads, other._payloads) && Same(_calls, other._calls) && Same(Diagnostics, other.Diagnostics);

        /// <inheritdoc/>
        public override bool Equals(object? obj) => Equals(obj as PublicationRequest);

        /// <inheritdoc/>
        public override int GetHashCode() => _options.GetHashCode() ^ _payloads.Length ^ _calls.Length;
    }

    /// <summary>Retains only normalized facts and generated text for a driver's preceding publication.</summary>
    private sealed class PublicationCache
    {
        internal PublicationSnapshot Snapshot = new(null);
    }

    /// <summary>An independently replaceable publication snapshot retained across incremental publications.</summary>
    private sealed class PublicationSnapshot
    {
        internal readonly Dictionary<string, CachedPayload> Payloads;
        internal readonly CompactPublication.Cache Compact;
        internal SharedFormatterInputs? SharedInputs;
        internal SharedFormatterSet? SharedSet;
        internal OwnerOperations? SharedOperations;
        internal KeyValuePair<string, string>[] SharedSources;

        /// <summary>Copies the preceding driver snapshot for an independent publication.</summary>
        /// <param name="prior">The preceding publication or operation contract.</param>
        internal PublicationSnapshot(PublicationSnapshot? prior)
        {
            Payloads = prior == null ? new(StringComparer.Ordinal) : new(prior.Payloads, StringComparer.Ordinal);
            Compact = new CompactPublication.Cache(prior?.Compact);
            SharedInputs = prior?.SharedInputs;
            SharedSet = prior?.SharedSet;
            SharedOperations = prior?.SharedOperations;
            SharedSources = prior?.SharedSources ?? Array.Empty<KeyValuePair<string, string>>();
        }
    }

    /// <summary>The raw files of one exact normalized model and its project options.</summary>
    private sealed class CachedPayload
    {
        internal readonly TypeModel Model;
        internal readonly GeneratorOptions Options;
        internal readonly GeneratedOperations Operations;
        internal readonly GeneratedSource[] Sources;

        /// <summary>Retains the raw files of one normalized model and its settings.</summary>
        /// <param name="model">The normalized payload model.</param>
        /// <param name="options">The normalized project settings.</param>
        /// <param name="operations">The operations the files implement.</param>
        /// <param name="sources">The generated source contributions.</param>
        internal CachedPayload(TypeModel model, GeneratorOptions options, GeneratedOperations operations, GeneratedSource[] sources)
        {
            Operations = operations;
            Model = model;
            Options = options;
            Sources = sources;
        }
    }

    /// <summary>Renders algorithms before the final method and file publication pass.</summary>
    /// <param name="options">The normalized project settings.</param>
    /// <param name="payloads">The normalized declaration results.</param>
    /// <param name="policy">The assembly wire policy.</param>
    /// <param name="set">The shared formatter requirements.</param>
    /// <param name="snapshot">The independently owned publication snapshot.</param>
    /// <param name="plan">The operations each payload and the shared owners keep.</param>
    /// <returns>The rendered source contributions or statement representation.</returns>
    // AggressiveOptimization is available in newer hosts but unnamed by netstandard2.0.
    [MethodImpl((MethodImplOptions)512)]
    private static List<GeneratedSource> Render(ImmutableArray<ModeledPayload> payloads, SharedFormatterSet set,
        GeneratorOptions options, WirePolicy policy, PublicationSnapshot snapshot, OperationPlan plan)
    {
        var sources = new List<GeneratedSource>();
        var retained = new List<TypeModel>();
        var pending = new Stack<TypeModel>();
        foreach (ModeledPayload payload in payloads)
        {
            if (payload.Result.IsComplete && payload.Result.Model is { } model)
            {
                retained.Add(model);
                pending.Push(model);
            }
        }
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (TypeModel model in retained)
            seen.Add(model.Identity.GlobalName);
        while (pending.Count != 0)
        {
            TypeModel model = pending.Pop();
            foreach (MemberModel member in model.Members)
                if (member is PayloadMember { Nested: RecordModel { Implicit: true } nested } && seen.Add(nested.Identity.GlobalName))
                {
                    retained.Add(nested);
                    pending.Push(nested);
                }
        }
        if (!snapshot.SharedSet.HasValue || !plan.Owners.Equals(snapshot.SharedOperations) || !snapshot.SharedSet.Value.Equals(set))
        {
            snapshot.SharedSources = SharedFormatterPublisher.Render(set, plan.Owners).ToArray();
            snapshot.SharedSet = set;
            snapshot.SharedOperations = plan.Owners;
        }
        var shared = snapshot.SharedSources;
        Dictionary<string, PayloadRenderModel>? inputCandidates = null;
        HashSet<string>? copyable = null;
        List<string>? sharedInputSources = null;
        Dictionary<string, string>? compressedChildren = null;
        HashSet<string>? unchangedUnboundedReads = null;
        var trustedReads = TrustedReadReach.Create(retained);
        Dictionary<string, (TypeModel Payload, GeneratedOperations Operations)>? checkedOwners = null;
        foreach (FormatterModel owner in set.GeneralOwners ?? Array.Empty<FormatterModel>())
        {
            if (!owner.PublishPayload || owner.Payload is not { } payload || payload.Identity.IsGeneric ||
                !HasProjectableRead(payload) || !NeedsInputScope(payload))
                continue;
            GeneratedOperations operations = plan.Owners.For(GeneratedNames.PayloadKey(owner.Type));
            if ((operations & GeneratedOperations.BinaryRead) == 0)
                continue;
            checkedOwners ??= new Dictionary<string, (TypeModel, GeneratedOperations)>(StringComparer.Ordinal);
            string hint = SharedFormatterPublisher.PayloadBinaryHint(ReadableTypeName.Of(GeneratedNames.PayloadKey(owner.Type)));
            if (!checkedOwners.ContainsKey(hint))
                checkedOwners.Add(hint, (payload, operations));
        }
        foreach (var source in shared)
        {
            string text = source.Value;
            if (checkedOwners != null && checkedOwners.TryGetValue(source.Key, out var checkedOwner) &&
                RenderModelFactory.Create(checkedOwner.Payload, options) is { } owner)
            {
                TypeModel payload = checkedOwner.Payload;
                var redirect = CreateRedirect(owner.Readable, payload.Policy.Limits);
                text = PayloadEmitter.Render(owner.WithInput(payload.Policy.Limits, owner.Recursive, redirect), false,
                    options.AvailableAliases, checkedOwner.Operations);
                AddCopies("LuminPackGen." + PublicationNames.Mangle(payload.Identity.GlobalName), redirect);
            }
            sources.Add(new GeneratedSource(source.Key, text, GenericFormatterReuse.IsJson(source.Key) ? GenerationKind.Json : GenerationKind.Formatter));
        }
        foreach (TypeModel model in retained)
        {
            GeneratedOperations operations = plan.For(model);
            if (operations == GeneratedOperations.None)
                continue;
            bool checkedUnion = model is UnionModel { Rejection: null } unionModel && model.Policy.Input == InputPolicy.Untrusted &&
                (operations & GeneratedOperations.BinaryRead) != 0 &&
                (model.Policy.Limits.Explicit || TrustedReadReach.HasTrustedCase(unionModel));
            bool checkedRoot = (operations & GeneratedOperations.BinaryRead) != 0 && HasProjectableRead(model) && NeedsInputScope(model);
            bool cacheable = !checkedRoot && !checkedUnion;
            if (cacheable && snapshot.Payloads.TryGetValue(model.Identity.GlobalName, out var cached) && cached.Operations == operations &&
                cached.Model.Equals(model) && cached.Options.Equals(options))
            {
                sources.AddRange(cached.Sources);
                continue;
            }
            int first = sources.Count;
            var renderContext = new RenderContext(options, AliasTable.For(options.AvailableAliases), operations);
            string hint = "LuminPackGen." + PublicationNames.Mangle(model.Identity.GlobalName);
            string binary;
            string json;
            if (model is UnionModel)
            {
                var union = RenderModelFactory.Create(model, options);
                binary = union == null ? string.Empty : UnionRenderer.Render(union, renderContext, json: false);
                json = union == null ? string.Empty : UnionRenderer.Render(union, renderContext, json: true);
                if (checkedUnion && union != null)
                {
                    InputRedirect? redirect = null;
                    using var writer = new CodeWriter(options.AvailableAliases) { Scoped = union.Net8 };
                    HashSet<string>? emitted = null;
                    foreach (UnionRenderCase item in union.UnionCases)
                    {
                        if (!UnionEmitter.NeedsCheckedCase(union, item) || !(emitted ??= new HashSet<string>(StringComparer.Ordinal)).Add(item.Readable))
                            continue;
                        if (redirect == null)
                        {
                            redirect = CreateRedirect(union.Readable, model.Policy.Limits);
                            writer.Line("namespace LuminPack");
                            writer.Open();
                            writer.Line("public static partial class LuminPackSerializer");
                            writer.Open();
                            writer.Line("internal static class LuminUnionInput_" + union.Readable);
                            writer.Open();
                        }
                        var payload = item.Model;
                        BinaryEmitter.EmitCheckedPayloadRead(payload.WithInput(redirect.Limits, payload.Recursive, redirect), writer, unionCase: true);
                    }
                    if (redirect != null)
                    {
                        writer.Close();
                        writer.Close();
                        writer.Close();
                        Add(hint + ".UnionInput.g.cs", writer.Complete(false), GenerationKind.Binary);
                        AddCopies(hint, redirect);
                    }
                }
            }
            else if (checkedRoot && RenderModelFactory.Create(model, options) is { } root)
            {
                var redirect = CreateRedirect(root.Readable, model.Policy.Limits);
                binary = PayloadEmitter.Render(root.WithInput(model.Policy.Limits, root.Recursive, redirect), false,
                    options.AvailableAliases, operations);
                if ((operations & GeneratedOperations.BinaryRead) != 0)
                    AddCopies(hint, redirect);
                json = JsonRenderer.Instance.Render(model, renderContext);
            }
            else
            {
                binary = BinaryRenderer.Instance.Render(model, renderContext);
                json = JsonRenderer.Instance.Render(model, renderContext);
            }
            Add(hint + ".g.cs", binary, GenerationKind.Binary);
            Add(hint + ".g.cs", json, GenerationKind.Json);
            if (model is StructModel { StoragePlan: not null } && RenderModelFactory.Create(model, options) is { } direct)
                Add(hint + ".Mirror.g.cs", BinaryEmitter.MirrorSource(direct, options.AvailableAliases), GenerationKind.Binary);
            if (cacheable)
            {
                var emitted = new GeneratedSource[sources.Count - first];
                sources.CopyTo(first, emitted, 0, emitted.Length);
                snapshot.Payloads[model.Identity.GlobalName] = new CachedPayload(model, options, operations, emitted);
            }
        }

        bool NeedsInputScope(TypeModel model) => model.Policy.Input == InputPolicy.Untrusted &&
            (model.Policy.Limits.Bounded || trustedReads?.Reaches(model) == true);

        InputRedirect CreateRedirect(string readable, InputLimits limits)
        {
            if (copyable == null)
            {
                copyable = new HashSet<string>(StringComparer.Ordinal);
                inputCandidates = new Dictionary<string, PayloadRenderModel>(StringComparer.Ordinal);
                foreach (TypeModel candidate in retained)
                    if ((plan.For(candidate) & GeneratedOperations.BinaryRead) != 0 && CanCopyPayload(candidate) &&
                        RenderModelFactory.Create(candidate, options, checkedUnionCopy: true) is { Rejection: null } rendered)
                    {
                        inputCandidates[rendered.Readable] = rendered;
                        copyable.Add(rendered.Readable);
                    }
                foreach (FormatterModel owner in set.GeneralOwners ?? Array.Empty<FormatterModel>())
                    if ((owner.PublishPayload || owner.Definition == FormatterDefinitions.GenericUnion) &&
                        owner.Payload is { } candidate && CanCopyPayload(candidate) &&
                        (plan.Owners.For(GeneratedNames.PayloadKey(owner.Type)) & GeneratedOperations.BinaryRead) != 0 &&
                        RenderModelFactory.Create(candidate, options, checkedUnionCopy: true) is { Rejection: null } rendered &&
                        !inputCandidates.ContainsKey(rendered.Readable))
                    {
                        inputCandidates.Add(rendered.Readable, rendered);
                        copyable.Add(rendered.Readable);
                    }
                sharedInputSources = new List<string>(shared.Length);
                foreach (var source in shared)
                {
                    sharedInputSources.Add(source.Value);
                    foreach (Match match in Regex.Matches(source.Value, @"class LuminRoots_(\w+)", RegexOptions.CultureInvariant))
                        if (InputReadRenderer.CanCopy(source.Value, match.Groups[1].Value))
                            copyable.Add(match.Groups[1].Value);
                }
            }
            if (!limits.Bounded && unchangedUnboundedReads == null)
            {
                unchangedUnboundedReads = new HashSet<string>(StringComparer.Ordinal);
                foreach (var candidate in inputCandidates!)
                    if (trustedReads?.NeedsCopy(candidate.Value.GlobalName) != true && !candidate.Value.Trusted)
                        unchangedUnboundedReads.Add(candidate.Key);
            }
            if (limits.Collection != int.MaxValue && compressedChildren == null)
            {
                compressedChildren = new Dictionary<string, string>(StringComparer.Ordinal);
                foreach (FormatterModel owner in set.GeneralOwners ?? Array.Empty<FormatterModel>())
                    if ((owner.Definition == FormatterDefinitions.Array && owner.Rank == 1 ||
                         owner.Definition == "System.Collections.Generic.List") &&
                        owner.Arguments[0].Definition == FormatterDefinitions.Array && owner.Arguments[0].Rank == 1)
                        AddCompressedChild(owner.Type, owner.Arguments[0].Type);
                foreach (SequenceOwnerFact owner in set.SequenceOwners ?? Array.Empty<SequenceOwnerFact>())
                    if ((owner.Family == FormatterRegistry.Array || owner.Family.Kind == CollectionKind.List) &&
                        owner.ForwardedType is { } child)
                        AddCompressedChild(owner.DeclaredType, child);
            }
            return new InputRedirect(readable, GeneratedNames.Extension(options.AssemblyName), limits, copyable,
                limits.Bounded ? null : unchangedUnboundedReads, compressedChildren!);

            void AddCompressedChild(string type, string child)
            {
                if (child.IndexOf('<') < 0 && child.EndsWith("[]", StringComparison.Ordinal))
                    compressedChildren![ReadableTypeName.Of(GeneratedNames.PayloadKey(type))] =
                        ReadableTypeName.Of(GeneratedNames.PayloadKey(child));
            }
        }

        void AddCopies(string hint, InputRedirect redirect)
        {
            string formatters = InputReadRenderer.RenderCopies(redirect, inputCandidates!, sharedInputSources!,
                options.AvailableAliases, options.Net8, set, out string payloadCopies);
            Add(hint + ".InputReads.g.cs", formatters, GenerationKind.Binary);
            Add(hint + ".InputPayloadReads.g.cs", payloadCopies, GenerationKind.Binary);
        }

        var obsolete = new List<string>();
        foreach (string name in snapshot.Payloads.Keys)
            if (!seen.Contains(name))
                obsolete.Add(name);
        foreach (string name in obsolete)
            snapshot.Payloads.Remove(name);
        Add("LuminPackGen.Registration.g.cs", SerializerRegistrationSource.Render(options), GenerationKind.Formatter);
        Add("LuminPackGen.FormatterDispatch.Options.g.cs", DispatchOptionsSource.Render(ProfileNames.Type(policy.Strings),
            policy.Strings.Encoding == StringEncoding.Utf8 ? 0 : 1, policy.Input == InputPolicy.Untrusted, policy.Limits.Input,
            options.RegisterMode != RegisterMode.Disabled, ProfileNames.Type(policy.JsonInput)), GenerationKind.Formatter);
        Add("LuminPackGen.Options.g.cs", ProfileSource.Render(retained, policy), GenerationKind.Formatter);
        return sources;

        void Add(string hint, string text, GenerationKind family)
        {
            if (text.Length != 0)
                sources.Add(new GeneratedSource(hint, text, family));
        }
    }

    /// <summary>Whether a declaration owns a read that can be rendered in another input scope.</summary>
    /// <param name="model">The declaration.</param>
    /// <returns>Whether the read has a supported concrete record model.</returns>
    private static bool CanCopyPayload(TypeModel model) => !model.Identity.IsGeneric &&
        (HasProjectableRead(model) || model is UnionModel { Rejection: null });

    /// <summary>Recognizes payload algorithms that accept a nested read scope.</summary>
    /// <param name="model">The declaration or closed owner.</param>
    /// <returns>Whether the payload renderer supports applying a read scope.</returns>
    private static bool HasProjectableRead(TypeModel model) =>
        model is RecordModel { Rejection: null } or StructModel { Storage: StructStorage.ManagedRecord, Rejection: null } or CircleReferenceModel;

    /// <summary>Builds the closed operation catalog consumed by interception.</summary>
    /// <param name="payloads">The normalized declaration results.</param>
    /// <param name="set">The shared formatter requirements.</param>
    /// <param name="shared">The already rendered shared formatter sources.</param>
    /// <param name="sharedRoots">The shared roots with unambiguous names.</param>
    /// <returns>The closed operation catalog.</returns>
    private static RootCatalog Catalog(ImmutableArray<ModeledPayload> payloads, SharedFormatterSet set,
        HashSet<string> sharedRoots, KeyValuePair<string, string>[] shared)
    {
        var entries = new List<KeyValuePair<string, RootEntry>>();
        foreach (ModeledPayload payload in payloads)
            if (payload.Result.IsComplete && payload.Result.Model is { } model)
            {
                bool generic = model.Identity.IsGeneric;
                bool intrinsic = !generic && model is UnionModel or StructModel { StoragePlan: not null };
                if (generic && model is not (RecordModel or StructModel { StoragePlan: null } or UnionModel))
                    continue;
                PayloadRenderModel? rendered = intrinsic ? null : RenderModelFactory.Create(model, payload.Options);
                if (!intrinsic && rendered == null)
                    continue;
                WirePolicy policy = model.Policy;
                string profile = policy.Declared ? ProfileNames.Type(policy.Strings) : RootEntry.DefaultProfile;
                // Only the record and plain struct emitters publish MeasureRecord_<payload>, and only for a closed payload with
                // unique entry names; the entry measures through it.
                bool measured = !generic && rendered is { MeasureRecord: true, UniqueEntries: true } &&
                    !(rendered.IsStruct && (rendered.Version != null || rendered.ManagedStruct));
                entries.Add(new KeyValuePair<string, RootEntry>(model.Identity.GlobalName,
                    new RootEntry(ReadableTypeName.Of(GeneratedNames.PayloadKey(model.Identity.GlobalName)), profile, true, true,
                        limit: policy.Input == InputPolicy.Untrusted ? policy.Limits.Input : null,
                        encoding: policy.Strings.Encoding == StringEncoding.Utf8 ? 0 : 1,
                        jsonReadProfile: policy.JsonInput.Equals(policy.Strings) ? null : ProfileNames.Type(policy.JsonInput),
                        genericUnion: model is UnionModel && model.Identity.IsGeneric, measured: measured)));
            }
        var measures = new List<string>();
        foreach (var source in shared)
            foreach (Match match in Regex.Matches(source.Value, @"static void MeasureRecord_(\w+?)(?:<TLuminProfile>)?\(", RegexOptions.CultureInvariant))
                measures.Add(match.Groups[1].Value);
        return new RootCatalog(entries, sharedRoots, set.Extension, measures);
    }
