using System.Globalization;
using System.Text;
using LuminPack.SourceGenerator.Next.Rendering.Emitters;

namespace LuminPack.SourceGenerator.Next.Pipeline;

/// <summary>Counts final source and selected directions without scanning the generated syntax.</summary>
internal sealed class PublicationCounts
{
    private readonly int[] _files = new int[3];
    private readonly long[] _characters = new long[3];
    private readonly long[] _bytes = new long[3];
    private readonly int[] _payloads = new int[4];
    private readonly int[] _owners = new int[4];

    /// <summary>Records one final source file.</summary>
    /// <param name="kind">The publication folder.</param>
    /// <param name="text">The complete generated text.</param>
    internal void AddSource(GenerationKind kind, string text)
    {
        int index = (int)kind;
        _files[index]++;
        _characters[index] += text.Length;
        _bytes[index] += Encoding.UTF8.GetByteCount(text);
    }

    /// <summary>Counts a complete declaration's retained directions.</summary>
    /// <param name="operations">The selected operation mask.</param>
    internal void AddPayload(GeneratedOperations operations) => AddOperations(_payloads, operations);

    /// <summary>Counts a shared root's retained directions.</summary>
    /// <param name="operations">The selected operation mask.</param>
    internal void AddOwner(GeneratedOperations operations) => AddOperations(_owners, operations);

    /// <summary>Renders the build report as comments without adding executable members.</summary>
    /// <param name="fixedOperations">Operations retained by the project kind or assembly options.</param>
    /// <param name="usage">Operations retained by direct state access, registration or method groups.</param>
    /// <param name="fallback">Operations retained by facade calls without a closed binding.</param>
    /// <returns>The report source, excluded from its own totals.</returns>
    internal string Render(GeneratedOperations fixedOperations, GeneratedOperations usage, GeneratedOperations fallback)
    {
        var text = new StringBuilder("// <auto-generated/>\n// LuminPack Next output report\n");
        text.Append("// Family Files Utf16CodeUnits Utf8Bytes\n");
        Family("Binary", GenerationKind.Binary);
        Family("Json", GenerationKind.Json);
        Family("Formatters", GenerationKind.Formatter);
        text.Append("// SelectedOperations BinaryWrite BinaryRead JsonWrite JsonRead\n");
        Operations("Payloads", _payloads);
        Operations("SharedRoots", _owners);
        text.Append("// GlobalRetention BinaryWrite BinaryRead JsonWrite JsonRead\n");
        Retention("ProjectOrForced", fixedOperations);
        Retention("DirectUsage", usage);
        Retention("FacadeFallback", fallback);
        return text.ToString();

        void Family(string name, GenerationKind kind)
        {
            int index = (int)kind;
            text.Append("// ").Append(name).Append(' ');
            text.Append(_files[index].ToString(CultureInfo.InvariantCulture)).Append(' ');
            text.Append(_characters[index].ToString(CultureInfo.InvariantCulture)).Append(' ');
            text.Append(_bytes[index].ToString(CultureInfo.InvariantCulture)).Append('\n');
        }

        void Operations(string name, int[] counts)
        {
            text.Append("// ").Append(name);
            foreach (int count in counts)
                text.Append(' ').Append(count.ToString(CultureInfo.InvariantCulture));
            text.Append('\n');
        }

        void Retention(string name, GeneratedOperations operations)
        {
            text.Append("// ").Append(name);
            for (int index = 0; index < 4; index++)
                text.Append(((int)operations & (1 << index)) != 0 ? " 1" : " 0");
            text.Append('\n');
        }
    }

    /// <summary>Increments the counters selected by one operation mask.</summary>
    /// <param name="counts">The four counters in operation order.</param>
    /// <param name="operations">The selected directions.</param>
    private static void AddOperations(int[] counts, GeneratedOperations operations)
    {
        for (int index = 0; index < counts.Length; index++)
            if (((int)operations & (1 << index)) != 0)
                counts[index]++;
    }
}
