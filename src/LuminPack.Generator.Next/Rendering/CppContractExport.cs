using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Threading;
using LuminPack.SourceGenerator.Next.Diagnostics;
using LuminPack.SourceGenerator.Next.Model;
using LuminPack.SourceGenerator.Next.Rendering.Emitters;
using LuminPack.SourceGenerator.Next.Rendering.Formatters;
using Microsoft.CodeAnalysis.CSharp;

namespace LuminPack.SourceGenerator.Next.Rendering;

/// <summary>Projects normalized Next contracts into build-only assembly metadata for the C++ tool.</summary>
internal static class CppContractExport
{
    internal const string MetadataKey = "LuminPack.Cpp.Contract.v1";

    /// <summary>Renders contract rows in a stable order.</summary>
    /// <param name="roots">The complete payloads already analyzed by Next.</param>
    /// <param name="callRoots">The normalized formatter graphs reached by closed serializer calls.</param>
    /// <param name="options">The compiled generator profile and target capabilities.</param>
    /// <param name="getNativeStorage">The optional native layout analysis for raw structs.</param>
    /// <param name="getRawCompoundStorage">The layout proof for headerless framework storage.</param>
    /// <param name="custom">The validated registrations whose representations are application-owned.</param>
    /// <param name="assemblyPolicy">The document policy for the registered fallback.</param>
    /// <param name="cancellationToken">Cancels the projection.</param>
    /// <returns>Source containing assembly metadata, or an empty string when no payloads are available.</returns>
    internal static string Render(IEnumerable<TypeModel> roots, IEnumerable<MemberModel> callRoots, GeneratorOptions options,
        Func<StructModel, (int Strategy, FormatterStorageModel Layout)?> getNativeStorage,
        Func<FormatterModel, FormatterStorageModel?> getRawCompoundStorage,
        IEnumerable<(string Id, string Type, bool Reference, bool Json)> custom, WirePolicy assemblyPolicy,
        CancellationToken cancellationToken)
    {
        TypeModel[] declarations = roots.ToArray();
        var contracts = new SortedDictionary<string, TypeModel>(StringComparer.Ordinal);
        foreach (TypeModel model in declarations)
            contracts[model.Identity.MetadataName] = model;
        foreach (TypeModel model in declarations)
            AddDependencies(contracts, model, cancellationToken);
        foreach (MemberModel root in callRoots)
            AddMember(contracts, root, cancellationToken);

        StringBuilder? source = null;
        var json = new StringBuilder();
        foreach (TypeModel model in contracts.Values)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var jsonModel = model is RecordModel && !model.Policy.TrackReferences
                ? RenderModelFactory.Create(model, options, json: true)
                : null;
            var orderedRuns = jsonModel == null ? null : JsonEmitter.FindGeneratedInt32Runs(jsonModel);
            var generatedIntegerProperties = jsonModel == null ? null : JsonEmitter.FindGeneratedIntegerProperties(jsonModel);
            Append(Contract(model, model is StructModel value ? getNativeStorage(value) : null, orderedRuns, generatedIntegerProperties,
                options.RegisterMode != RegisterMode.Disabled, getRawCompoundStorage));
        }
        var ids = new HashSet<string>(contracts.Keys, StringComparer.Ordinal);
        foreach (var declaration in custom.OrderBy(item => item.Id, StringComparer.Ordinal))
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (ids.Add(declaration.Id))
                Append(Object(("id", declaration.Id), ("type", declaration.Type), ("kind", "Custom"),
                    ("typeParameters", Array.Empty<string>()), ("profile", Profile(assemblyPolicy)),
                    ("customReference", declaration.Reference), ("customJson", declaration.Json)));
        }
        return source?.ToString() ?? string.Empty;

        void Append(object contract)
        {
            json.Clear();
            Value(json, contract);
            (source ??= new StringBuilder("// <auto-generated/>\n"))
                .Append("[assembly: global::System.Reflection.AssemblyMetadataAttribute(\"")
                .Append(MetadataKey).Append("\", ")
                .Append(SymbolDisplay.FormatLiteral(json.ToString(), true)).Append(")]\n");
        }
    }

    /// <summary>Retains each reachable normalized definition once.</summary>
    /// <param name="contracts">The retained payloads.</param>
    /// <param name="model">The current payload or null for a reference-only edge.</param>
    /// <param name="cancellationToken">Cancels graph traversal.</param>
    private static void Add(IDictionary<string, TypeModel> contracts, TypeModel? model, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        if (model == null || contracts.ContainsKey(model.Identity.MetadataName))
            return;
        contracts.Add(model.Identity.MetadataName, model);
        AddDependencies(contracts, model, cancellationToken);
    }

    /// <summary>Projects dependencies without replacing the model of a declared root.</summary>
    /// <param name="contracts">The retained payloads.</param>
    /// <param name="model">The current declaration.</param>
    /// <param name="cancellationToken">Cancels graph traversal.</param>
    private static void AddDependencies(IDictionary<string, TypeModel> contracts, TypeModel model, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        foreach (MemberModel member in model.Members)
            AddMember(contracts, member, cancellationToken);
        if (model is UnionModel union)
        {
            foreach (UnionCaseModel item in union.Cases)
            {
                Add(contracts, item.Model, cancellationToken);
                Add(contracts, item.Closed?.Payload, cancellationToken);
            }
        }
    }

    /// <summary>Visits declaration dependencies embedded in a normalized member.</summary>
    /// <param name="contracts">The retained payloads.</param>
    /// <param name="member">The member shape or null.</param>
    /// <param name="cancellationToken">Cancels graph traversal.</param>
    private static void AddMember(IDictionary<string, TypeModel> contracts, MemberModel? member, CancellationToken cancellationToken)
    {
        switch (member)
        {
            case PayloadMember payload:
                Add(contracts, payload.Nested, cancellationToken);
                break;
            case CollectionMember collection:
                Add(contracts, collection.Nested, cancellationToken);
                AddMember(contracts, collection.ForwardedElement, cancellationToken);
                break;
            case DictionaryMember dictionary:
                Add(contracts, dictionary.Nested, cancellationToken);
                AddMember(contracts, dictionary.ForwardedValue, cancellationToken);
                break;
            case SpecialMember special when special.Formatter != null:
                AddFormatter(contracts, special.Formatter, cancellationToken);
                break;
        }
    }

    /// <summary>Visits payloads reached through a shared static formatter.</summary>
    /// <param name="contracts">The retained payloads.</param>
    /// <param name="formatter">The current formatter.</param>
    /// <param name="cancellationToken">Cancels formatter traversal.</param>
    private static void AddFormatter(IDictionary<string, TypeModel> contracts, FormatterModel formatter, CancellationToken cancellationToken)
    {
        Add(contracts, formatter.Payload, cancellationToken);
        foreach (FormatterModel argument in formatter.Arguments)
            AddFormatter(contracts, argument, cancellationToken);
    }

    /// <summary>Projects one declaration without referring to its generated C# formatter text.</summary>
    /// <param name="model">The declaration facts.</param>
    /// <param name="native">The independent tag-free layout facts, when available.</param>
    /// <param name="orderedRuns">The proven generated JSON Int32 runs by start ordinal.</param>
    /// <param name="generatedIntegerProperties">Members with a generated UTF-8 head and integer write.</param>
    /// <param name="registration">Whether the consuming assembly enables runtime registration.</param>
    /// <param name="getRawCompoundStorage">The layout proof for headerless framework storage.</param>
    /// <returns>The JSON properties for the contract row.</returns>
    private static object Contract(TypeModel model, (int Strategy, FormatterStorageModel Layout)? native, int[]? orderedRuns,
        bool[]? generatedIntegerProperties, bool registration, Func<FormatterModel, FormatterStorageModel?> getRawCompoundStorage)
    {
        var record = model as RecordModel;
        var value = model as StructModel;
        var union = model as UnionModel;
        VersionSchemaModel? version = record?.Version ?? value?.Version;
        return Object(("id", model.Identity.MetadataName), ("type", model.Identity.GlobalName), ("name", model.Identity.Name),
            ("namespace", model.Identity.Namespace), ("containingTypes", model.Identity.ContainingTypes),
            ("typeParameters", model.Identity.TypeParameters), ("kind", model.Kind.ToString()),
            ("profile", Profile(model.Policy)), ("versioned", version != null), ("dynamicVersion", version?.Dynamic),
            ("recursive", record?.Recursive),
            ("storageKind", value?.Storage.ToString()), ("storage", Storage(value?.StoragePlan)),
            ("nativeStrategy", native?.Strategy), ("nativeStorage", Storage(native?.Layout)),
            ("jsonInt32Runs", orderedRuns), ("jsonGeneratedIntegerProperties", generatedIntegerProperties),
            ("sequenceBase", record?.SequenceBase), ("collectionBase", Formatter(record?.CollectionBase, getRawCompoundStorage)),
            ("unionWideTags", union?.WideTags), ("unionRegistration", union != null && registration),
            ("unionTier", union?.ClosedWriteSlot != null ? UnionDispatchTier.Exact.ToString() : union?.Tier.ToString()),
            ("cases", union?.Cases.Select(static item => Object(("id", item.Type.MetadataName), ("type", item.Type.GlobalName),
                ("hash", item.NameHash), ("tag", item.Tag), ("ownEntry", item.OwnEntry), ("definition", item.Definition)))),
            ("members", model.Members.Select((member, index) => Member(member, version, index, getRawCompoundStorage))));
    }

    /// <summary>Projects one member in the declaration's existing wire order.</summary>
    /// <param name="member">The normalized member.</param>
    /// <param name="version">The declaration's Version descriptor table or null.</param>
    /// <param name="index">The member's position in the declaration.</param>
    /// <param name="getRawCompoundStorage">The layout proof for headerless framework storage.</param>
    /// <returns>The JSON properties for the member.</returns>
    private static object Member(MemberModel member, VersionSchemaModel? version, int index,
        Func<FormatterModel, FormatterStorageModel?> getRawCompoundStorage) =>
        Object(("name", member.Name), ("profile", Profile(member.Policy)), ("compressed", member.Compressed),
            ("shape", Shape(member, getRawCompoundStorage)), ("descriptor", version?.Descriptors[index].ToString("X16", CultureInfo.InvariantCulture)),
            ("oldNames", version?.OldNames[index]), ("nameKeys", version?.NameKeys[index]),
            ("fixedNullable", version?.FixedNullable[index]));

    /// <summary>Captures the existing binary and JSON profile decisions for a declaration or member.</summary>
    /// <param name="policy">The normalized wire policy.</param>
    /// <returns>The JSON properties for the profile.</returns>
    private static object Profile(WirePolicy policy)
    {
        StringProfile strings = policy.Strings;
        int encoding = (int)strings.Encoding;
        int recording = (int)strings.Recording;
        int binary = strings.Recording == StringRecording.VarInt ? 4 + encoding : 2 * encoding + recording;
        return Object(("binary", binary), ("declared", policy.Declared), ("jsonEncoding", encoding),
            ("jsonDepth", policy.JsonInput.Depth), ("strictJson", policy.JsonInput.Strict),
            ("format", strings.Format.ToString()), ("precision", strings.Precision), ("trackReferences", policy.TrackReferences),
            ("trusted", policy.Input == InputPolicy.Trusted), ("bound", policy.Bound), ("maxInput", policy.Limits.Input),
            ("maxCollection", policy.Limits.Collection), ("maxString", policy.Limits.String), ("maxDepth", policy.Limits.Depth));
    }

    /// <summary>Projects a typed member edge using its actual Next representation.</summary>
    /// <param name="member">The normalized member or null.</param>
    /// <param name="getRawCompoundStorage">The layout proof for headerless framework storage.</param>
    /// <returns>The JSON shape to serialize.</returns>
    private static object? Shape(MemberModel? member, Func<FormatterModel, FormatterStorageModel?> getRawCompoundStorage) => member switch
    {
        null => null,
        ScalarMember scalar => Object(("kind", scalar.EnumType == null ? "scalar" : "enum"), ("type", scalar.EnumType ?? scalar.Scalar),
            ("underlying", scalar.Underlying), ("size", scalar.Size), ("raw", scalar.Raw), ("volatile", scalar.Volatile)),
        TextMember => Object(("kind", "string"), ("type", "string")),
        PayloadMember payload => Object(("kind", "payload"), ("type", payload.Type.GlobalName),
            ("framing", payload.Shape.ToString()), ("nullable", payload.Type.Nullable)),
        CollectionMember sequence => Object(("kind", sequence.Kind.ToString()), ("type", sequence.DeclaredType),
            ("element", sequence.Element.GlobalName), ("rank", sequence.ArrayRank), ("raw", sequence.Raw),
            ("forwardedElement", Shape(sequence.ForwardedElement, getRawCompoundStorage))),
        DictionaryMember dictionary => Object(("kind", dictionary.Kind.ToString()), ("type", dictionary.DeclaredType),
            ("key", dictionary.Key.GlobalName), ("value", dictionary.Value.GlobalName), ("sparseValue", dictionary.Sparse),
            ("forwardedValue", Shape(dictionary.ForwardedValue, getRawCompoundStorage))),
        SpecialMember special => Object(("kind", "formatter"), ("type", special.Declared), ("formatter", Formatter(special.Formatter, getRawCompoundStorage))),
        CultureInfoMember culture => Object(("kind", "formatter"), ("type", culture.Declared)),
        TypeParameterMember parameter => Object(("kind", "parameter"), ("type", parameter.ParameterName)),
        _ => Object(("kind", "unsupported"), ("details", member.GetType().Name))
    };

    /// <summary>Projects a closed formatter's typed arguments and block-storage descriptions.</summary>
    /// <param name="formatter">The formatter to export or null.</param>
    /// <param name="getRawCompoundStorage">The layout proof for headerless framework storage.</param>
    /// <returns>The JSON formatter description.</returns>
    private static object? Formatter(FormatterModel? formatter, Func<FormatterModel, FormatterStorageModel?> getRawCompoundStorage)
    {
        if (formatter == null)
            return null;
        var fields = Object(("type", formatter.Type), ("definition", formatter.Definition),
            ("arguments", formatter.Arguments.Select(argument => Formatter(argument, getRawCompoundStorage))),
            ("underlying", formatter.Underlying), ("rank", formatter.Rank), ("raw", formatter.Raw),
            ("rawCollection", formatter.RawCollection), ("layout", Storage(formatter.Layout)),
            ("nullableLayout", Storage(formatter.NullableStorage)), ("nullableEncoding", formatter.NullableEncoding),
            ("nativeNullableElement", formatter.NativeNullableElement));
        if (formatter.Definition is not (GenericIdentity.ValueTuple or GenericIdentity.KeyValuePair) ||
            !formatter.RawCollection || getRawCompoundStorage(formatter) is not { } storage)
            return fields;
        if (storage.ModelSizes[0] != storage.WireSize || !storage.ModelOffsets[0].SequenceEqual(Enumerable.Range(0, storage.WireSize)))
            return fields.Append(("rawCompoundStorage", Storage(storage))).ToArray();
        return formatter.Definition == GenericIdentity.ValueTuple && formatter.Raw
            ? fields.Append(("denseTupleStorage", (object?)true)).ToArray() : fields;
    }

    /// <summary>Projects one native layout and its modeled Tagged wire offsets.</summary>
    /// <param name="storage">The normalized storage description or null.</param>
    /// <returns>The JSON storage description.</returns>
    private static object? Storage(FormatterStorageModel? storage) => storage == null ? null :
        Object(("type", storage.Type), ("attribute", storage.Attribute), ("wireSize", storage.WireSize),
            ("tagged", storage.Tagged), ("modelSizes", storage.ModelSizes), ("modelOffsets", storage.ModelOffsets),
            ("fields", storage.Fields.Select(static field => Object(("name", field.Name), ("offset", field.Offset),
                ("volatile", field.Volatile), ("storage", Storage(field.Storage))))));

    /// <summary>Retains an ordered set of JSON object properties.</summary>
    /// <param name="fields">The properties in publication order.</param>
    /// <returns>The ordered properties.</returns>
    private static (string Name, object? Value)[] Object(params (string Name, object? Value)[] fields) => fields;

    /// <summary>Appends a projected JSON value with invariant numbers and deterministic property order.</summary>
    /// <param name="output">The manifest text builder.</param>
    /// <param name="value">The projected data.</param>
    private static void Value(StringBuilder output, object? value)
    {
        switch (value)
        {
            case null:
                output.Append("null");
                break;
            case bool flag:
                output.Append(flag ? "true" : "false");
                break;
            case string text:
                Quote(output, text);
                break;
            case (string Name, object? Value)[] fields:
                output.Append('{');
                for (int index = 0; index < fields.Length; index++)
                {
                    if (index != 0)
                        output.Append(',');
                    Quote(output, fields[index].Name);
                    output.Append(':');
                    Value(output, fields[index].Value);
                }
                output.Append('}');
                break;
            case IEnumerable items:
                output.Append('[');
                bool first = true;
                foreach (object? item in items)
                {
                    if (!first)
                        output.Append(',');
                    Value(output, item);
                    first = false;
                }
                output.Append(']');
                break;
            case IFormattable number:
                output.Append(number.ToString(null, CultureInfo.InvariantCulture));
                break;
            default:
                LuminPackExceptionHelper.ThrowInvalidOperation("Unexpected value in a LuminPack C++ contract.");
                break;
        }
    }

    /// <summary>Writes a JSON string, including standalone UTF-16 code units in aliases.</summary>
    /// <param name="output">The manifest text builder.</param>
    /// <param name="value">The text to quote.</param>
    private static void Quote(StringBuilder output, string value)
    {
        output.Append('"');
        foreach (char character in value)
        {
            if (character is '"' or '\\')
                output.Append('\\').Append(character);
            else if (character < 0x20 || char.IsSurrogate(character))
                output.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
            else
                output.Append(character);
        }
        output.Append('"');
    }
}
