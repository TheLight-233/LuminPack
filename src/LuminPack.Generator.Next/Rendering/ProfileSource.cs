using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using LuminPack.SourceGenerator.Next.Model;

namespace LuminPack.SourceGenerator.Next.Rendering;

/// <summary>Publishes each nondefault profile component once without reparsing generated source.</summary>
internal static class ProfileSource
{
    /// <summary>Collects and renders the immutable component declarations used by complete payload graphs.</summary>
    /// <param name="models">The retained payloads.</param>
    /// <returns>The shared component source, or an empty string.</returns>
    internal static string Render(IEnumerable<TypeModel> models)
    {
        var components = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var visited = new HashSet<string>(StringComparer.Ordinal);
        foreach (TypeModel model in models)
            Collect(model, components, visited);
        if (components.Count == 0)
            return string.Empty;
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace LuminPack.Generated\n{\n");
        foreach (string declaration in components.Values)
            source.Append(declaration);
        return source.Append("}\n").ToString();
    }

    /// <summary>Visits each payload graph once and retains only its nondefault profile components.</summary>
    /// <param name="model">The payload graph.</param>
    /// <param name="components">The deduplicated declarations.</param>
    /// <param name="visited">The payload identities already visited.</param>
    private static void Collect(TypeModel model, SortedDictionary<string, string> components, HashSet<string> visited)
    {
        if (!visited.Add(model.Identity.GlobalName))
            return;
        Add(model.Policy.Strings, components);
        foreach (MemberModel member in model.Members)
        {
            Add(member.Policy.Strings, components);
            if (member is PayloadMember { Nested: { } nested })
                Collect(nested, components, visited);
            if (member is CollectionMember { Nested: { } element })
                Collect(element, components, visited);
            if (member is DictionaryMember { Nested: { } value })
                Collect(value, components, visited);
            if (member is SpecialMember { Formatter: { } formatter })
                CollectFormatter(formatter, components, visited);
        }
        if (model is UnionModel union)
            foreach (UnionCaseModel item in union.Cases)
                if (item.Model != null)
                    Collect(item.Model, components, visited);
    }

    /// <summary>Visits closed formatter payload dependencies alongside ordinary members.</summary>
    /// <param name="formatter">The closed contract.</param>
    /// <param name="components">The shared declarations.</param>
    /// <param name="visited">The payload identities already visited.</param>
    private static void CollectFormatter(FormatterModel formatter, SortedDictionary<string, string> components, HashSet<string> visited)
    {
        if (formatter.Payload != null)
            Collect(formatter.Payload, components, visited);
        foreach (FormatterModel argument in formatter.Arguments)
            CollectFormatter(argument, components, visited);
    }

    /// <summary>Adds the existing runtime composition's nondefault components.</summary>
    /// <param name="profile">The declaration constants.</param>
    /// <param name="components">The component declarations.</param>
    private static void Add(StringProfile profile, SortedDictionary<string, string> components)
    {
        if (profile.Format != 'G' || profile.Precision != byte.MaxValue)
        {
            string name = ProfileNames.Format(profile);
            if (!components.ContainsKey(name))
                components.Add(name, "    /// <summary>Provides a declaration-time standard format.</summary>\n    public readonly struct " + name +
                    " : global::LuminPack.Option.ILuminPackFormatOptions\n    {\n        /// <inheritdoc/>\n        public global::System.Buffers.StandardFormat Value => new global::System.Buffers.StandardFormat((char)" +
                    ((int)profile.Format).ToString(CultureInfo.InvariantCulture) + ", (byte)" + profile.Precision.ToString(CultureInfo.InvariantCulture) + ");\n    }\n");
        }
        if (profile.Depth != 1024)
        {
            string name = ProfileNames.Depth(profile);
            if (!components.ContainsKey(name))
                components.Add(name, "    /// <summary>Provides a declaration-time JSON depth bound.</summary>\n    public readonly struct " + name +
                    " : global::LuminPack.Option.ILuminPackDepthOptions\n    {\n        /// <inheritdoc/>\n        public int Value => " +
                    profile.Depth.ToString(CultureInfo.InvariantCulture) + ";\n    }\n");
        }
    }
}
