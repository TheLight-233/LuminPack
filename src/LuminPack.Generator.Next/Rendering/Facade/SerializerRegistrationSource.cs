using LuminPack.SourceGenerator.Next.Model;

namespace LuminPack.SourceGenerator.Next.Rendering.Facade;

/// <summary>Publishes typed registration APIs only when the consuming assembly enables registration.</summary>
internal static class SerializerRegistrationSource
{
    /// <summary>Selects the assembly-owned registration facade.</summary>
    /// <param name="options">The consuming assembly's immutable generation settings.</param>
    /// <returns>The registration APIs, or an empty contribution when registration is disabled.</returns>
    internal static string Render(GeneratorOptions options) => options.RegisterMode == RegisterMode.Disabled ? string.Empty : Source;

    private const string Source = @"// <auto-generated/>
#nullable enable annotations
#pragma warning disable CS1591
namespace LuminPack
{
    public static partial class LuminPackSerializer
    {
        /// <summary>Registers an additional binary and JSON Union case.</summary>
        /// <typeparam name=""TUnion"">The Union root.</typeparam>
        /// <typeparam name=""TMember"">The concrete case.</typeparam>
        /// <param name=""tag"">The UInt16 wire tag, excluding generated cases.</param>
        /// <param name=""writeValue"">The binary writer, including its Union tag.</param>
        /// <param name=""readValue"">The binary payload reader.</param>
        /// <param name=""writeValueJson"">The JSON writer, including its Union envelope.</param>
        /// <param name=""readValueJson"">The JSON payload reader.</param>
        public static void Register<TUnion, TMember>(int tag,
            global::LuminPack.Code.LuminPackUnionWriteDelegate<TUnion> writeValue,
            global::LuminPack.Code.LuminPackReadDelegate<TUnion> readValue,
            global::LuminPack.Code.LuminPackUnionJsonWriteDelegate<TUnion> writeValueJson,
            global::LuminPack.Code.LuminPackJsonReadDelegate<TUnion> readValueJson)
            => global::LuminPack.Code.LuminPackUnionFormatter<TUnion>.Register<TMember>(tag, writeValue, readValue, writeValueJson, readValueJson);

        /// <summary>Registers binary delegates for generic payload entry points.</summary>
        /// <typeparam name=""T"">The runtime type to register.</typeparam>
        /// <param name=""writeValue"">Static binary writer, e.g. <c>MyType.Write</c>.</param>
        /// <param name=""readValue"">Static binary reader, e.g. <c>MyType.Read</c>.</param>
        /// <remarks>Accepts method groups without an unsafe context.</remarks>
        public static void Register<T>(
            global::LuminPack.Code.LuminPackWriteDelegate<T> writeValue,
            global::LuminPack.Code.LuminPackReadDelegate<T> readValue)
                => global::LuminPack.Code.LuminPackFormatterRegistry.Register(typeof(T), writeValue, readValue);
        /// <summary>Registers binary delegates for generic payload entry points.</summary>
        /// <typeparam name = ""T"">The runtime type to register.</typeparam>
        /// <param name = ""writeValue"">Static binary writer, e.g. <c>MyType.Write</c>.</param>
        /// <param name = ""readValue"">Static binary reader, e.g. <c>MyType.Read</c>.</param>
        /// <remarks>Accepts method groups without an unsafe context.</remarks>

        /// <typeparam name = ""TOptions"">The stateless profile used by these closed delegates.</typeparam>
        public static void Register<T, TOptions>(
            global::LuminPack.Code.LuminPackWriteDelegate<T> writeValue,
            global::LuminPack.Code.LuminPackReadDelegate<T> readValue)
            where TOptions : struct, global::LuminPack.Option.ILuminPackOptions => global::LuminPack.Code.LuminPackFormatterRegistry<TOptions>.Register(typeof(T), writeValue, readValue);
        /// <summary>Registers binary and JSON delegates for generic payload entry points.</summary>
        /// <typeparam name=""T"">The runtime type to register.</typeparam>
        /// <param name=""writeValue"">Static binary writer, e.g. <c>MyType.Write</c>.</param>
        /// <param name=""readValue"">Static binary reader, e.g. <c>MyType.Read</c>.</param>
        /// <param name=""writeValueJson"">Static JSON writer, e.g. <c>MyType.WriteJson</c>.</param>
        /// <param name=""readValueJson"">Static JSON reader, e.g. <c>MyType.ReadJson</c>.</param>
        /// <remarks>Accepts method groups without an unsafe context.</remarks>
        public static void Register<T>(
            global::LuminPack.Code.LuminPackWriteDelegate<T> writeValue,
            global::LuminPack.Code.LuminPackReadDelegate<T> readValue,
            global::LuminPack.Code.LuminPackJsonWriteDelegate<T> writeValueJson,
            global::LuminPack.Code.LuminPackJsonReadDelegate<T> readValueJson)
                => global::LuminPack.Code.LuminPackFormatterRegistry.Register(
                    typeof(T),
                    writeValue,
                    readValue,
                    writeValueJson,
                    readValueJson);
        /// <summary>Registers binary and JSON delegates for generic payload entry points.</summary>
        /// <typeparam name = ""T"">The runtime type to register.</typeparam>
        /// <param name = ""writeValue"">Static binary writer, e.g. <c>MyType.Write</c>.</param>
        /// <param name = ""readValue"">Static binary reader, e.g. <c>MyType.Read</c>.</param>
        /// <param name = ""writeValueJson"">Static JSON writer, e.g. <c>MyType.WriteJson</c>.</param>
        /// <param name = ""readValueJson"">Static JSON reader, e.g. <c>MyType.ReadJson</c>.</param>
        /// <remarks>Accepts method groups without an unsafe context.</remarks>

        /// <typeparam name = ""TOptions"">The stateless profile used by these closed delegates.</typeparam>
        public static void Register<T, TOptions>(
            global::LuminPack.Code.LuminPackWriteDelegate<T> writeValue,
            global::LuminPack.Code.LuminPackReadDelegate<T> readValue,
            global::LuminPack.Code.LuminPackJsonWriteDelegate<T> writeValueJson,
            global::LuminPack.Code.LuminPackJsonReadDelegate<T> readValueJson)
            where TOptions : struct, global::LuminPack.Option.ILuminPackOptions => global::LuminPack.Code.LuminPackFormatterRegistry<TOptions>.Register(typeof(T), writeValue, readValue, writeValueJson, readValueJson);
    }
}";
}
