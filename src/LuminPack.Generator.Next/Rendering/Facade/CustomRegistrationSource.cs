using System.Collections.Generic;
using System.Text;

namespace LuminPack.SourceGenerator.Next.Rendering.Facade;

/// <summary>Renders the registration of user-written Custom formatters through the established typed-delegate boundary.</summary>
/// <remarks>Each valid Custom type registers its static binary pair, and its JSON pair when both are declared, once at module
/// initialization, or at Unity load. This is the original registry file.</remarks>
internal static class CustomRegistrationSource
{
    /// <summary>Renders one type's registration statement.</summary>
    /// <param name="type">The fully qualified Custom type.</param>
    /// <param name="json">Whether the type declares the complete JSON pair.</param>
    /// <returns>The registration block.</returns>
    internal static string Block(string type, bool json)
    {
        var block = new StringBuilder();
        block.Append("            global::LuminPack.LuminPackSerializer.Register<").Append(type).Append(">(\n");
        block.Append("                ").Append(type).Append(".Serialize,\n");
        block.Append("                ").Append(type).Append(".Deserialize\n");
        if (json)
        {
            block.Append("                , ").Append(type).Append(".SerializeJson\n");
            block.Append("                , ").Append(type).Append(".DeserializeJson\n");
        }
        block.Append("            );\n");
        return block.ToString();
    }

    /// <summary>Renders the registry file for the collected blocks.</summary>
    /// <param name="blocks">The registration blocks in declaration order.</param>
    /// <param name="assemblyName">The consuming assembly name.</param>
    /// <param name="unity">Whether the consumer is a Unity project.</param>
    /// <returns>The file, or an empty string without blocks.</returns>
    internal static string Render(IReadOnlyList<string> blocks, string assemblyName, bool unity)
    {
        if (blocks.Count == 0)
            return string.Empty;
        string assembly = Sanitize(assemblyName);
        var file = new StringBuilder();
        file.Append("// <auto-generated/>\n");
        file.Append("// LuminPack Custom formatter registration — do not modify\n");
        file.Append("#nullable enable annotations\n#pragma warning disable CS0162, CS0168, CS0219, CS0436, CS0649\n\n");
        file.Append("using global::System;\nusing global::System.Runtime.CompilerServices;\nusing global::LuminPack;\n\n");
        bool scoped = assembly != "Unknown";
        if (scoped)
            file.Append("namespace LuminPackRegisters.").Append(assembly).Append("\n{\n");
        file.Append("    internal static class LuminPackCustomFormatterRegistry\n    {\n");
        if (unity)
        {
            file.Append("#if UNITY_EDITOR\n        [global::UnityEditor.InitializeOnLoadMethod]\n#endif\n");
            file.Append("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.BeforeSceneLoad)]\n");
        }
        else
        {
            file.Append("#if NET5_0_OR_GREATER\n        [System.Runtime.CompilerServices.ModuleInitializerAttribute]\n#else\n");
            file.Append("        // Initialization must be invoked explicitly.\n");
            file.Append("        // Call from the application entry point: LuminPackRegisters.").Append(assembly)
                .Append(".LuminPackCustomFormatterRegistry.Initialize()\n#endif\n");
        }
        file.Append("        internal static void Initialize()\n        {\n");
        foreach (string block in blocks)
            file.Append(block);
        file.Append("        }\n    }\n");
        if (scoped)
            file.Append("}\n");
        return file.ToString();
    }

    /// <summary>Sanitizes the assembly name into one namespace identifier, as the original registry does.</summary>
    /// <param name="name">The assembly name.</param>
    /// <returns>The identifier.</returns>
    private static string Sanitize(string name)
    {
        if (string.IsNullOrEmpty(name))
            return "Unknown";
        var text = new StringBuilder(name.Length);
        for (int index = 0; index < name.Length; index++)
        {
            char c = name[index];
            text.Append(index == 0 ? (char.IsLetter(c) || c == '_' ? c : '_') : (char.IsLetterOrDigit(c) || c == '_' ? c : '_'));
        }
        return text.ToString();
    }
}
