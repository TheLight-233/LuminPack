using System.Collections.Generic;
using System.Text;
using LuminPack.SourceGenerator.Next.Rendering.Emitters;

namespace LuminPack.SourceGenerator.Next.Rendering.Facade;

/// <summary>Renders the registrations that belong to the consuming assembly.</summary>
internal static class CustomRegistrationSource
{
    /// <summary>Renders the typed method groups of one user-written Custom formatter.</summary>
    /// <param name="type">The fully qualified Custom type.</param>
    /// <param name="json">Whether both JSON operations are available.</param>
    /// <returns>The registration statement.</returns>
    internal static string Block(string type, bool json) =>
        "global::LuminPack.LuminPackSerializer.Register<" + type + ">(\n" +
        "    " + type + ".Serialize,\n" +
        "    " + type + ".Deserialize" +
        (json ? ",\n    " + type + ".SerializeJson,\n    " + type + ".DeserializeJson" : string.Empty) + ");";

    /// <summary>Renders the facade's first-use initializer and its generated delegate tables.</summary>
    /// <param name="custom">The Custom registrations and Union tag reservations.</param>
    /// <param name="generated">The emitted operations keyed by closed payload.</param>
    /// <param name="profile">The consuming assembly's default profile.</param>
    /// <param name="jsonReadProfile">The consuming assembly's default JSON read profile.</param>
    /// <param name="assemblyName">The consuming assembly name used by the Custom registry.</param>
    /// <param name="openUnionTags">The open Union definitions and the numeric tags reserved by their generated cases.</param>
    /// <param name="known">Whether the referenced Core supplies the built-in registration table.</param>
    /// <returns>The generated registry source.</returns>
    internal static string Render(IReadOnlyList<string> custom,
        IEnumerable<(string Type, string BinarySuffix, string JsonSuffix, string Arguments, GeneratedOperations Operations)> generated,
        string profile, string jsonReadProfile, string assemblyName, bool known,
        IReadOnlyList<(string Definition, string Tags)>? openUnionTags = null)
    {
        string assembly = Sanitize(assemblyName);
        string? registryNamespace = assembly == "Unknown" ? null : "LuminPackRegisters." + assembly;
        string registry = registryNamespace == null ? "LuminPackCustomFormatterRegistry" : registryNamespace + ".LuminPackCustomFormatterRegistry";
        var file = new StringBuilder("""
            // <auto-generated/>
            #nullable enable annotations
            #pragma warning disable CS0436, CS1591

            namespace LuminPack
            {
                public static partial class LuminPackSerializer
                {
                    private static readonly global::System.Collections.Generic.Dictionary<nint, global::LuminPack.Code.LuminPackFormatter> DefaultGeneratedFormatters;

                    static LuminPackSerializer()
                    {
            """).Append('\n');
        if (known)
            file.Append("            global::LuminPack.Code.LuminPackKnownFormatters.Register<").Append(jsonReadProfile).Append(">();\n");
        if (custom.Count != 0)
            file.Append("            global::").Append(registry).Append(".RegisterFormatters();\n");
        file.Append("            DefaultGeneratedFormatters = RegisterGeneratedFormatters<").Append(profile).Append(", ")
            .Append(jsonReadProfile).Append(">();\n        }\n\n");
        if (openUnionTags is { Count: > 0 })
        {
            file.Append("        static partial void ReserveOpenUnionTags<TUnion>()\n        {\n");
            file.Append("            var type = typeof(TUnion);\n            if (!type.IsGenericType) return;\n");
            file.Append("            var definition = type.GetGenericTypeDefinition();\n");
            foreach (var (definition, tags) in openUnionTags)
                file.Append("            if (definition == typeof(").Append(definition)
                    .Append(")) global::LuminPack.Code.LuminPackUnionFormatter<TUnion>.ReserveTags(new int[] { ")
                    .Append(tags).Append(" });\n");
            file.Append("        }\n\n");
        }
        file.Append("""
                    private static global::LuminPack.Code.LuminPackFormatter FindGeneratedFormatter<T, TOptions>()
                        where TOptions : struct, global::LuminPack.Option.ILuminPackOptions
                    {
                        var table = typeof(TOptions) == typeof(global::LuminPack.Option.LuminPackDeclaredOptions)
                            ? DefaultGeneratedFormatters
                            : GeneratedFormatters<TOptions>.Table;
                        var key = global::LuminPack.Code.LuminPackMarshal.GetMethodTable(typeof(T));
                        if (table.TryGetValue(key, out var formatter))
                            return formatter;
            """).Append('\n');
        if (known)
            file.Append("            var known = typeof(TOptions) == typeof(global::LuminPack.Option.LuminPackDeclaredOptions)\n")
                .Append("                ? global::LuminPack.Code.LuminPackKnownFormatters.Register<").Append(jsonReadProfile).Append(">()\n")
                .Append("                : global::LuminPack.Code.LuminPackKnownFormatters.Register<TOptions>();\n")
                .Append("            known.TryGetValue(key, out formatter);\n");
        file.Append("""
                        return formatter;
                    }

                    private static class GeneratedFormatters<TOptions>
                        where TOptions : struct, global::LuminPack.Option.ILuminPackOptions
                    {
                        internal static readonly global::System.Collections.Generic.Dictionary<nint, global::LuminPack.Code.LuminPackFormatter> Table = RegisterGeneratedFormatters<TOptions, TOptions>();
                    }

                    private static global::System.Collections.Generic.Dictionary<nint, global::LuminPack.Code.LuminPackFormatter> RegisterGeneratedFormatters<TOptions, TJsonReadOptions>()
                        where TOptions : struct, global::LuminPack.Option.ILuminPackOptions
                        where TJsonReadOptions : struct, global::LuminPack.Option.ILuminPackOptions
                    {
                        // The consuming assembly owns generated delegates, including operations for framework payloads.
                        var table = new global::System.Collections.Generic.Dictionary<nint, global::LuminPack.Code.LuminPackFormatter>();
            """).Append('\n');
        foreach (var entry in generated)
        {
            file.Append("            global::LuminPack.LuminPackSerializer.RegisterGenerated<").Append(entry.Type).Append(">(table,\n");
            AppendOperation("Serialize", entry.BinarySuffix, GeneratedOperations.BinaryWrite, "TOptions", ",");
            AppendOperation("Deserialize", entry.BinarySuffix, GeneratedOperations.BinaryRead, "TOptions", ",");
            AppendOperation("SerializeJson", entry.JsonSuffix, GeneratedOperations.JsonWrite, "TOptions", ",");
            AppendOperation("DeserializeJson", entry.JsonSuffix, GeneratedOperations.JsonRead, "TJsonReadOptions", ");");

            void AppendOperation(string name, string suffix, GeneratedOperations operation, string options, string end)
            {
                file.Append("                ");
                if ((entry.Operations & operation) != 0)
                    file.Append("global::LuminPack.LuminPackSerializer.").Append(name).Append(suffix)
                        .Append('<').Append(entry.Arguments).Append(options).Append('>');
                else
                    file.Append("null");
                file.Append(end).Append('\n');
            }
        }
        file.Append("            return table;\n        }\n");
        file.Append("\n        internal static void EnsureFormatterRegistration() { }\n");
        file.Append("""

                    private static void RegisterGenerated<T>(
                        global::System.Collections.Generic.Dictionary<nint, global::LuminPack.Code.LuminPackFormatter> table,
                        global::LuminPack.Code.LuminPackWriteDelegate<T>? write,
                        global::LuminPack.Code.LuminPackReadDelegate<T>? read,
                        global::LuminPack.Code.LuminPackJsonWriteDelegate<T>? writeJson,
                        global::LuminPack.Code.LuminPackJsonReadDelegate<T>? readJson)
                    {
                        var formatter = new global::LuminPack.Code.LuminPackFormatter
                        {
                            WriteValue = write,
                            ReadValue = read,
                            WriteValueJson = writeJson,
                            ReadValueJson = readJson
                        };
                        var key = global::LuminPack.Code.LuminPackMarshal.GetMethodTable(typeof(T));
                        table.TryAdd(key, formatter);
                    }
                }
            }
            """).Append('\n');
        if (custom.Count == 0)
            return file.ToString();

        file.Append('\n');
        string indent = registryNamespace == null ? string.Empty : "    ";
        if (registryNamespace != null)
            file.Append("namespace ").Append(registryNamespace).Append("\n{\n");
        file.Append(indent).Append("internal static class LuminPackCustomFormatterRegistry\n").Append(indent).Append("{\n");
        file.Append(indent).Append("    internal static void Initialize() => global::LuminPack.LuminPackSerializer.EnsureFormatterRegistration();\n\n");
        file.Append(indent).Append("    internal static void RegisterFormatters()\n").Append(indent).Append("    {\n");
        foreach (string block in custom)
        {
            foreach (string line in block.Split('\n'))
                file.Append(indent).Append("        ").Append(line).Append('\n');
        }
        file.Append(indent).Append("    }\n").Append(indent).Append("}\n");
        if (registryNamespace != null)
            file.Append("}\n");
        return file.ToString();
    }

    /// <summary>Preserves the assembly-derived namespace of the Custom registry.</summary>
    /// <param name="name">The consuming assembly name.</param>
    /// <returns>The namespace identifier.</returns>
    private static string Sanitize(string name)
    {
        if (string.IsNullOrEmpty(name))
            return "Unknown";
        var text = new StringBuilder(name.Length);
        for (int index = 0; index < name.Length; index++)
        {
            char character = name[index];
            text.Append(char.IsLetter(character) || character == '_' || index != 0 && char.IsDigit(character) ? character : '_');
        }
        string identifier = text.ToString();
        return Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(identifier) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
            ? "@" + identifier : identifier;
    }
}
