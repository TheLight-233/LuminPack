TEXT ·detectVectorFeatures(SB), NOSPLIT, $0-1
	MOVL $0, AX
	CPUID
	CMPL AX, $7
	JB unavailable
	MOVL $1, AX
	CPUID
	ANDL $0x18000000, CX
	CMPL CX, $0x18000000
	JNE unavailable
	XORL CX, CX
	XGETBV
	MOVL AX, R8
	ANDL $0x6, R8
	CMPL R8, $0x6
	JNE unavailable
	MOVL AX, R8
	MOVL $7, AX
	XORL CX, CX
	CPUID
	XORL AX, AX
	TESTL $0x20, BX
	JZ check512
	ORL $1, AX
check512:
	ANDL $0xe6, R8
	CMPL R8, $0xe6
	JNE returnFeatures
	ANDL $0x40010000, BX
	CMPL BX, $0x40010000
	JNE returnFeatures
	ORL $2, AX
returnFeatures:
	MOVB AX, ret+0(FP)
	RET
unavailable:
	MOVB $0, ret+0(FP)
	RET

