TEXT ·asciiPrefixVector(SB), NOSPLIT, $0-32
	MOVQ src_base+0(FP), SI
	MOVQ src_len+8(FP), CX
	XORQ AX, AX
scan:
	MOVOU (SI)(AX*1), X0
	PMOVMSKB X0, DX
	TESTL DX, DX
	JNZ nonascii
	ADDQ $16, AX
	CMPQ AX, CX
	JB scan
	MOVQ AX, ret+24(FP)
	RET
nonascii:
	BSFL DX, DX
	ADDQ DX, AX
	MOVQ AX, ret+24(FP)
	RET

