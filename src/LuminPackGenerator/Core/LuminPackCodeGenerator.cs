            //             sb.AppendLine($"            internal {localField.TypeName}{nullable} {localField.Name};");
            //         }
            //
            //         sb.AppendLine("        }");
            //         
            //         sb.AppendLine();
            //     }
            //     
            //     
            // }
            
            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static void GenerateSerializeLengthCode(StringBuilder sb, LuminDataField field, string fieldPath,
            int indent, int depth, string multList = "_")
        {
            string indentStr = new string(' ', indent * 4);
            string depthSuffix = $"{multList}{depth}";

            switch (field.Type)
            {
                case LuminFiledType.Byte or LuminFiledType.Bool or LuminFiledType.SByte:
                    sb.AppendLine($"{indentStr}totalLength += 1;");
                    break;
                case LuminFiledType.Short or LuminFiledType.UShort or LuminFiledType.Char:
                    sb.AppendLine($"{indentStr}totalLength += 2;");
                    break;
                case LuminFiledType.Int or LuminFiledType.Float or LuminFiledType.UInt:
                    sb.AppendLine($"{indentStr}totalLength += 4;");
                    break;
                case LuminFiledType.Long or  LuminFiledType.Double or LuminFiledType.ULong:
                    sb.AppendLine($"{indentStr}totalLength += 8;");
                    break;
                case LuminFiledType.Decimal:
                    sb.AppendLine($"{indentStr}totalLength += 16;");
                    break;
                case LuminFiledType.String:
                    //sb.AppendLine($"{indentStr}var {field.Name}Length = System.Text.Encoding.UTF8.GetByteCount({fieldPath});");
                    sb.AppendLine($"{indentStr}var {field.Name}{depthSuffix}TempValue = {fieldPath};");
                    sb.AppendLine($"{indentStr}totalLength += evaluator.GetStringLength(ref {field.Name}{depthSuffix}TempValue);");
                    break;
                case LuminFiledType.List:
                    var elementType = ConvertGenericsToFieldType(field.GenericType[0]);
                    bool isElementList = elementType == LuminFiledType.List;
    
                    if (!isElementList && IsFixedLengthType(elementType))
                    {
                        string elementLength = GetFixedFieldLength(new LuminDataField { Type = elementType });
                        if (depth > 0)
                            sb.AppendLine($"{indentStr}if ({fieldPath} == null) continue;");
                        sb.AppendLine($"{indentStr}totalLength += 4 + {fieldPath}.Count * {elementLength};");
                    }
                    else if (elementType is LuminFiledType.Class or LuminFiledType.Struct)
                    {
                        
                        sb.AppendLine($"{indentStr}totalLength += 4; // 列表长度前缀");
                        if (depth > 0) 
                            sb.AppendLine($"{indentStr}if ({fieldPath} == null) continue;");
                        
                        if (elementType is LuminFiledType.Struct)
                        {
                            sb.AppendLine($"{indentStr}if (!evaluator.IsReferenceOrContainsReferences<{field.ClassName}>())");
                            sb.AppendLine($"{indentStr}    totalLength += Unsafe.SizeOf<{field.ClassName}>() * {fieldPath}.Count;");
                            sb.AppendLine($"{indentStr}else");
                        }
                        
                        sb.AppendLine($"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {fieldPath}.Count; i{depthSuffix}++)"); // 改为for循环
                        sb.AppendLine($"{indentStr}{{");
                        sb.AppendLine($"{indentStr}    var element = {fieldPath}[i{depthSuffix}];"); // 通过索引访问
                        
                        // if (elementType is LuminFiledType.Class) 
                        //     sb.AppendLine($"{indentStr}    if (element == null) continue;");
                        sb.AppendLine($"{indentStr}    totalLength += 1;");
                        
                        for (int i = 0; i < field.ClassFields.Count; i++)
                        {
                            var subField = field.ClassFields[i];
                            
                            if (subField.FieldType is LuminDataType.Reference)
                            {
                                if (subField.IsPrivate)
                                    sb.AppendLine($"{indentStr}    if (Get{field.Name}{subField.Name}(element) != null)");
                                else 
                                    sb.AppendLine($"{indentStr}    if (element.{subField.Identifier} != null)");
                                
                                sb.AppendLine($"{indentStr}    {{");
                                if (subField.IsPrivate)
                                {
                                    GenerateSerializeLengthCode(sb, subField, $"Get{field.Name}{subField.Name}(element)", indent + 2, depth + 1);
                                }
                                else 
                                    GenerateSerializeLengthCode(sb, subField, "element." + subField.Identifier, indent + 2, depth + 1);
                                
                                sb.AppendLine($"{indentStr}    }}");
                                switch (subField.Type)
                                {
                                    case LuminFiledType.List or LuminFiledType.Array:
                                        sb.AppendLine($"{indentStr}    else");
                                        sb.AppendLine($"{indentStr}    {{");
                                        sb.AppendLine($"{indentStr}        totalLength += 4;");
                                        sb.AppendLine($"{indentStr}    }}"); break;
                                    case LuminFiledType.String:
                                        sb.AppendLine($"{indentStr}    else");
                                        sb.AppendLine($"{indentStr}    {{");
                                        sb.AppendLine($"{indentStr}        totalLength += evaluator.StringRecordLength();");
                                        sb.AppendLine($"{indentStr}    }}"); break;
                                    default:
                                        sb.AppendLine($"{indentStr}    else");
                                        sb.AppendLine($"{indentStr}    {{");
                                        sb.AppendLine($"{indentStr}        totalLength += 1;");
                                        sb.AppendLine($"{indentStr}    }}"); break;
                                }
                                
                            }
                            else
                            {
                                
                                #region 连续值类型字段优化

                                if (IsMergeableField(subField))
                                {
                                    var num = FindNextMergeableField(field.ClassFields, i);

                                    if (num != i)
                                    {
                                        int sum = 0;
                                        for (var j = i; j <= num; j++)
                                        {
                                            int.TryParse(GetFixedFieldLength(field.ClassFields[j]), out var result);
                                            sum += result;
                                        }
                                        sb.Append($"{indentStr}    totalLength += {sum};");
                                        sb.AppendLine();
                                        i = num;
                                        continue;
                                    }
                                }
                                #endregion
                                
                                GenerateSerializeLengthCode(sb, subField, "element." + subField.Identifier, indent + 1, depth + 1);
                            }
                            
                        }
                        sb.AppendLine($"{indentStr}}}");
                    }
                    else
                    {
                        // 处理嵌套列表或可变长度元素
                        sb.AppendLine($"{indentStr}totalLength += 4;");
                        if (depth > 0) 
                            sb.AppendLine($"{indentStr}if ({fieldPath} == null) continue;");
                        sb.AppendLine(field.FixLength is int.MaxValue 
                            ? $"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {fieldPath}.Count; i{depthSuffix}++)"
                            : $"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {field.FixLength}; i{depthSuffix}++)");
                        
                        sb.AppendLine($"{indentStr}{{");
                        var elementField = new LuminDataField
                        {
                            Type = elementType, 
                            FieldType = field.FieldType,
                            GenericType = field.GenericType.Skip(1).ToList(),
                            ClassFields = field.ClassFields,
                            ClassName = field.ClassName,
                            ClassGenericType = field.ClassGenericType
                        };
                        
                        if (elementType is LuminFiledType.String)
                        {
                            sb.AppendLine($"{indentStr}    if ({fieldPath}[i{depthSuffix}] == null)");
                            sb.AppendLine($"{indentStr}    {{");
                            sb.AppendLine($"{indentStr}        totalLength += evaluator.StringRecordLength();");
                            sb.AppendLine($"{indentStr}        continue;");
                            sb.AppendLine($"{indentStr}    }}");
                        }
                        
                        GenerateSerializeLengthCode(sb, elementField, $"{fieldPath}[i{depthSuffix}]", indent + 1, depth + 1);
                        sb.AppendLine($"{indentStr}}}");
                    }
                    break;
                case LuminFiledType.Array:
                    var arrayType = ConvertGenericsToFieldType(field.GenericType[0]);
                    bool isElementArray = arrayType == LuminFiledType.Array;
    
                    if (!isElementArray && IsFixedLengthType(arrayType))
                    {
                        string elementLength = GetFixedFieldLength(new LuminDataField { Type = arrayType });
                        if (depth > 0) 
                            sb.AppendLine($"{indentStr}if ({fieldPath} == null) continue;");
                        sb.AppendLine($"{indentStr}totalLength += 4 + {fieldPath}.Length * {elementLength};");
                    }
                    else if (arrayType is LuminFiledType.Class or LuminFiledType.Struct)
                    {
                        sb.AppendLine($"{indentStr}totalLength += 4; // 列表长度前缀");
                        if (depth > 0 && arrayType is LuminFiledType.Class) 
                            sb.AppendLine($"{indentStr}if ({fieldPath} == null) continue;");
                        
                        if (arrayType is LuminFiledType.Struct)
                        {
                            sb.AppendLine($"{indentStr}if (!evaluator.IsReferenceOrContainsReferences<{field.ClassName}>())");
                            sb.AppendLine($"{indentStr}    totalLength += Unsafe.SizeOf<{field.ClassName}>() * {fieldPath}.Length;");
                            sb.AppendLine($"{indentStr}else");
                        }
                        
                        sb.AppendLine($"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {fieldPath}.Length; i{depthSuffix}++)"); // 改为for循环
                        sb.AppendLine($"{indentStr}{{");
                        sb.AppendLine($"{indentStr}    totalLength += 1;");
                        
                        for (int i = 0; i < field.ClassFields.Count; i++)
                        {
                            var subField  = field.ClassFields[i];
                            
                            if (subField.FieldType is LuminDataType.Reference)
                            {
                                if (subField.IsPrivate)
                                    sb.AppendLine($"{indentStr}    if (Get{field.Name}{subField.Name}({fieldPath}[i{depthSuffix}]) != null)");
                                else 
                                    sb.AppendLine($"{indentStr}    if ({fieldPath}[i{depthSuffix}].{subField.Identifier} != null)");
                                
                                sb.AppendLine($"{indentStr}    {{");
                                if (subField.IsPrivate)
                                {
                                    GenerateSerializeLengthCode(sb, subField, $"Get{field.Name}{subField.Name}({fieldPath}[i{depthSuffix}])", indent + 2, depth + 1);
                                }
                                else 
                                    GenerateSerializeLengthCode(sb, subField, $"{fieldPath}[i{depthSuffix}]." + subField.Identifier, indent + 2, depth + 1);
                                
                                sb.AppendLine($"{indentStr}    }}");
                                switch (subField.Type)
                                {
                                    case LuminFiledType.List or LuminFiledType.Array:
                                        sb.AppendLine($"{indentStr}    else");
                                        sb.AppendLine($"{indentStr}    {{");
                                        sb.AppendLine($"{indentStr}        totalLength += 4;");
                                        sb.AppendLine($"{indentStr}    }}"); break;
                                    case LuminFiledType.String:
                                        sb.AppendLine($"{indentStr}    else");
                                        sb.AppendLine($"{indentStr}    {{");
                                        sb.AppendLine($"{indentStr}        totalLength += evaluator.StringRecordLength();");
                                        sb.AppendLine($"{indentStr}    }}"); break;
                                    default:
                                        sb.AppendLine($"{indentStr}    else");
                                        sb.AppendLine($"{indentStr}    {{");
                                        sb.AppendLine($"{indentStr}        totalLength += 1;");
                                        sb.AppendLine($"{indentStr}    }}"); break;
                                }
                            }
                            else
                            {
                                #region 连续值类型字段优化

                                if (IsMergeableField(subField))
                                {
                                    var num = FindNextMergeableField(field.ClassFields, i);

                                    if (num != i)
                                    {
                                        int sum = 0;
                                        for (var j = i; j <= num; j++)
                                        {
                                            int.TryParse(GetFixedFieldLength(field.ClassFields[j]), out var result);
                                            sum += result;
                                        }
                                        sb.Append($"{indentStr}    totalLength += {sum};");
                                        sb.AppendLine();
                                        i = num;
                                        continue;
                                    }
                                }
                                #endregion
                                
                                GenerateSerializeLengthCode(sb, subField, $"{fieldPath}[i{depthSuffix}]." + subField.Identifier, indent + 1, depth + 1);
                            }
                            
                        }
                        sb.AppendLine($"{indentStr}}}");
                    }
                    else
                    {
                        // 处理嵌套列表或可变长度元素
                        sb.AppendLine($"{indentStr}totalLength += 4;");
                        if (depth > 0) 
                            sb.AppendLine($"{indentStr}if ({fieldPath} == null) continue;");
                        sb.AppendLine(field.FixLength is int.MaxValue 
                            ? $"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {fieldPath}.Length; i{depthSuffix}++)"
                            : $"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {field.FixLength}; i{depthSuffix}++)");
                            
                        sb.AppendLine($"{indentStr}{{");
                        var elementField = new LuminDataField
                        {
                            Type = arrayType, 
                            FieldType = field.FieldType,
                            GenericType = field.GenericType.Skip(1).ToList(),
                            ClassFields = field.ClassFields,
                            ClassName = field.ClassName,
                            ClassGenericType = field.ClassGenericType
                        };
                        
                        if (arrayType is LuminFiledType.String)
                        {
                            sb.AppendLine($"{indentStr}    if ({fieldPath}[i{depthSuffix}] == null)");
                            sb.AppendLine($"{indentStr}    {{");
                            sb.AppendLine($"{indentStr}        totalLength += evaluator.StringRecordLength();");
                            sb.AppendLine($"{indentStr}        continue;");
                            sb.AppendLine($"{indentStr}    }}");
                        }
                        
                        
                        GenerateSerializeLengthCode(sb, elementField, $"{fieldPath}[i{depthSuffix}]", indent + 1, depth + 1);
                        sb.AppendLine($"{indentStr}}}");
                    }
                    break;
                case LuminFiledType.Class:
                case LuminFiledType.Struct:
                    if (IsPureValueTypeStruct(field))
                    {
                        sb.AppendLine($"{indentStr}totalLength += Unsafe.SizeOf<{field.ClassName}>();");
                        break;
                    }
                    sb.AppendLine($"{indentStr}// {field.ClassName}长度计算");
                    sb.AppendLine($"{indentStr}totalLength += 1;");
                    for (int i = 0; i < field.ClassFields.Count; i++)
                    {
                        var subField = field.ClassFields[i];
                        if (subField.FieldType is LuminDataType.Reference)
                        {
                            if (subField.IsPrivate)
                                sb.AppendLine($"{indentStr}if (Get{field.Name}{subField.Name}({fieldPath}) != null)");
                            else 
                                sb.AppendLine($"{indentStr}if ({fieldPath}.{subField.Identifier} != null)");
                            sb.AppendLine($"{indentStr}{{");
                            var classDepth = subField.Type is LuminFiledType.Array or LuminFiledType.List ? 0 : depth + 1;

                            if (subField.IsPrivate)
                            {
                                GenerateSerializeLengthCode(sb, subField, $"Get{field.Name}{subField.Name}({fieldPath})", indent + 1, classDepth, multList + "_");
                            }
                            else 
                                GenerateSerializeLengthCode(sb, subField, $"{fieldPath}.{subField.Identifier}", indent + 1, classDepth, multList + "_");
                            
                            sb.AppendLine($"{indentStr}}}");
                            switch (subField.Type)
                            {
                                case LuminFiledType.List or LuminFiledType.Array:
                                    sb.AppendLine($"{indentStr}else");
                                    sb.AppendLine($"{indentStr}{{");
                                    sb.AppendLine($"{indentStr}    totalLength += 4;");
                                    sb.AppendLine($"{indentStr}}}"); break;
                                case LuminFiledType.String:
                                    sb.AppendLine($"{indentStr}else");
                                    sb.AppendLine($"{indentStr}{{");
                                    sb.AppendLine($"{indentStr}    totalLength += evaluator.StringRecordLength();");
                                    sb.AppendLine($"{indentStr}}}"); break;
                                default:
                                    sb.AppendLine($"{indentStr}else");
                                    sb.AppendLine($"{indentStr}{{");
                                    sb.AppendLine($"{indentStr}    totalLength += 1;");
                                    sb.AppendLine($"{indentStr}}}"); break;
                            }
                        }
                        else
                        {
                            
                            #region 连续值类型字段优化

                            if (IsUnmanagedFiledType(subField.Type))
                            {
                                var num = FindNextUnmanagedType(field.ClassFields, i);

                                if (num != i)
                                {
                                    int sum = 0;
                                    for (var j = i; j <= num; j++)
                                    {
                                        int.TryParse(GetFixedFieldLength(field.ClassFields[j]), out var result);
                                        sum += result;
                                    }
                                    sb.Append($"{indentStr}totalLength += {sum};");
                                    sb.AppendLine();
                                    i = num;
                                    continue;
                            
                                }
                            }
                    
                            #endregion
                            
                            GenerateSerializeLengthCode(sb, subField, $"{fieldPath}.{subField.Identifier}", indent, depth + 1, multList + "_");
                        }
                        
                    }
                    break;
                case LuminFiledType.Enum:
                    sb.AppendLine($"{indentStr}totalLength += {GetEnumFieldLength(field.EnumType)};");
                    break;
                case LuminFiledType.Other:
                default:
                    sb.AppendLine($"{indentStr}evaluator.CalculateValue(in {fieldPath});"); break;
            }
        }


        private static void GenerateSerializeCode(
            StringBuilder sb, LuminDataField field, string fieldPath, string span, string offset,
            int indent, int depth, bool isMultClass = false,
            string stringRecordLength = "writer.StringRecordLength()")
        {
            string indentStr = new string(' ', indent * 4);
            string depthSuffix = $"_{depth}";

            switch (field.Type)
            {
                case LuminFiledType.Byte or LuminFiledType.SByte:
                    sb.AppendLine($"{indentStr}writer.GetSpanReference({offset}) = {fieldPath};");
                    if (isMultClass)
                        sb.AppendLine($"{indentStr}{offset} += 1;");
                    break;
                case LuminFiledType.Bool:
                    if (isMultClass)
                        sb.AppendLine($"{indentStr}writer.WriteBooleanAndAdvance(ref {offset}, {fieldPath});");
                    else
                        sb.AppendLine($"{indentStr}writer.WriteUnmanagedWithoutSizeReturn(ref {offset}, {fieldPath});");
                    break;
                case LuminFiledType.Short or LuminFiledType.UShort or LuminFiledType.Char:
                    sb.AppendLine($"{indentStr}writer.WriteUnmanagedWithoutSizeReturn(ref {offset}, {fieldPath});");
                    if (isMultClass)
                        sb.AppendLine($"{indentStr}{offset} += 2;");
                    break;
                case LuminFiledType.Int or LuminFiledType.UInt:
                case LuminFiledType.Float:
                    sb.AppendLine($"{indentStr}writer.WriteUnmanagedWithoutSizeReturn(ref {offset}, {fieldPath});");
                    if (isMultClass)
                        sb.AppendLine($"{indentStr}{offset} += 4;");
                    break;
                case LuminFiledType.Long or LuminFiledType.ULong:
                case LuminFiledType.Double:
                    sb.AppendLine($"{indentStr}writer.WriteUnmanagedWithoutSizeReturn(ref {offset}, {fieldPath});");
                    if (isMultClass)
                        sb.AppendLine($"{indentStr}{offset} += 8;");
                    break;
                case LuminFiledType.Decimal:
                    sb.AppendLine($"{indentStr}writer.WriteUnmanagedWithoutSizeReturn(ref {offset}, {fieldPath});");
                    if (isMultClass)
                        sb.AppendLine($"{indentStr}{offset} += 16;");
                    break;
                case LuminFiledType.String:
                    //if (depth < 1) sb.AppendLine($"{indentStr}var {field.Name}Length = writer.GetStringLength({fieldPath});");
                    sb.AppendLine($"{indentStr}var {field.Name}Length = writer.WriteString(ref {offset}, {fieldPath});");
                    if (isMultClass)
                        sb.AppendLine($"{indentStr}{offset} += {field.Name}Length + {stringRecordLength};");
                    //sb.AppendLine($"{indentStr}System.Text.Encoding.UTF8.GetBytes({fieldPath}, {span}.Slice({offset}, {field.Name}Length));");
                    //sb.AppendLine($"{indentStr}{span}[{offset} + {field.Name}Length] = 0; // 终止符");
                    break;
                case LuminFiledType.List:
                    if (!IsReferenceGenericType(field.GenericType.FirstOrDefault()))
                    {
                        if (field.IsCompress)
                        {
                            // Compress path: get list span and use DangerousWriteUnmanagedSpanWithCompress
                            sb.AppendLine($"{indentStr}var {field.Name}ListTempValue{depthSuffix} = {fieldPath};");
                            sb.AppendLine($"{indentStr}var {field.Name}ListTempSpan{depthSuffix} = LuminPackMarshal.GetListSpan({field.Name}ListTempValue{depthSuffix}!);");
                            sb.AppendLine($"{indentStr}writer.DangerousWriteUnmanagedSpanWithCompress(ref {offset}, {field.Name}ListTempSpan{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        }
                        else
                        {
                            sb.AppendLine($"{indentStr}var {field.Name}ListTempValue{depthSuffix} = {fieldPath};");
                            sb.AppendLine($"{indentStr}writer.WriteUnmanagedList(ref {offset}, ref {field.Name}ListTempValue{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        }
                        sb.AppendLine($"{indentStr}var {field.Name}ListOffset{depthSuffix} = {offset} + {field.Name}TempLength{depthSuffix};");

                        if (isMultClass)
                            sb.AppendLine($"{indentStr}{offset} = {field.Name}ListOffset{depthSuffix};");
                        return;
                    }
                    
                    if (depth > 0)
                    {
                        sb.AppendLine($"{indentStr}var {field.Name}v{depthSuffix} = {fieldPath};");
                        sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = writer.WriteListHeaderAndGetSpan(ref {offset}, {field.Name}v{depthSuffix}!);");
                    }
                    else 
                        sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = writer.WriteListHeaderAndGetSpan(ref {offset}, {fieldPath}!);");

                    sb.AppendLine($"{indentStr}int {field.Name}Count{depthSuffix} = {field.Name}TempSpan{depthSuffix}.Length;");
                    sb.AppendLine($"{indentStr}int {field.Name}ListOffset{depthSuffix} = {offset} + 4;");
                    
                    
                    var elementField = new LuminDataField
                    {
                        Type = ConvertGenericsToFieldType(field.GenericType[0]),
                        ClassName = field.ClassName,
                        ClassFields = field.ClassFields,
                        ClassGenericType = field.ClassGenericType,
                        GenericType = field.GenericType.Skip(1).ToList(),
                        IsCompress = field.IsCompress,
                    };
                    
                    if (IsPureValueTypeStruct(elementField))
                    {
                        if (field.IsCompress)
                            // 自定义 unmanaged 结构体 List 的压缩路径：
                            // WriteCollectionHeader 已在 offset 写入 [count:4]，
                            // WithOutHeader 必须从 ListOffset(=offset+4) 开始写 [compressedLen:4][data]
                            sb.AppendLine($"{indentStr}writer.DangerousWriteUnmanagedSpanWithOutHeaderWithCompress(ref {field.Name}ListOffset{depthSuffix}, {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        else
                            sb.AppendLine($"{indentStr}writer.WriteUnmanagedSpanWithOutHeader(ref {offset}, {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                        break;
                        
                        // sb.AppendLine($"{indentStr}if (!writer.IsReferenceOrContainsReferences<{field.ClassName}>() && {field.Name}Count{depthSuffix} is not 0)");
                        // sb.AppendLine($"{indentStr}{{");
                        // sb.AppendLine($"{indentStr}    var {field.Name}ListTempValue{depthSuffix} = {fieldPath};");
                        // sb.AppendLine($"{indentStr}    writer.WriteUnmanagedSpanWithOutHeader(ref {offset}, {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        // sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                        // sb.AppendLine($"{indentStr}}}");
                            // sb.AppendLine($"{indentStr}else");
                    }

                    //sb.AppendLine($"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {field.Name}Count{depthSuffix}; i{depthSuffix}++)");
                    sb.AppendLine($"{indentStr}foreach (ref var v{depthSuffix} in {field.Name}TempSpan{depthSuffix})");
                    sb.AppendLine($"{indentStr}{{");
                    
                    // 特殊处理字符串元素
                    if (elementField.Type is LuminFiledType.String)
                    {
                        //sb.AppendLine($"{indentStr}    if ({fieldPath}[i{depthSuffix}] == null)");
                        sb.AppendLine($"{indentStr}    if (v{depthSuffix} == null)");
                        sb.AppendLine($"{indentStr}    {{");
                        sb.AppendLine($"{indentStr}        writer.WriteNullStringHeader(ref {field.Name}ListOffset{depthSuffix});");
                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += {stringRecordLength};");
                        sb.AppendLine($"{indentStr}        continue;");
                        sb.AppendLine($"{indentStr}    }}");
                        
                        // 一次性获取字节数组并写入
                        //sb.AppendLine($"{indentStr}    int strLen_{depthSuffix} = System.Text.Encoding.UTF8.GetByteCount({fieldPath}[i{depthSuffix}]);");
                        //sb.AppendLine($"{indentStr}    System.Text.Encoding.UTF8.GetBytes({fieldPath}[i{depthSuffix}], {span}.Slice({field.Name}ListOffset{depthSuffix}, strLen_{depthSuffix}));");
                        //sb.AppendLine($"{indentStr}    {span}[{field.Name}ListOffset{depthSuffix} + strLen_{depthSuffix}] = 0;");
                        //sb.AppendLine($"{indentStr}    int strLen_{depthSuffix} = writer.GetStringLength({fieldPath}[i{depthSuffix}]);");
                        sb.AppendLine($"{indentStr}    int strLen_{depthSuffix} = writer.WriteString(ref {field.Name}ListOffset{depthSuffix}, v{depthSuffix});");
                        sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += strLen_{depthSuffix} + {stringRecordLength};");
                        
                        if (isMultClass)
                            sb.AppendLine($"{indentStr}    {offset} = {field.Name}ListOffset{depthSuffix};");
                    }
                    else if (elementField.Type is LuminFiledType.Class or LuminFiledType.Struct)
                    {
                        if (IsPureValueTypeStruct(elementField))
                        {
                            sb.AppendLine($"{indentStr}    // 纯值类型结构体");
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += writer.WriteUnmanaged(ref {field.Name}ListOffset{depthSuffix}, v{depthSuffix});");
                            sb.AppendLine($"{indentStr}}}");
                            break;
                        }
                        
                        if (elementField.Type is LuminFiledType.Class)
                            sb.AppendLine($"{indentStr}    var element = v{depthSuffix};");
                        else
                            sb.AppendLine($"{indentStr}    ref var element = ref v{depthSuffix};");

                        if (elementField.Type is LuminFiledType.Class)
                        {
                            sb.AppendLine($"{indentStr}    if (element == null)");
                            sb.AppendLine($"{indentStr}    {{");
                            sb.AppendLine($"{indentStr}        writer.WriteNullObjectHeader(ref {field.Name}ListOffset{depthSuffix});");
                            sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 1;");
                            sb.AppendLine($"{indentStr}        continue;");
                            sb.AppendLine($"{indentStr}    }}");
                        }
                        
                        sb.AppendLine($"{indentStr}    writer.WriteObjectHeader(ref {field.Name}ListOffset{depthSuffix}, {elementField.ClassFields.Count});");
                        sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += 1;");
                        sb.AppendLine();
                        
                        for (var i = 0; i < elementField.ClassFields.Count; i++)
                        {
                            var subField = elementField.ClassFields[i];
                            
                            if (subField.FieldType is LuminDataType.Reference)
                            {
                                var serializeSubFieldName = $"serialize{subField.Name}Field{depthSuffix}";
                                if (subField.IsPrivate)
                                    sb.AppendLine($"{indentStr}    if (Get{field.Name}{subField.Name}(element) is {{ }} {serializeSubFieldName})");
                                else 
                                    sb.AppendLine($"{indentStr}    if (element.{subField.Identifier} is {{ }} {serializeSubFieldName})");
                                sb.AppendLine($"{indentStr}    {{");
                                GenerateSerializeCode(sb, subField, serializeSubFieldName, span,
                                    $"{field.Name}ListOffset{depthSuffix}", indent + 2, depth + 1, true,
                                    stringRecordLength);
                                
                                //sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += {GetFieldLength(subField, depth + 1)};");
                                
                                sb.AppendLine($"{indentStr}    }}");
                                sb.AppendLine($"{indentStr}    else");
                                sb.AppendLine($"{indentStr}    {{");
                                switch (subField.Type)
                                {
                                    case LuminFiledType.Array or LuminFiledType.List:
                                        sb.AppendLine($"{indentStr}        writer.WriteNullCollectionHeader(ref {field.Name}ListOffset{depthSuffix});");
                                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 4;");
                                        break;
                                    case LuminFiledType.String:
                                        sb.AppendLine($"{indentStr}        writer.WriteNullStringHeader(ref {field.Name}ListOffset{depthSuffix});");
                                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += {stringRecordLength};");
                                        break;
                                    default:
                                        sb.AppendLine($"{indentStr}        writer.WriteNullObjectHeader(ref {field.Name}ListOffset{depthSuffix});");
                                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 1;");
                                        break;
                                }
                                sb.AppendLine($"{indentStr}    }}");
                            }
                            else
                            {
                                
                                #region 连续值类型字段优化

                                if (IsMergeableField(subField))
                                {
                                    var num = FindNextMergeableField(elementField.ClassFields, i);

                                    if (num != i)
                                    {
                                        if (num - i >= 14)
                                        {
                                            num = i + 14;
                                        }
                        
                                        sb.Append($"{indentStr}    {field.Name}ListOffset{depthSuffix} += writer.WriteUnmanaged(ref {field.Name}ListOffset{depthSuffix}");
                                        for (var j = i; j <= num; j++)
                                        {
                                            if (elementField.ClassFields[j].IsPrivate)
                                                sb.Append($", Get{field.Name}{elementField.ClassFields[j].Name}(element)");
                                            else 
                                                sb.Append($", element.{elementField.ClassFields[j].Name}");
                                        }
                                        sb.Append(");");
                                        sb.AppendLine();
                                        i = num;
                                        continue;
                                    }
                                }
                                #endregion
                                
                                if (subField.IsPrivate)
                                {
                                    GenerateSerializeCode(sb, subField, $"Get{field.Name}{subField.Name}(element)", span, $"{field.Name}ListOffset{depthSuffix}", indent + 2, depth + 1, true, stringRecordLength);
                                }
                                else
                                    GenerateSerializeCode(sb, subField, $"element.{subField.Identifier}", span, $"{field.Name}ListOffset{depthSuffix}", indent + 1, depth + 1, true, stringRecordLength);
                                //sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {GetFieldLength(subField, depth + 1, pattern: "writer")};");
                            }
                            
                        }
                    }
                    else
                    {
                        if (elementField.Type is LuminFiledType.Array or LuminFiledType.List)
                        {
                            sb.AppendLine($"{indentStr}    if (v{depthSuffix} == null)");
                            sb.AppendLine($"{indentStr}    {{");
                            sb.AppendLine($"{indentStr}        writer.WriteNullCollectionHeader(ref {field.Name}ListOffset{depthSuffix});");
                            sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 4;");
                            sb.AppendLine($"{indentStr}        continue;");
                            sb.AppendLine($"{indentStr}    }}");
                        }
                        
                        GenerateSerializeCode(
                            sb,
                            elementField,
                            $"v{depthSuffix}",
                            span,
                            $"{field.Name}ListOffset{depthSuffix}",
                            indent + 1,
                            depth + 1,
                            stringRecordLength: stringRecordLength
                        );
                        if(elementField.Type is LuminFiledType.List or LuminFiledType.Array) 
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} = {GetSerializeFieldLength(elementField, depth + 1, stringRecordLength)};");
                        else
                        {
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {GetSerializeFieldLength(elementField, depth + 1, stringRecordLength)};");
                        }
                    }
                    //sb.AppendLine($"{indentStr}    writer.FlushCurrentIndex({field.Name}ListOffset{depthSuffix});");
                    sb.AppendLine($"{indentStr}}}");
                    break;
                case LuminFiledType.Array:
                    
                    if (!IsReferenceGenericType(field.GenericType.FirstOrDefault()))
                    {
                        if (field.IsCompress)
                        {
                            sb.AppendLine($"{indentStr}writer.DangerousWriteUnmanagedArrayWithCompress(ref {offset}, {fieldPath}, out var {field.Name}TempLength{depthSuffix});");
                        }
                        else
                        {
                            sb.AppendLine($"{indentStr}writer.EnsureAdditionalCapacity(checked(4 + global::System.Runtime.InteropServices.MemoryMarshal.AsBytes({fieldPath}.AsSpan()).Length));");
                            sb.AppendLine($"{indentStr}writer.DangerousWriteUnmanagedArray(ref {offset}, {fieldPath}, out var {field.Name}TempLength{depthSuffix});");
                        }
                        sb.AppendLine($"{indentStr}var {field.Name}ListOffset{depthSuffix} = {offset} + {field.Name}TempLength{depthSuffix};");
                        
                        if (isMultClass)
                            sb.AppendLine($"{indentStr}{offset} = {field.Name}ListOffset{depthSuffix};");
                        
                        return;
                    }
                    
                    var arrayElementField = new LuminDataField
                    {
                        Type = ConvertGenericsToFieldType(field.GenericType[0]),
                        ClassName = field.ClassName,
                        ClassFields = field.ClassFields,
                        ClassGenericType = field.ClassGenericType,
                        GenericType = field.GenericType.Skip(1).ToList(),
                        IsCompress = field.IsCompress,
                    };
                    
                    sb.AppendLine($"{indentStr}int {field.Name}Count{depthSuffix} = {fieldPath}.Length;");
                    //sb.AppendLine($"{indentStr}Unsafe.WriteUnaligned(ref {span}[{offset}], {field.Name}Count{depthSuffix});");
                    sb.AppendLine($"{indentStr}writer.WriteCollectionHeader(ref {offset}, {field.Name}Count{depthSuffix});");
                    sb.AppendLine($"{indentStr}int {field.Name}ListOffset{depthSuffix} = {offset} + 4;");
                    
                    if (IsPureValueTypeStruct(arrayElementField))
                    {
                        if (field.IsCompress)
                            // 自定义 unmanaged 结构体 Array 的压缩路径：
                            // WriteCollectionHeader 已在 offset 写入 [count:4]，
                            // WithOutHeader 必须从 ListOffset(=offset+4) 开始写 [compressedLen:4][data]
                            sb.AppendLine($"{indentStr}writer.DangerousWriteUnmanagedArrayWithOutHeaderWithCompress(ref {field.Name}ListOffset{depthSuffix}, {fieldPath}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        else
                            sb.AppendLine($"{indentStr}writer.WriteUnmanagedArrayWithOutHeader(ref {offset}, {fieldPath}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                        break;
                        
                        // sb.AppendLine($"{indentStr}if (!writer.IsReferenceOrContainsReferences<{field.ClassName}>())");
                        // sb.AppendLine($"{indentStr}{{");
                        // sb.AppendLine($"{indentStr}    var tempArray{depthSuffix} = {fieldPath};");
                        // sb.AppendLine($"{indentStr}    writer.WriteUnmanagedArrayWithOutHeader(ref {offset}, tempArray{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        // sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                        // sb.AppendLine($"{indentStr}}}");
                            // sb.AppendLine($"{indentStr}else");
                    }

                    
                    sb.AppendLine($"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {field.Name}Count{depthSuffix}; i{depthSuffix}++)");
                    sb.AppendLine($"{indentStr}{{");
                    sb.AppendLine($"{indentStr}    ref var v{depthSuffix} = ref {fieldPath}[i{depthSuffix}];");
    
                    
    
                    // 特殊处理字符串元素
                    if (arrayElementField.Type == LuminFiledType.String)
                    {
                        sb.AppendLine($"{indentStr}    if (v{depthSuffix} == null)");
                        sb.AppendLine($"{indentStr}    {{");
                        sb.AppendLine($"{indentStr}        writer.WriteNullStringHeader(ref {field.Name}ListOffset{depthSuffix});");
                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += {stringRecordLength};");
                        sb.AppendLine($"{indentStr}        continue;");
                        sb.AppendLine($"{indentStr}    }}");
                        
                        // 一次性获取字节数组并写入
                        //sb.AppendLine($"{indentStr}    int strLen_{depthSuffix} = System.Text.Encoding.UTF8.GetByteCount({fieldPath}[i{depthSuffix}]);");
                        //sb.AppendLine($"{indentStr}    System.Text.Encoding.UTF8.GetBytes({fieldPath}[i{depthSuffix}], {span}.Slice({field.Name}ListOffset{depthSuffix}, strLen_{depthSuffix}));");
                        //sb.AppendLine($"{indentStr}    {span}[{field.Name}ListOffset{depthSuffix} + strLen_{depthSuffix}] = 0;");
                        //sb.AppendLine($"{indentStr}    int strLen_{depthSuffix} = writer.GetStringLength({fieldPath}[i{depthSuffix}]);");
                        sb.AppendLine($"{indentStr}    int strLen_{depthSuffix} = writer.WriteString(ref {field.Name}ListOffset{depthSuffix}, v{depthSuffix});");
                        sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += strLen_{depthSuffix} + {stringRecordLength};");
                        
                        if (isMultClass)
                            sb.AppendLine($"{indentStr}    {offset} = {field.Name}ListOffset{depthSuffix};");
                    }
                    else if (arrayElementField.Type is LuminFiledType.Class or LuminFiledType.Struct)
                    {
                        
                        if (IsPureValueTypeStruct(arrayElementField))
                        {
                            sb.AppendLine($"{indentStr}    // 纯值类型结构体");
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += writer.WriteUnmanaged(ref {field.Name}ListOffset{depthSuffix}, v{depthSuffix});");
                            sb.AppendLine($"{indentStr}}}");
                            break;
                        }
                        
                        var serializedArrayElementPath = $"v{depthSuffix}";
                        if (arrayElementField.Type is LuminFiledType.Class)
                        {
                            var serializedArrayElementName = $"element{depthSuffix}";
                            sb.AppendLine($"{indentStr}    var {serializedArrayElementName} = v{depthSuffix};");
                            serializedArrayElementPath = serializedArrayElementName;
                            sb.AppendLine($"{indentStr}    if ({serializedArrayElementPath} == null)");
                            sb.AppendLine($"{indentStr}    {{");
                            sb.AppendLine($"{indentStr}        writer.WriteNullObjectHeader(ref {field.Name}ListOffset{depthSuffix});");
                            sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 1;");
                            sb.AppendLine($"{indentStr}        continue;");
                            sb.AppendLine($"{indentStr}    }}");
                        }
                        
                        var arrayElementStartField = 0;
                        var firstMergedArrayField = arrayElementField.ClassFields.Count > 0 &&
                                                    IsMergeableField(arrayElementField.ClassFields[0])
                            ? FindNextMergeableField(arrayElementField.ClassFields, 0)
                            : 0;
                        if (firstMergedArrayField == 2)
                        {
                            sb.Append($"{indentStr}    writer.WriteObjectHeaderAndUnmanaged(ref {field.Name}ListOffset{depthSuffix}, {arrayElementField.ClassFields.Count}");
                            for (var j = 0; j <= firstMergedArrayField; j++)
                            {
                                var mergedField = arrayElementField.ClassFields[j];
                                if (mergedField.IsPrivate)
                                    sb.Append($", Get{field.Name}{mergedField.Name}({serializedArrayElementPath})");
                                else
                                    sb.Append($", {serializedArrayElementPath}.{mergedField.Name}");
                            }
                            sb.AppendLine(");");
                            arrayElementStartField = firstMergedArrayField + 1;
                        }
                        else
                        {
                            sb.AppendLine($"{indentStr}    writer.WriteObjectHeader(ref {field.Name}ListOffset{depthSuffix}, {arrayElementField.ClassFields.Count});");
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += 1;");
                        }
                        sb.AppendLine();
                        
                        for (var i = arrayElementStartField; i < arrayElementField.ClassFields.Count; i++)
                        {
                            var subField = arrayElementField.ClassFields[i];
                            
                            if (subField.FieldType is LuminDataType.Reference)
                            {
                                var serializeSubFieldName = $"serialize{subField.Name}Field{depthSuffix}";
                                if (subField.IsPrivate)
                                    sb.AppendLine($"{indentStr}    if (Get{field.Name}{subField.Name}({serializedArrayElementPath}) is {{ }} {serializeSubFieldName})");
                                else 
                                    sb.AppendLine($"{indentStr}    if ({serializedArrayElementPath}.{subField.Identifier} is {{ }} {serializeSubFieldName})");
                                sb.AppendLine($"{indentStr}    {{");
                                GenerateSerializeCode(sb, subField, serializeSubFieldName, span,
                                    $"{field.Name}ListOffset{depthSuffix}", indent + 2, depth + 1, true,
                                    stringRecordLength);
                                
                                //sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += {GetFieldLength(subField, depth + 1)};");
                                
                                sb.AppendLine($"{indentStr}    }}");
                                sb.AppendLine($"{indentStr}    else");
                                sb.AppendLine($"{indentStr}    {{");
                                switch (subField.Type)
                                {
                                    case LuminFiledType.Array or LuminFiledType.List:
                                        sb.AppendLine($"{indentStr}        writer.WriteNullCollectionHeader(ref {field.Name}ListOffset{depthSuffix});");
                                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 4;");
                                        break;
                                    case LuminFiledType.String:
                                        sb.AppendLine($"{indentStr}        writer.WriteNullStringHeader(ref {field.Name}ListOffset{depthSuffix});");
                                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += {stringRecordLength};");
                                        break;
                                    default:
                                        sb.AppendLine($"{indentStr}        writer.WriteNullObjectHeader(ref {field.Name}ListOffset{depthSuffix});");
                                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 1;");
                                        break;
                                }
                                sb.AppendLine($"{indentStr}    }}");
                            }
                            else
                            {
                                
                                #region 连续值类型字段优化

                                if (IsMergeableField(subField))
                                {
                                    var num = FindNextMergeableField(arrayElementField.ClassFields, i);

                                    if (num != i)
                                    {
                                        if (num - i >= 14)
                                        {
                                            num = i + 14;
                                        }
                        
                                        sb.Append($"{indentStr}    {field.Name}ListOffset{depthSuffix} += writer.WriteUnmanaged(ref {field.Name}ListOffset{depthSuffix}");
                                        for (var j = i; j <= num; j++)
                                        {
                                            if (arrayElementField.ClassFields[j].IsPrivate)
                                                sb.Append($", Get{field.Name}{arrayElementField.ClassFields[j].Name}({serializedArrayElementPath})");
                                            else
                                                sb.Append($", {serializedArrayElementPath}.{arrayElementField.ClassFields[j].Name}");
                                        }
                                        sb.Append(");");
                                        sb.AppendLine();
                                        i = num;
                                        continue;
                                    }
                                }
                                #endregion
                                
                                if (subField.IsPrivate)
                                {
                                    GenerateSerializeCode(sb, subField, $"Get{field.Name}{subField.Name}({serializedArrayElementPath})", span, $"{field.Name}ListOffset{depthSuffix}", indent + 1, depth + 1, true, stringRecordLength);
                                }
                                else
                                {
                                    GenerateSerializeCode(sb, subField, $"{serializedArrayElementPath}.{subField.Identifier}", span, $"{field.Name}ListOffset{depthSuffix}", indent + 1, depth + 1, true, stringRecordLength);
                                }
                                
                                //sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {GetFieldLength(subField, depth + 1, pattern: "writer")};");
                            }
                            
                        }
                    }
                    else
                    {
                        
                        if (arrayElementField.Type is LuminFiledType.Array or LuminFiledType.List)
                        {
                            sb.AppendLine($"{indentStr}    if (v{depthSuffix} == null)");
                            sb.AppendLine($"{indentStr}    {{");
                            sb.AppendLine($"{indentStr}        writer.WriteNullCollectionHeader(ref {field.Name}ListOffset{depthSuffix});");
                            sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 4;");
                            sb.AppendLine($"{indentStr}        continue;");
                            sb.AppendLine($"{indentStr}    }}");
                        }
                        
                        
                        GenerateSerializeCode(
                            sb,
                            arrayElementField,
                            $"v{depthSuffix}",
                            span,
                            $"{field.Name}ListOffset{depthSuffix}",
                            indent + 1,
                            depth + 1,
                            stringRecordLength: stringRecordLength
                        );
                        if(arrayElementField.Type is LuminFiledType.List or LuminFiledType.Array) 
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} = {GetSerializeFieldLength(arrayElementField, depth + 1, stringRecordLength)};");
                        else
                        {
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {GetSerializeFieldLength(arrayElementField, depth + 1, stringRecordLength)};");
                        }
                    }
                    //sb.AppendLine($"{indentStr}    writer.FlushCurrentIndex({field.Name}ListOffset{depthSuffix});");
                    sb.AppendLine($"{indentStr}}}");
                    break;
                case LuminFiledType.Class:
                case LuminFiledType.Struct:
                    if (IsPureValueTypeStruct(field))
                    {
                        sb.AppendLine($"{indentStr}// 纯值类型结构体 {field.ClassName}，直接整体写入");
                        sb.AppendLine($"{indentStr}writer.Advance(writer.WriteUnmanaged(ref {offset}, {fieldPath}));");
                        break;
                    }
                    sb.AppendLine($"{indentStr}// 序列化{field.ClassName}");
                    var serializedObjectPath = fieldPath;
                    if (field.Type is LuminFiledType.Class && field.ClassFields.Count > 1)
                    {
                        var serializedObjectName = $"serialize{field.Name}Value{depthSuffix}";
                        sb.AppendLine($"{indentStr}var {serializedObjectName} = {fieldPath};");
                        serializedObjectPath = serializedObjectName;
                    }
                    sb.AppendLine($"{indentStr}writer.WriteObjectHeader(ref {offset}, {field.ClassFields.Count});");
                    sb.AppendLine($"{indentStr}{offset} += 1;");
                    sb.AppendLine();
                    for (int i = 0; i < field.ClassFields.Count; i++)
                    {
                        var subField = field.ClassFields[i];
                        
                        if (subField.FieldType is LuminDataType.Reference)
                        {
                            var serializeSubFieldName = $"serialize{subField.Name}Field{depthSuffix}";
                            if (subField.IsPrivate)
                                sb.AppendLine($"{indentStr}if (Get{field.Name}{subField.Name}({serializedObjectPath}) is {{ }} {serializeSubFieldName})");
                            else 
                                sb.AppendLine($"{indentStr}if ({serializedObjectPath}.{subField.Identifier} is {{ }} {serializeSubFieldName})");
                            sb.AppendLine($"{indentStr}{{");
                            
                            GenerateSerializeCode(sb, subField, serializeSubFieldName, span, offset, indent + 1, depth + 1, true, stringRecordLength);
                            if (subField.Type is LuminFiledType.Array or LuminFiledType.List)
                            {
                                var newDepthSuffix = $"_{depth + 1}";
                                sb.AppendLine($"{indentStr}    writer.FlushCurrentIndex({subField.Name}ListOffset{newDepthSuffix});");
                            }
                            sb.AppendLine($"{indentStr}}}");
                            switch (subField.Type)
                            {
                                case LuminFiledType.List or LuminFiledType.Array:
                                    sb.AppendLine($"{indentStr}else");
                                    sb.AppendLine($"{indentStr}{{");
                                    sb.AppendLine($"{indentStr}    writer.WriteNullCollectionHeader(ref {offset});");
                                    sb.AppendLine($"{indentStr}    {offset} += 4;");
                                    sb.AppendLine($"{indentStr}}}"); break;
                                case LuminFiledType.String:
                                    sb.AppendLine($"{indentStr}else");
                                    sb.AppendLine($"{indentStr}{{");
                                    sb.AppendLine($"{indentStr}    writer.WriteNullStringHeader(ref {offset});");
                                    sb.AppendLine($"{indentStr}    {offset} += {stringRecordLength};");
                                    sb.AppendLine($"{indentStr}}}"); break;
                                default:
                                    sb.AppendLine($"{indentStr}else");
                                    sb.AppendLine($"{indentStr}{{");
                                    sb.AppendLine($"{indentStr}    writer.WriteNullObjectHeader(ref {offset});");
                                    sb.AppendLine($"{indentStr}    {offset} += 1;");
                                    sb.AppendLine($"{indentStr}}}"); break;
                            }
                        }
                        else
                        {
                            #region 连续值类型字段优化

                            if (IsMergeableField(subField))
                            {
                                var num = FindNextMergeableField(field.ClassFields, i);

                                if (num != i)
                                {
                                    if (num - i >= 14)
                                    {
                                        num = i + 14;
                                    }
                            
                                    sb.Append($"{indentStr}writer.Advance(writer.WriteUnmanaged(ref {offset}");
                                    for (var j = i; j <= num; j++)
                                    {
                                        if (field.ClassFields[j].IsPrivate) 
                                            sb.Append($", Get{field.Name}{field.ClassFields[j].Name}({serializedObjectPath})");
                                        else 
                                            sb.Append($", {serializedObjectPath}.{field.ClassFields[j].Name}");
                                    }
                                    sb.Append("));");
                                    sb.AppendLine();
                                    i = num;
                                    continue;
                                }
                            }
                            #endregion
                            
                            if (subField.IsPrivate)
                                GenerateSerializeCode(sb, subField, $"Get{field.Name}{subField.Name}({serializedObjectPath})", span, offset, indent, depth + 1, true, stringRecordLength);
                            else 
                                GenerateSerializeCode(sb, subField, $"{serializedObjectPath}.{subField.Identifier}", span, offset, indent, depth + 1, true, stringRecordLength);
                        }
                        
                    }
                    break;
                case LuminFiledType.Enum:
                    
                    if (isMultClass)
                        sb.AppendLine($"{indentStr}writer.Advance(writer.WriteUnmanaged(ref {offset}, ({GetEnumTypeName(field.EnumType)}){fieldPath}));");
                    else
                        sb.AppendLine($"{indentStr}writer.WriteUnmanagedWithoutSizeReturn(ref {offset}, ({GetEnumTypeName(field.EnumType)}){fieldPath});");
                    break;
                case LuminFiledType.Other:
                default:
                    if (field.IsCompress)
                        sb.AppendLine($"{indentStr}writer.WriteValueWithCompress({fieldPath});");
                    else
                        sb.AppendLine($"{indentStr}writer.WriteValue({fieldPath});");
                    break;
            }
        }

        private static void GenerateDeserializeCode(
            StringBuilder sb, LuminDataField field,
            string targetObj, string span,
            string offset, int indent, int depth,
            bool isFirst = true, string fieldPath = "", bool isArray = false, bool isList = false,
            string multList = "_", bool isPrivateFiled = false, string parentName = "",
            bool collectionHeadAlreadyRead = false, bool targetIsKnownFresh = false)
        {
            string indentStr = new string(' ', indent * 4);
            string depthSuffix = $"{multList}{depth}";

            switch (field.Type)
            {
                case LuminFiledType.Byte:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out byte {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.SByte:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out sbyte {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Bool:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out bool {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Short:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out short {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.UShort:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out ushort {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Int:
                    if (isFirst)
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out int {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.UInt:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out uint {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Long:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out long {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.ULong:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out ulong {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Float:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out float {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Double:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out double {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Decimal:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out decimal {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Char:
                    if (isFirst) 
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn(ref {offset}, out char {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.String:
                    sb.AppendLine($"{indentStr}{targetObj} = reader.ReadStringAndAdvance(ref {offset})!;");
                    break;
                case LuminFiledType.List:
                    if (isFirst && depth is 0 && !collectionHeadAlreadyRead) 
                        sb.AppendLine($"{indentStr}reader.TryReadCollectionHead(ref {offset}, out int {field.Name}Count{depthSuffix});");
            
                    var elementField = new LuminDataField
                    {
                        Name = field.Name,
                        Type = ConvertGenericsToFieldType(field.GenericType.FirstOrDefault()),
                        GenericType = field.GenericType.Skip(1).ToList(),
                        ClassName = field.ClassName,
                        ClassFields = field.ClassFields,
                        ClassGenericType = field.ClassGenericType,
                        ConstructParameterCount = field.ConstructParameterCount,
                        IsCompress = field.IsCompress,
                    };
            
                    string genericType = GetFullGenericTypeName(field.GenericType, elementField.ClassName, elementField.ClassGenericType);
                    bool useFreshTopLevelList = isFirst && depth is 0;
                    if (useFreshTopLevelList)
                        sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = reader.CreateFreshListSpan<{genericType}>({field.Name}Count{depthSuffix}, out {targetObj});");
                    else if (isFirst) 
                        sb.AppendLine($"{indentStr}{targetObj} = new List<{genericType}>({field.Name}Count{depthSuffix});");
            
                    sb.AppendLine($"{indentStr}int {field.Name}ListOffset{depthSuffix} = {offset} + 4;");
            
                    if (!IsReferenceGenericType(field.GenericType.FirstOrDefault()))
                    {
                        if (depth > 0)
                        {
                            sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan(element__{depth - 1}, {field.Name}Count{depthSuffix});");
                            if (field.IsCompress)
                            {
                                // 压缩路径：从 offset 起读取 [count:4][compressedLen:4][data]，内部 reader 重读 count
                                sb.AppendLine($"{indentStr}reader.DangerousReadUnmanagedSpanWithCompress(ref {offset}, ref {field.Name}TempSpan{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                                sb.AppendLine($"{indentStr}LuminPackMarshal.SetListSize(element__{depth - 1}, {field.Name}Count{depthSuffix});");
                                sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} = {offset} + {field.Name}TempLength{depthSuffix};");
                            }
                            else
                            {
                                sb.AppendLine($"{indentStr}reader.ReadUnmanagedSpan(ref {field.Name}ListOffset{depthSuffix}, ref {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                                sb.AppendLine($"{indentStr}LuminPackMarshal.SetListSize(element__{depth - 1}, {field.Name}Count{depthSuffix});");
                                sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                            }
                        }
                        else
                        {
                            if (!useFreshTopLevelList)
                                sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan({targetObj}!, {field.Name}Count{depthSuffix});");
                            if (field.IsCompress)
                            {
                                // 压缩路径：从 offset 起读取 [count:4][compressedLen:4][data]
                                sb.AppendLine($"{indentStr}reader.DangerousReadUnmanagedSpanWithCompress(ref {offset}, ref {field.Name}TempSpan{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                                sb.AppendLine($"{indentStr}LuminPackMarshal.SetListSize({targetObj}, {field.Name}Count{depthSuffix});");
                                sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} = {offset} + {field.Name}TempLength{depthSuffix};");
                            }
                            else
                            {
                                sb.AppendLine($"{indentStr}reader.ReadUnmanagedSpan(ref {field.Name}ListOffset{depthSuffix}, ref {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                                sb.AppendLine($"{indentStr}LuminPackMarshal.SetListSize({targetObj}, {field.Name}Count{depthSuffix});");
                                sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                            }
                        }
                        break;
                    }
            
                    if (IsPureValueTypeStruct(elementField))
                    {
                        if (field.IsCompress)
                        {
                            // 压缩路径：count 已由 TryReadCollectionHead 读取，ListOffset=offset+4 跳过 count 头，
                            // 从 ListOffset 开始读 [compressedLen:4][data]
                            if (depth > 0)
                            {
                                sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan(element__{depth - 1}, {field.Name}Count{depthSuffix});");
                                sb.AppendLine($"{indentStr}reader.DangerousReadUnmanagedSpanWithOutHeaderWithCompress(ref {field.Name}ListOffset{depthSuffix}, ref {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                                sb.AppendLine($"{indentStr}LuminPackMarshal.SetListSize(element__{depth - 1}, {field.Name}Count{depthSuffix});");
                            }
                            else
                            {
                                if (!useFreshTopLevelList)
                                    sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan({targetObj}!, {field.Name}Count{depthSuffix});");
                                sb.AppendLine($"{indentStr}reader.DangerousReadUnmanagedSpanWithOutHeaderWithCompress(ref {field.Name}ListOffset{depthSuffix}, ref {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                                sb.AppendLine($"{indentStr}LuminPackMarshal.SetListSize({targetObj}, {field.Name}Count{depthSuffix});");
                            }
                        }
                        else
                        {
                            if (depth > 0)
                            {
                                sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan(element__{depth - 1}, {field.Name}Count{depthSuffix});");
                                sb.AppendLine($"{indentStr}reader.ReadUnmanagedSpan(ref {offset}, ref {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                                sb.AppendLine($"{indentStr}LuminPackMarshal.SetListSize(element__{depth - 1}, {field.Name}Count{depthSuffix});");
                            }
                            else
                            {
                                if (!useFreshTopLevelList)
                                    sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan({targetObj}!, {field.Name}Count{depthSuffix});");
                                sb.AppendLine($"{indentStr}reader.ReadUnmanagedSpan(ref {offset}, ref {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                                sb.AppendLine($"{indentStr}LuminPackMarshal.SetListSize({targetObj}, {field.Name}Count{depthSuffix});");
                            }
                        }
                        sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                        break;
                        
                        // sb.AppendLine($"{indentStr}if (!reader.IsReferenceOrContainsReferences<{field.ClassName}>())");
                        // sb.AppendLine($"{indentStr}{{");
                        // if (depth > 0)
                        // {
                        //     sb.AppendLine($"{indentStr}    var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan(ref element__{depth - 1}, {field.Name}Count{depthSuffix});");
                        //     sb.AppendLine($"{indentStr}    reader.ReadUnmanagedSpan(ref {offset}, ref {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        //     sb.AppendLine($"{indentStr}    LuminPackMarshal.SetListSize(ref element__{depth - 1}, {field.Name}Count{depthSuffix});");
                        // }
                        // else
                        // {
                        //     sb.AppendLine($"{indentStr}    var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan(ref {targetObj}!, {field.Name}Count{depthSuffix});");
                        //     sb.AppendLine($"{indentStr}    reader.ReadUnmanagedSpan(ref {offset}, ref {field.Name}TempSpan{depthSuffix}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        //     sb.AppendLine($"{indentStr}    LuminPackMarshal.SetListSize(ref {targetObj}, {field.Name}Count{depthSuffix});");
                        // }
                        //
                        // sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                        // sb.AppendLine($"{indentStr}}}");
                        // sb.AppendLine($"{indentStr}else");
                    }
            
                    if (depth > 0)
                    {
                        sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan({fieldPath}!, {field.Name}Count{depthSuffix});");
                    }
                    else if (!useFreshTopLevelList)
                        sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = LuminPackMarshal.GetListSpan({targetObj}!, {field.Name}Count{depthSuffix});");

                    
                    sb.AppendLine($"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {field.Name}Count{depthSuffix}; i{depthSuffix}++)");
                    sb.AppendLine($"{indentStr}{{");
            
                    
                    StringBuilder arrayIndexFullSB = new StringBuilder();
                    if (isArray)
                    {
                        arrayIndexFullSB.Append($"[i{multList}{depth}]");
                    }
            
                    if (elementField.Type is LuminFiledType.List)
                    {
                        sb.AppendLine($"{indentStr}    if (!reader.TryReadCollectionHead(ref {field.Name}ListOffset{depthSuffix}, out int {elementField.Name}Count_{depth + 1}))");
                        sb.AppendLine($"{indentStr}    {{");
                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 4;");
                        sb.AppendLine($"{indentStr}        {field.Name}TempSpan{depthSuffix}[i{depthSuffix}] = default!;");
                        sb.AppendLine($"{indentStr}        continue;");
                        sb.AppendLine($"{indentStr}    }}");
                
                        string nestedGeneric = GetFullGenericTypeName(elementField.GenericType, elementField.ClassName, elementField.ClassGenericType);
                        sb.AppendLine($"{indentStr}    var element_{depthSuffix} = new List<{nestedGeneric}>({elementField.Name}Count_{depth + 1});");
                        sb.AppendLine($"{indentStr}    {field.Name}TempSpan{depthSuffix}[i{depthSuffix}] = element_{depthSuffix};");
                    }
                    else if (elementField.Type is LuminFiledType.Array)
                    {
                        var type = field.GenericType.Last();
                
                        sb.AppendLine($"{indentStr}    if (!reader.TryReadCollectionHead(ref {field.Name}ListOffset{depthSuffix}, out int {elementField.Name}Count_{depth + 1}))");
                        sb.AppendLine($"{indentStr}    {{");
                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 4;");
                        sb.AppendLine($"{indentStr}        {field.Name}TempSpan{depthSuffix}[i{depthSuffix}] = default!;");
                        sb.AppendLine($"{indentStr}        continue;");
                        sb.AppendLine($"{indentStr}    }}");
                
                        StringBuilder array = new StringBuilder();
                        for (var i = 1; i < field.GenericType.Count; i++)
                        {
                            if (field.GenericType[i] is not LuminGenericsType.Array) break;
                            array.Append("[]");
                        }
                
                        if (type is not LuminGenericsType.Struct and not LuminGenericsType.Class) 
                            sb.AppendLine($"{indentStr}    var element_{depthSuffix} = LuminPackMarshal.AllocateUninitializedArray<{GetGenericTypeName(type)}{array}>({elementField.Name}Count_{depth + 1});");
                        else
                            sb.AppendLine($"{indentStr}    var element_{depthSuffix} = LuminPackMarshal.AllocateUninitializedArray<{field.ClassName}{array}>({elementField.Name}Count_{depth + 1});");
                
                        sb.AppendLine($"{indentStr}    {field.Name}TempSpan{depthSuffix}[i{depthSuffix}] = element_{depthSuffix};");
                    }
                    else if (elementField.Type is LuminFiledType.Class)
                    {
                        sb.AppendLine($"{indentStr}    if (reader.PeekIsNullObject(ref {field.Name}ListOffset{depthSuffix}))");
                        sb.AppendLine($"{indentStr}    {{");
                        sb.AppendLine($"{indentStr}        {field.Name}TempSpan{depthSuffix}[i{depthSuffix}] = default!;");
                        sb.AppendLine($"{indentStr}        continue;");
                        sb.AppendLine($"{indentStr}    }}");
                    }
            
                    string elementPath = $"{field.Name}TempSpan{depthSuffix}[i{depthSuffix}]";
            
                    GenerateDeserializeCode(
                        sb, 
                        elementField, 
                        elementPath,
                        span, 
                        $"{field.Name}ListOffset{depthSuffix}", 
                        indent + 1, 
                        depth + 1, 
                        false,
                        elementPath,
                        isArray: false,
                        isList: true,
                        multList,
                        parentName: parentName + $"{field.Name}"
                    );
            
                    if (elementField.Type is not LuminFiledType.String and not LuminFiledType.Class and not LuminFiledType.Struct) 
                        if(elementField.Type is LuminFiledType.List or LuminFiledType.Array) 
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} = {GetFieldLength(elementField, depth + 1)};");
                        else
                        {
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {GetFieldLength(elementField, depth + 1)};");
                        }
                    sb.AppendLine($"{indentStr}}}");
                    break;
                case LuminFiledType.Array:
                    // 压缩路径：DangerousReadUnmanagedArrayWithCompress 内部自己读取 count+compressedLen，
                    // 不需要也不能在外部先调用 TryReadCollectionHead（否则指针会错位导致 Decompress 崩溃）
                    if (isFirst &&
                        !collectionHeadAlreadyRead &&
                        !(!IsReferenceGenericType(field.GenericType.FirstOrDefault()) && field.IsCompress))
                        sb.AppendLine($"{indentStr}reader.TryReadCollectionHead(ref {offset}, out int {field.Name}Count{depthSuffix});");
            
                    var arrayElementField = new LuminDataField
                    {
                        Name = field.Name,
                        Type = ConvertGenericsToFieldType(field.GenericType.FirstOrDefault()),
                        GenericType = field.GenericType.Skip(1).ToList(),
                        ClassName = field.ClassName,
                        ClassFields = field.ClassFields,
                        ClassGenericType = field.ClassGenericType,
                        ConstructParameterCount = field.ConstructParameterCount,
                        IsCompress = field.IsCompress,
                    };

                    StringBuilder arrayNum = new StringBuilder();
                    for (var i = 0; i < field.GenericType.Count; i++)
                    {
                        if (field.GenericType[i] is not LuminGenericsType.Array) break;
                        arrayNum.Append("[]");
                    }

                    // 压缩路径：reader.DangerousReadUnmanagedArrayWithCompress 会内部负责分配数组，不需要预分配
                    if (isFirst && !(!IsReferenceGenericType(field.GenericType.FirstOrDefault()) && field.IsCompress))
                    {
                        var type = field.GenericType.Last();
                
                        if (arrayElementField.Type is LuminFiledType.List)
                        {
                            string nestedGeneric = GetFullGenericTypeName(arrayElementField.GenericType, arrayElementField.ClassName, arrayElementField.ClassGenericType);
                            sb.AppendLine($"{indentStr}{targetObj} = LuminPackMarshal.AllocateUninitializedArray<List<{nestedGeneric}>{arrayNum}>({field.Name}Count{depthSuffix});");
                        }
                        else if (type is not LuminGenericsType.Struct and not LuminGenericsType.Class) 
                            sb.AppendLine($"{indentStr}{targetObj} = LuminPackMarshal.AllocateUninitializedArray<{GetGenericTypeName(type)}{arrayNum}>({field.Name}Count{depthSuffix});");
                        else
                            sb.AppendLine($"{indentStr}{targetObj} = LuminPackMarshal.AllocateUninitializedArray<{field.ClassName}{arrayNum}>({field.Name}Count{depthSuffix});");
                    }
                
                    sb.AppendLine($"{indentStr}int {field.Name}ListOffset{depthSuffix} = {offset} + 4;");
            
                    if (!IsReferenceGenericType(field.GenericType.FirstOrDefault()))
                    {
                        if (field.IsCompress)
                        {
                            // 压缩路径：从 offset（集合头部起点）开始读取，内部格式 [count:4][compressedLen:4][data]
                            // TempLength = 8 + compressedLen，所以 ListOffset = offset + TempLength
                            if (depth > 0)
                                sb.AppendLine($"{indentStr}reader.DangerousReadUnmanagedArrayWithCompress(ref {offset}, ref element__{depth - 1}, out var {field.Name}TempLength{depthSuffix});");
                            else
                                sb.AppendLine($"{indentStr}reader.DangerousReadUnmanagedArrayWithCompress(ref {offset}, ref {targetObj}!, out var {field.Name}TempLength{depthSuffix});");
                            sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} = {offset} + {field.Name}TempLength{depthSuffix};");
                        }
                        else
                        {
                            if (depth > 0) 
                                sb.AppendLine($"{indentStr}reader.ReadUnmanagedArray(ref {field.Name}ListOffset{depthSuffix}, ref element__{depth - 1}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                            else
                                sb.AppendLine($"{indentStr}reader.ReadUnmanagedArray(ref {field.Name}ListOffset{depthSuffix}, ref {targetObj}!, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                            sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                        }
                        break;
                    }
            
                    if (IsPureValueTypeStruct(arrayElementField))
                    {
                        if (field.IsCompress)
                        {
                            // 压缩路径：count 已由外层 TryReadCollectionHead 读取，这里从 ListOffset(=offset+4) 读 [compressedLen:4][data]
                            if (depth > 0)
                                sb.AppendLine($"{indentStr}reader.DangerousReadUnmanagedArrayWithOutHeaderWithCompress(ref {field.Name}ListOffset{depthSuffix}, ref element__{depth - 1}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                            else
                                sb.AppendLine($"{indentStr}reader.DangerousReadUnmanagedArrayWithOutHeaderWithCompress(ref {field.Name}ListOffset{depthSuffix}, ref {targetObj}!, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        }
                        else
                        {
                            if (depth > 0) 
                                sb.AppendLine($"{indentStr}reader.ReadUnmanagedArray(ref {offset}, ref element__{depth - 1}, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                            else
                                sb.AppendLine($"{indentStr}reader.ReadUnmanagedArray(ref {offset}, ref {targetObj}!, {field.Name}Count{depthSuffix}, out var {field.Name}TempLength{depthSuffix});");
                        }
                        sb.AppendLine($"{indentStr}{field.Name}ListOffset{depthSuffix} += {field.Name}TempLength{depthSuffix};");
                        break;
                    }
            
                    string arrayLoopLength;
                    if (depth > 0)
                    {
                        sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = {fieldPath}.AsSpan();");
                        arrayLoopLength = $"{field.Name}Count{depthSuffix}";
                    }
                    else
                    {
                        // The top-level array was allocated immediately above with the decoded
                        // length. Keeping it as an array lets the JIT use the cheaper array write
                        // barrier instead of the checked barrier required by a Span<T> byref.
                        sb.AppendLine($"{indentStr}var {field.Name}TempSpan{depthSuffix} = {targetObj}!;");
                        arrayLoopLength = $"{field.Name}Count{depthSuffix}";
                    }

                    sb.AppendLine($"{indentStr}for (int i{depthSuffix} = 0; i{depthSuffix} < {arrayLoopLength}; i{depthSuffix}++)");
                    sb.AppendLine($"{indentStr}{{");
            
                    if (arrayElementField.Type is LuminFiledType.List)
                    {
                        sb.AppendLine($"{indentStr}    if (!reader.TryReadCollectionHead(ref {field.Name}ListOffset{depthSuffix}, out int {arrayElementField.Name}Count_{depth + 1}))");
                        sb.AppendLine($"{indentStr}    {{");
                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 4;");
                        sb.AppendLine($"{indentStr}        continue;");
                        sb.AppendLine($"{indentStr}    }}");
                
                        string nestedGeneric = GetFullGenericTypeName(arrayElementField.GenericType, arrayElementField.ClassName, arrayElementField.ClassGenericType);
                        sb.AppendLine($"{indentStr}    var element_{depthSuffix} = new List<{nestedGeneric}>({arrayElementField.Name}Count_{depth + 1});");
                        sb.AppendLine($"{indentStr}    {field.Name}TempSpan{depthSuffix}[i{depthSuffix}] = element_{depthSuffix};");
                    }
                    else if (arrayElementField.Type is LuminFiledType.Array)
                    {
                        sb.AppendLine($"{indentStr}    if (!reader.TryReadCollectionHead(ref {field.Name}ListOffset{depthSuffix}, out int {arrayElementField.Name}Count_{depth + 1}))");
                        sb.AppendLine($"{indentStr}    {{");
                        sb.AppendLine($"{indentStr}        {field.Name}ListOffset{depthSuffix} += 4;");
                        sb.AppendLine($"{indentStr}        continue;");
                        sb.AppendLine($"{indentStr}    }}");
                
                        StringBuilder array = new StringBuilder();
                        for (var i = 1; i < field.GenericType.Count; i++)
                        {
                            if (field.GenericType[i] is not LuminGenericsType.Array) break;
                            array.Append("[]");
                        }
                        var type = field.GenericType.Last();
                        if (type is not LuminGenericsType.Struct and not LuminGenericsType.Class) 
                            sb.AppendLine($"{indentStr}    var element_{depthSuffix} = LuminPackMarshal.AllocateUninitializedArray<{GetGenericTypeName(type)}{array}>({arrayElementField.Name}Count_{depth + 1});");
                        else
                            sb.AppendLine($"{indentStr}    var element_{depthSuffix} = LuminPackMarshal.AllocateUninitializedArray<{field.ClassName}{array}>({arrayElementField.Name}Count_{depth + 1});");
                
                        sb.AppendLine($"{indentStr}    {field.Name}TempSpan{depthSuffix}[i{depthSuffix}] = element_{depthSuffix};");
                    }
                    else if (arrayElementField.Type is LuminFiledType.Class)
                    {
                        sb.AppendLine($"{indentStr}    if (reader.PeekIsNullObject(ref {field.Name}ListOffset{depthSuffix}))");
                        sb.AppendLine($"{indentStr}    {{");
                        sb.AppendLine($"{indentStr}        continue;");
                        sb.AppendLine($"{indentStr}    }}");
                    }
            
                    string arrayElementPath = $"{field.Name}TempSpan{depthSuffix}[i{depthSuffix}]";
            
                    GenerateDeserializeCode(
                        sb, 
                        arrayElementField, 
                        arrayElementPath,
                        span, 
                        $"{field.Name}ListOffset{depthSuffix}", 
                        indent + 1, 
                        depth + 1, 
                        false,
                        arrayElementPath,
                        isArray: true,
                        isList: false,
                        multList,
                        parentName: parentName + $"{field.Name}"
                    );
            
                    if (arrayElementField.Type is not LuminFiledType.String and not LuminFiledType.Class and not LuminFiledType.Struct) 
                        if(arrayElementField.Type is LuminFiledType.Array or LuminFiledType.List) 
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} = {GetFieldLength(arrayElementField, depth + 1)};");
                        else
                        {
                            sb.AppendLine($"{indentStr}    {field.Name}ListOffset{depthSuffix} += {GetFieldLength(arrayElementField, depth + 1)};");
                        }
                    sb.AppendLine($"{indentStr}}}");
                    break;
                case LuminFiledType.Class:
                case LuminFiledType.Struct:
                    if (IsPureValueTypeStruct(field))
                    {
                        sb.AppendLine($"{indentStr}// 纯值类型结构体");
                        sb.AppendLine($"{indentStr}reader.Advance(reader.ReadUnmanaged(ref {offset}, out {targetObj}));");
                        break;
                    }
                    sb.AppendLine($"{indentStr}// 反序列化{field.ClassName}");
                    sb.AppendLine($"{indentStr}{offset} += 1;");

                    var deserializeDirectlyIntoNestedObject = CanDeserializeDirectlyIntoNestedObject(field);
                    var nestedResultName = $"{parentName}{field.Name}Result{depthSuffix}";
                    if (deserializeDirectlyIntoNestedObject)
                    {
                        // Give the JIT one strongly typed object reference to keep live and avoid a
                        // large set of field temps. Named field types stay unpublished until complete;
                        // collection elements use target-typed new because their full name is absent.
                        if (string.IsNullOrWhiteSpace(field.FullTypeName))
                        {
                            sb.AppendLine($"{indentStr}var {nestedResultName} = {targetObj} = new();");
                        }
                        else
                        {
                            sb.AppendLine($"{indentStr}var {nestedResultName} = new {field.FullTypeName}();");
                        }
                    }
            
                    // 为嵌套类的每个字段定义局部变量
                    if (!deserializeDirectlyIntoNestedObject)
                    {
                        sb.AppendLine($"{indentStr}// 定义嵌套类字段的局部变量");
                        foreach (var subField in field.ClassFields)
                        {
                            var nullable = subField.FieldType == LuminDataType.Reference ? "?" : "";
                            sb.AppendLine($"{indentStr}{GetFieldLocalVariableType(subField)}{nullable} {parentName}{field.Name}{subField.Name}Temp{depthSuffix} = default!;");
                        }
                        sb.AppendLine();
                    }
            
                    // 反序列化嵌套类字段到局部变量
                    for (int i = 0; i < field.ClassFields.Count; i++)
                    {
                        var subField = field.ClassFields[i];
                        var subFieldTarget = deserializeDirectlyIntoNestedObject
                            ? $"{nestedResultName}.{subField.Identifier}"
                            : $"{parentName}{field.Name}{subField.Name}Temp{depthSuffix}";
                        subField.belongClassFieldName = field.Name;
                        var indentTemp = indent;
                        
                        #region 连续值类型字段优化
                        if (IsMergeableField(subField))
                        {
                            var num = FindNextMergeableField(field.ClassFields, i);
                            if (num != i)
                            {
                                if (num - i >= 14)
                                {
                                    num = i + 14;
                                }
                        
                                sb.Append($"{indentStr}{offset} += reader.ReadUnmanaged(ref {offset}");
                                for (var j = i; j <= num; j++)
                                {
                                    var mergedSubField = field.ClassFields[j];
                                    var mergedTarget = deserializeDirectlyIntoNestedObject
                                        ? $"{nestedResultName}.{mergedSubField.Identifier}"
                                        : $"{parentName}{field.Name}{mergedSubField.Name}Temp{depthSuffix}";
                                    sb.Append($", out {mergedTarget}");
                                }
                                sb.Append(");");
                                sb.AppendLine();
                                i = num;
                                continue;
                            }
                        }
                        #endregion
                        
                        switch (subField.Type)
                        {
                            case LuminFiledType.Array or LuminFiledType.List:
                                sb.AppendLine($"{indentStr}if (reader.PeekIsNullCollection(ref {offset}))");
                                sb.AppendLine($"{indentStr}{{");
                                sb.AppendLine($"{indentStr}    {offset} += 4;");
                                sb.AppendLine($"{indentStr}    {subFieldTarget} = default;");
                                sb.AppendLine($"{indentStr}}}"); 
                                sb.AppendLine($"{indentStr}else");
                                indentTemp += 1; break;
                            case LuminFiledType.Class:
                                sb.AppendLine($"{indentStr}if (reader.PeekIsNullObject(ref {offset}))");
                                sb.AppendLine($"{indentStr}{{");
                                sb.AppendLine($"{indentStr}    {offset} += 1;");
                                sb.AppendLine($"{indentStr}    {subFieldTarget} = default;");
                                sb.AppendLine($"{indentStr}}}");
                                sb.AppendLine($"{indentStr}else"); 
                                indentTemp += 1; break;
                        }
                
                        if (indentTemp != indent) 
                            sb.AppendLine($"{indentStr}{{");
                
                        var classDepth = subField.Type is LuminFiledType.List or LuminFiledType.Array ? 0 : depth + 1;
                
                        GenerateDeserializeCode(sb, subField, subFieldTarget, 
                            span, offset, indentTemp, classDepth, multList: multList + "_", 
                            isPrivateFiled: true, parentName: parentName + field.Name + "_");

                        var newIdentStr = indentTemp == indent ? indentStr : $"{indentStr}    ";

                        if (field.ClassFields[i].Type is not LuminFiledType.String and not LuminFiledType.Class and not LuminFiledType.Struct)
                        {
                            if (field.ClassFields[i].Type is LuminFiledType.Array or LuminFiledType.List)
                                sb.AppendLine($"{newIdentStr}{offset} = {GetFieldLength(subField, classDepth, multList: multList + "_")};");
                            else 
                                sb.AppendLine($"{newIdentStr}{offset} += {GetFieldLength(subField, classDepth, multList: multList + "_")};");
                        }
                    
                        if (indentTemp != indent) 
                            sb.AppendLine($"{indentStr}}}");
                    }

                    if (deserializeDirectlyIntoNestedObject)
                    {
                        if (!string.IsNullOrWhiteSpace(field.FullTypeName))
                            sb.AppendLine($"{indentStr}{targetObj} = {nestedResultName};");
                        break;
                    }
            
                    // 收集嵌套类构造函数参数
                    var nestedConstructorParams = new List<string>();
                    if (field.SelectedConstructor != null && field.SelectedConstructor.Parameters.Count > 0)
                    {
                        foreach (var param in field.SelectedConstructor.Parameters)
                        {
                            var matchingField = field.ClassFields.FirstOrDefault(f => f.Name == param.MatchingFieldName);
                            if (matchingField != null)
                            {
                                nestedConstructorParams.Add($"{parentName}{field.Name}{matchingField.Name}Temp{depthSuffix}");
                            }
                            else
                            {
                                nestedConstructorParams.Add("default");
                            }
                        }
                    }

                    string nestedConstructorArgs = string.Join(", ", nestedConstructorParams);

                    // 收集需要对象初始化器赋值的public字段
                    var nestedInitializerFields = field.ClassFields.Where(f => 
                        (field.SelectedConstructor == null || 
                         !field.SelectedConstructor.Parameters.Any(p => p.MatchingFieldName == f.Name)) &&
                        !f.IsPrivate
                    ).ToList();

                    // 收集需要单独设置的private字段
                    var nestedPrivateFields = field.ClassFields.Where(f => 
                        (field.SelectedConstructor == null || 
                         !field.SelectedConstructor.Parameters.Any(p => p.MatchingFieldName == f.Name)) &&
                        f.IsPrivate
                    ).ToList();

                    if (field.RentPoolMethod != null)
                    {
                        // 使用对象池分配嵌套类对象
                        if (field.RentPoolMethod.ReturnsByRef)
                            sb.AppendLine($"            value = ref {field.FullTypeName}.{field.RentPoolMethod.Name}();");
                        else
                        {
                            sb.AppendLine($"{indentStr}{targetObj} = {field.FullTypeName}.{field.RentPoolMethod.Name}();");
                        }
    
                        // 对于对象池分配的对象，直接设置所有字段
                        sb.AppendLine($"{indentStr}// 设置所有字段（对象池分配）");
    
                        // 设置所有字段（包括public和private）
                        foreach (var subField in field.ClassFields)
                        {
                            if (subField.IsPrivate)
                            {
                                // private字段使用UnsafeAccessor
                                sb.AppendLine($"{indentStr}Get{field.Name}{subField.Name}({targetObj}) = {parentName}{field.Name}{subField.Name}Temp{depthSuffix};");
                            }
                            else
                            {
                                // public字段直接设置
                                sb.AppendLine($"{indentStr}{targetObj}.{subField.Identifier} = {parentName}{field.Name}{subField.Name}Temp{depthSuffix};");
                            }
                        }
                    }
                    else
                    {
                        // 使用对象初始化器创建嵌套类对象
                        if (nestedInitializerFields.Count > 0)
                        {
                            // 有对象初始化器的情况
                            if (field.SelectedConstructor != null && field.SelectedConstructor.Parameters.Count > 0)
                            {
                                sb.AppendLine($"{indentStr}{targetObj} = new {field.FullTypeName}({nestedConstructorArgs})");
                            }
                            else
                            {
                                sb.AppendLine($"{indentStr}{targetObj} = new {field.FullTypeName}()");
                            }
                            sb.AppendLine($"{indentStr}{{");
                            foreach (var subField in nestedInitializerFields)
                            {
                                sb.AppendLine($"{indentStr}    {subField.Name} = {parentName}{field.Name}{subField.Name}Temp{depthSuffix},");
                            }
                            sb.AppendLine($"{indentStr}}};");
                        }
                        else
                        {
                            // 没有对象初始化器的情况
                            if (field.SelectedConstructor != null && field.SelectedConstructor.Parameters.Count > 0)
                            {
                                sb.AppendLine($"{indentStr}{targetObj} = new {field.FullTypeName}({nestedConstructorArgs});");
                            }
                            else
                            {
                                sb.AppendLine($"{indentStr}{targetObj} = new {field.FullTypeName}();");
                            }
                        }

                        // 设置private字段（使用UnsafeAccessor）
                        if (nestedPrivateFields.Count > 0)
                        {
                            sb.AppendLine($"{indentStr}// 设置private字段");
                            foreach (var subField in nestedPrivateFields)
                            {
                                sb.AppendLine($"{indentStr}Get{field.Name}{subField.Name}({targetObj}) = {parentName}{field.Name}{subField.Name}Temp{depthSuffix};");
                            }
                        }
                    }
                    
                    // 赋值给目标对象
                    //sb.AppendLine($"{indentStr}{targetObj} = {parentName}{field.Name}Temp{depthSuffix};");
                    // if (isFirst && !isPrivateFiled)
                    //     sb.AppendLine($"{indentStr}{targetObj}.{field.Name} = {parentName}{field.Name}Temp{depthSuffix};");
                    // else 
                    //     sb.AppendLine($"{indentStr}{targetObj} = {parentName}{field.Name}Temp{depthSuffix};");
                    break;
                case LuminFiledType.Enum:
                    if (isFirst) 
                    {
                        // Every first-level caller now passes the exact destination (field or temp).
                        // Appending the identifier again turns an isolated enum into e.g. SlotTemp.Slot.
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn<{field.TypeName}>(ref {offset}, out {targetObj});");
                    }
                    else
                    {
                        sb.AppendLine($"{indentStr}reader.ReadUnmanagedWithoutSizeReturn<{field.TypeName}>(ref {offset}, out var {field.Name}TempValue{depthSuffix});");
                        sb.AppendLine($"{indentStr}{targetObj} = {field.Name}TempValue{depthSuffix};");
                    }
                    break;
                case LuminFiledType.Other:
                default:
                    if (field.IsCompress)
                        sb.AppendLine($"{indentStr}reader.ReadValueWithCompress(ref {targetObj});");
                    else if (targetIsKnownFresh && IsExactFreshCollectionType(field))
                        sb.AppendLine($"{indentStr}reader.ReadFreshValue(ref {targetObj});");
                    else
                        sb.AppendLine($"{indentStr}reader.ReadValue(ref {targetObj});");
                    break;
            }
        }

