"""Generate typed Rust DTOs and their checked binary operations."""

from itertools import groupby

from generate import SCALARS, symbol


def bodies(n, entries):
    reads, writes = [], []
    for scalar, run in groupby(entries, key=lambda e: e[1] in SCALARS):
        fields = list(run)
        if not scalar or len(fields) == 1:
            for f, ch, _ in fields:
                reads.append(f"let {f}=read_{ch}(r)?;")
                writes.append(f"write_{ch}(out,&v.{f})?;")
            continue
        width = sum(SCALARS[ch][3] for _, ch, _ in fields)
        reads.append(f"let block=r.take({width})?;")
        writes.append(f"let mut block=[0u8;{width}];")
        offset = 0
        for f, ch, ty in fields:
            end = offset + SCALARS[ch][3]
            if end == offset + 1:
                expr = f"block[{offset}]"
                if ch == "bool":
                    expr = f'match {expr}{{0=>false,1=>true,_=>return Err("Invalid boolean")}}'
                writes.append(f"block[{offset}]=v.{f} as u8;")
            else:
                expr = (
                    f"{ty}::from_le_bytes(block[{offset}..{end}].try_into().unwrap())"
                )
                writes.append(
                    f"block[{offset}..{end}].copy_from_slice(&v.{f}.to_le_bytes());"
                )
            reads.append(f"let {f}={expr};")
            offset = end
        writes.append("out.extend_from_slice(&block);")
    read = (
        f"#[inline] fn body_{n}(r:&mut Reader)->Result<{n}>{{"
        + "".join(reads)
        + f"Ok({n}{{"
        + ",".join(f for f, _, _ in entries)
        + "})}"
    )
    write = (
        f"#[inline] fn store_{n}(out:&mut Vec<u8>,v:&{n})->Result<()>{{"
        + "".join(writes)
        + "Ok(())}"
    )
    return read, write


def emit(s):
    out = [
        "// Generated by LuminPack.\nuse luminpack::direct::{Reader, Result, write_count, write_text as put_text};"
    ]

    def function(n, ty, read, write):
        out.extend(
            [
                f"#[inline] fn read_{n}(r: &mut Reader) -> Result<{ty}> {{ {read} }}",
                f"#[inline] fn write_{n}(out: &mut Vec<u8>, v: &{ty}) -> Result<()> {{ {write} }}",
            ]
        )

    for n, w in list(s.shapes.items()):
        k = w["kind"]
        if k == "scalar":
            read = f"r.{SCALARS[n][1]}()"
            write = (
                "out.push(*v as u8);"
                if n in ("bool", "byte")
                else "out.extend_from_slice(&v.to_le_bytes());"
            ) + " Ok(())"
        elif k == "string":
            read, write = "r.text()", "put_text(out,v.as_deref())"
        else:
            dictionary = k == "dictionary"
            key = w.get("key")
            strings = dictionary and key["kind"] == "string"
            elem = w["value" if dictionary else "element"]
            child = s.shape(elem)
            minimum = s.width(elem) + (s.width(key) if dictionary else 0)
            read = f"let Some(n)=r.count({minimum})? else {{return Ok(None)}};"
            write = "let Some(items)=v else {out.extend_from_slice(&(-1i32).to_le_bytes());return Ok(())}; write_count(out,items.len())?;"
            if (
                not dictionary
                and elem["kind"] == "scalar"
                and elem["type"] in ("int", "long", "float", "byte")
            ):
                ty = s.rust_type(elem)
                if ty == "u8":
                    read += "Ok(Some(r.take(n)?.to_vec()))"
                    write += "out.extend_from_slice(items);Ok(())"
                else:
                    read += f"Ok(Some(r.take(n*{minimum})?.chunks_exact({minimum}).map(|b|{ty}::from_le_bytes(b.try_into().unwrap())).collect()))"
                    write += f'out.reserve(items.len().checked_mul({minimum}).ok_or("Collection too large")?); for x in items {{out.extend_from_slice(&x.to_le_bytes());}} Ok(())'
            else:
                read += (
                    "let mut items="
                    + ("std::collections::HashMap" if strings else "Vec")
                    + "::with_capacity(n.min(1024));"
                )
                if dictionary:
                    if strings:
                        read += f'for _ in 0..n {{let k=r.text()?.ok_or("Null key")?;if items.insert(k,read_{child}(r)?).is_some(){{return Err("Duplicate key")}}}}'
                        write += f"for(k,x)in items{{put_text(out,Some(k))?;write_{child}(out,x)?;}}"
                    else:
                        kn = s.shape(key)
                        seen = "let mut seen=std::collections::HashSet::new();"
                        dup = 'if !seen.insert(k){return Err("Duplicate key")};'
                        read += (
                            seen
                            + f"for _ in 0..n {{let k=read_{kn}(r)?;{dup}items.push((k,read_{child}(r)?));}}"
                        )
                        write += (
                            seen
                            + f"for(k,x)in items{{{dup}write_{kn}(out,k)?;write_{child}(out,x)?;}}"
                        )
                else:
                    read += f"for _ in 0..n {{items.push(read_{child}(r)?);}}"
                    write += f"for x in items {{write_{child}(out,x)?;}}"
                read += "Ok(Some(items))"
                write += "Ok(())"
        function(n, s.rust_type(w), read, write)
    for t, c in s.contracts.items():
        n = s.names[t]
        fields = c["members"]
        record = c["kind"] == "Record"
        if c["kind"] == "Union":
            cases = [
                (s.names[x["type"].replace("global::", "")], x["hash"])
                for x in c["cases"]
            ]
            out.append(
                f"pub enum {n} {{" + ",".join(f"{v}({v})" for v, _ in cases) + "}"
            )
            read = (
                "match r.int()? as u32 {0=>Ok(None),"
                + ",".join(f"{h}=>Ok(Some({n}::{v}(body_{v}(r)?)))" for v, h in cases)
                + ',_=>Err("Unknown Union tag")}'
            )
            write = (
                "match v {None=>out.extend_from_slice(&0u32.to_le_bytes()),"
                + ",".join(
                    f"Some({n}::{v}(x))=>{{out.extend_from_slice(&{h}u32.to_le_bytes());store_{v}(out,x)?;}}"
                    for v, h in cases
                )
                + "};Ok(())"
            )
        else:
            entries = [
                ("f_" + symbol(m["name"]), s.shape(m["wire"]), s.rust_type(m["wire"]))
                for m in fields
            ]
            out.append(
                "#[allow(non_snake_case)] pub struct "
                + n
                + "{"
                + ",".join(f"pub {f}:{ty}" for f, _, ty in entries)
                + "}"
            )
            out.extend(bodies(n, entries))
            if record:
                read = f'match r.byte()? {{255=>Ok(None),{len(fields)}=>Ok(Some(body_{n}(r)?)),_=>Err("Invalid record header")}}'
                write = f"if let Some(x)=v {{out.push({len(fields)});store_{n}(out,x)}}else{{out.push(255);Ok(())}}"
            else:
                read, write = f"body_{n}(r)", f"store_{n}(out,v)"
        function(n, s.rust_type({"kind": "contract", "type": t}), read, write)
    n = s.names[s.root]
    ty = s.rust_type({"kind": "contract", "type": s.root})
    out.append(f"pub type Root={ty};")
    out.append(
        f'pub fn decode_binary(data:&[u8])->Result<Root>{{if data.len()>{s.limits[0]}{{return Err("Input too large")}}let mut r=Reader::new(data,{s.limits[1]},{s.limits[2]});let v=read_{n}(&mut r)?;'
    )
    if s.complete:
        out.append('if !r.complete(){return Err("Trailing bytes")}')
    out.append(
        "Ok(v)}\nstd::thread_local! {static LAST_SIZE:std::cell::Cell<usize>=const {std::cell::Cell::new(256)};}"
    )
    out.append(
        f"pub fn encode_binary_into(v:&Root,out:&mut Vec<u8>)->Result<()>{{let start=out.len();if let Err(e)=write_{n}(out,v){{out.truncate(start);return Err(e)}}Ok(())}}"
    )
    out.append(
        f"pub fn encode_binary(v:&Root)->Result<Vec<u8>>{{let mut out=Vec::with_capacity(LAST_SIZE.get());write_{n}(&mut out,v)?;LAST_SIZE.set(out.len().min(1048576));Ok(out)}}"
    )
    out.append("""
pub fn decode_json(codec:&luminpack::Codec, data:&[u8], format:luminpack::Format,
                   binary_scratch:&mut [u8])->std::result::Result<Root,String>{
    let doc=codec.decode(data,format)?;
    decode_binary(doc.encode_into(binary_scratch,luminpack::Format::Binary)?).map_err(String::from)
}
pub fn encode_json<'a>(codec:&luminpack::Codec, value:&Root, format:luminpack::Format,
                       output:&'a mut [u8])->std::result::Result<&'a [u8],String>{
    let binary=encode_binary(value)?;
    codec.decode(&binary,luminpack::Format::Binary)?.encode_into(output,format)
}
""")
    out.append("pub use self::{encode_binary as serialize, decode_binary as deserialize};")
    return "\n".join(out) + "\n"
