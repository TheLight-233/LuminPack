using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;

/// <summary>Projects LuminPack contracts and emits their native runtime entry points.</summary>
internal static class PortableGenerateCommand
{
    /// <summary>Runs the portable projection or generation command after validating its options.</summary>
    /// <param name="language">The output language, or null for the shared manifest.</param>
    /// <param name="arguments">The options, manifest path, root identity and destination.</param>
    /// <returns>Whether the arguments describe a complete request.</returns>
    internal static bool TryRun(string? language, ReadOnlySpan<string> arguments)
    {
        if (language is not (null or "java" or "go" or "typescript"))
            return false;

        int index = 0;
        int? binaryProfile = null;
        int? nativeIntegerBytes = null;
        int? nativeScalarAlignment = null;
        string? package = null;
        string? runtimeImport = null;
        while (index < arguments.Length && arguments[index].StartsWith("--", StringComparison.Ordinal))
        {
            if (index + 1 >= arguments.Length)
                return false;
            string flag = arguments[index++];
            string value = arguments[index++];
            switch (flag)
            {
                case "--binary-profile" when binaryProfile == null:
                    binaryProfile = BinaryProfiles.Parse(value);
                    break;
                case "--native-integer-bytes" when nativeIntegerBytes == null && value is "4" or "8":
                    nativeIntegerBytes = int.Parse(value, CultureInfo.InvariantCulture);
                    break;
                case "--native-scalar-alignment" when nativeScalarAlignment == null && value is "4" or "8":
                    nativeScalarAlignment = int.Parse(value, CultureInfo.InvariantCulture);
                    break;
                case "--package" when package == null && language is "java" or "go":
                    package = value;
                    break;
                case "--runtime-import" when runtimeImport == null && language == "typescript" && value.Length != 0:
                    runtimeImport = value;
                    break;
                default:
                    return false;
            }
        }
        if (arguments.Length - index != 3)
            return false;
        string manifest = arguments[index];
        string destination = arguments[index + 2];
        JsonObject schema = PortableManifest.Project(manifest, arguments[index + 1], binaryProfile, nativeIntegerBytes ?? 8,
            nativeScalarAlignment ?? 8);
        string document = schema.ToJsonString();
        string output = language switch
        {
            "java" => EmitJava(destination, package ?? "luminpack.generated", document),
            "go" => EmitGo(schema, package ?? "generated", document),
            "typescript" => EmitTypeScript(schema, runtimeImport ?? "@luminpack/typescript", document),
            _ => document + "\n"
        };
        OutputFile.Replace(manifest, destination, stream =>
        {
            using var writer = new StreamWriter(stream, new UTF8Encoding(false), leaveOpen: true);
            writer.Write(output);
        });
        return true;
    }

    /// <summary>Generates a Java class with an immutable runtime binding.</summary>
    /// <param name="destination">The Java file whose name matches the class.</param>
    /// <param name="package">The package selected for generated sources.</param>
    /// <param name="document">The normalized contract.</param>
    /// <returns>The Java source.</returns>
    private static string EmitJava(string destination, string package, string document)
    {
        string name = Path.GetFileNameWithoutExtension(destination);
        if (!ValidIdentifier(name) || !package.Split('.').All(ValidIdentifier))
            throw new ArgumentException("Invalid Java class or package name.");
        var output = new StringBuilder("// Generated by LuminPack.Codegen.\npackage ");
        output.Append(package).Append(";\n\nimport luminpack.LuminPack;\n\npublic final class ").Append(name)
            .Append(" {\n    private ").Append(name).Append("() {}\n\n    public static final LuminPack CODEC = LuminPack.fromManifest(String.join(\n        \"\",\n");
        string[] parts = Enumerable.Range(0, (document.Length + 11999) / 12000)
            .Select(index => Quote(document.Substring(index * 12000, Math.Min(12000, document.Length - index * 12000)))).ToArray();
        output.Append("        ").Append(string.Join(",\n        ", parts)).Append("));\n}\n");
        return output.ToString();
    }

    /// <summary>Generates a Go loader for the named root.</summary>
    /// <param name="schema">The projected manifest.</param>
    /// <param name="package">The package selected for generated sources.</param>
    /// <param name="document">The normalized contract.</param>
    /// <returns>The Go source.</returns>
    private static string EmitGo(JsonObject schema, string package, string document)
    {
        if (!ValidIdentifier(package))
            throw new ArgumentException("Invalid Go package name.");
        string type = PortableManifest.Text(schema, "root");
        JsonObject? root = PortableManifest.Objects(schema, "contracts").FirstOrDefault(item =>
            PortableManifest.Normalize(PortableManifest.Text(item, "type")) == type);
        string function = "Load" + Identifier(root == null ? type : PortableManifest.Text(root, "name")) + "LuminPack";
        return "// Code generated by LuminPack.Codegen. DO NOT EDIT.\n\npackage " + package +
            "\n\nimport \"github.com/TheLight-233/LuminPack/src/LuminPack.Go\"\n\n// " + function +
            " loads the generated LuminPack root.\nfunc " + function + "() (*luminpack.Schema, error) {\n\treturn luminpack.LoadSchema([]byte(" +
            Quote(document) + "))\n}\n";
    }

    /// <summary>Generates native TypeScript DTO shapes and the typed serializer entry point.</summary>
    /// <param name="schema">The projected manifest.</param>
    /// <param name="runtimeImport">The runtime module specifier.</param>
    /// <param name="document">The normalized contract.</param>
    /// <returns>The TypeScript source.</returns>
    private static string EmitTypeScript(JsonObject schema, string runtimeImport, string document)
    {
        JsonObject[] contracts = PortableManifest.Objects(schema, "contracts").ToArray();
        var declarations = contracts.ToDictionary(item => PortableManifest.Normalize(PortableManifest.Text(item, "type")), StringComparer.Ordinal);
        var result = new StringBuilder("// Generated by LuminPack.Codegen.\nimport { createCodec, type Codec, type CodecOptions } from ");
        result.Append(Quote(runtimeImport)).Append(";\n\n");
        foreach (var (type, contract) in declarations)
        {
            string name = "Contract_" + Identifier(type) + "<_ArrayViews extends boolean = false>";
            if (contract["sequenceWire"] is JsonObject sequence)
            {
                result.Append("export type ").Append(name).Append(" = ").Append(TypeScriptType(sequence, declarations, "_ArrayViews")).Append(";\n\n");
                continue;
            }
            switch (PortableManifest.Text(contract, "kind"))
            {
                case "Union":
                    result.Append("export type ").Append(name).Append(" = null");
                    foreach (JsonObject item in PortableManifest.Objects(contract, "cases"))
                    {
                        string identity = PortableManifest.Normalize(PortableManifest.Text(item, "type"));
                        result.Append("\n  | { type: ").Append(Quote(identity)).Append("; value: NonNullable<Contract_")
                            .Append(Identifier(identity)).Append("<_ArrayViews>> }");
                    }
                    result.Append(";\n\n");
                    break;
                case "Custom":
                    result.Append("export type ").Append(name).Append(" = unknown;\n\n");
                    break;
                default:
                    result.Append("export type ").Append(name).Append(" = {\n");
                    foreach (JsonObject member in PortableManifest.Objects(contract, "members"))
                        result.Append("  ").Append(Quote(PortableManifest.Text(member, "name"))).Append(": ")
                            .Append(TypeScriptType((JsonObject)member["wire"]!, declarations, "_ArrayViews")).Append(";\n");
                    result.Append("}");
                    if (PortableManifest.Text(contract, "kind") == "Record")
                        result.Append(" | null");
                    result.Append(";\n\n");
                    break;
            }
        }
        string root = "Contract_" + Identifier(PortableManifest.Text(schema, "root"));
        if (schema["rootWire"] is JsonObject wire)
            result.Append("export type Root = ").Append(TypeScriptType(wire, declarations, "false")).Append(";\n")
                .Append("export type RootInput = ").Append(TypeScriptType(wire, declarations, "true")).Append(";\n\n");
        else
            result.Append("export type Root = ").Append(root).Append(";\n")
                .Append("export type RootInput = ").Append(root).Append("<true>;\n\n");
        result
            .Append("const manifest: unknown = JSON.parse(").Append(Quote(document)).Append(");\n\n")
            .Append("export function bindCodec(options?: CodecOptions): Codec<Root, RootInput>;\n")
            .Append("export function bindCodec<T, TInput = T>(options?: CodecOptions): Codec<T, TInput>;\n")
            .Append("export function bindCodec(options?: CodecOptions): Codec<unknown> {\n  return createCodec(manifest, options);\n}\n\n")
            .Append("export const codec = bindCodec();\n");
        return result.ToString();
    }

    /// <summary>Translates a normalized descriptor to the TypeScript runtime's value surface.</summary>
    /// <param name="wire">The normalized wire descriptor.</param>
    /// <param name="declarations">The reachable declarations.</param>
    /// <param name="arrayViews">The flag that permits native numeric inputs.</param>
    /// <returns>The generated TypeScript type expression.</returns>
    private static string TypeScriptType(JsonObject wire, Dictionary<string, JsonObject> declarations, string arrayViews)
    {
        string kind = PortableManifest.Text(wire, "kind");
        string? scalar = wire["type"]?.GetValue<string>();
        return kind switch
        {
            "scalar" when scalar is "long" or "ulong" => "bigint",
            "scalar" when scalar is "nint" or "nuint" => wire["width"]?.GetValue<int>() == 4 ? "number" : "bigint",
            "scalar" when scalar == "bool" => "boolean",
            "scalar" when scalar == "char" => "string",
            "scalar" => "number",
            "string" => "string | null",
            "contract" when declarations.ContainsKey(scalar!) => "Contract_" + Identifier(scalar!) + "<" + arrayViews + ">",
            "nullable" => TypeScriptType((JsonObject)wire["element"]!, declarations, arrayViews) + " | null",
            "sequence" => TypeScriptSequence((JsonObject)wire["element"]!, declarations, arrayViews) +
                (wire["required"]?.GetValue<bool>() == true ? string.Empty : " | null"),
            "dictionary" => "Map<NonNullable<" + TypeScriptType((JsonObject)wire["key"]!, declarations, arrayViews) + ">, " +
                TypeScriptType((JsonObject)wire["value"]!, declarations, arrayViews) + "> | null",
            "pair" or "tuple" => "[" + string.Join(", ", PortableManifest.Objects(wire, "elements")
                .Select(item => TypeScriptType(item, declarations, arrayViews))) + "]",
            "rectangular" => "{ lengths: number[]; lowerBounds: number[]; values: Array<" +
                TypeScriptType((JsonObject)wire["element"]!, declarations, arrayViews) + "> } | null",
            _ => "unknown"
        };
    }

    /// <summary>Allows exact native typed-array inputs for numeric collections.</summary>
    /// <param name="element">The normalized element descriptor.</param>
    /// <param name="declarations">The reachable declarations.</param>
    /// <param name="arrayViews">The flag that permits native numeric inputs.</param>
    /// <returns>The generated TypeScript collection shape.</returns>
    private static string TypeScriptSequence(JsonObject element, Dictionary<string, JsonObject> declarations, string arrayViews)
    {
        string? view = PortableManifest.Text(element, "kind") == "scalar" ? PortableManifest.Text(element, "type") switch
        {
            "sbyte" => "Int8Array",
            "byte" => "Uint8Array",
            "short" => "Int16Array",
            "ushort" => "Uint16Array",
            "int" => "Int32Array",
            "uint" => "Uint32Array",
            "long" => "BigInt64Array",
            "ulong" => "BigUint64Array",
            "float" => "Float32Array",
            "double" => "Float64Array",
            "nint" => element["width"]?.GetValue<int>() == 4 ? "Int32Array" : "BigInt64Array",
            "nuint" => element["width"]?.GetValue<int>() == 4 ? "Uint32Array" : "BigUint64Array",
            _ => null
        } : null;
        string array = "Array<" + TypeScriptType(element, declarations, arrayViews) + ">";
        return view == null || arrayViews == "false" ? array :
            array + " | (" + arrayViews + " extends true ? " + view + " : never)";
    }

    /// <summary>Checks a package or source identifier component.</summary>
    /// <param name="value">The requested name.</param>
    /// <returns>Whether the name uses portable identifier characters.</returns>
    private static bool ValidIdentifier(string value) => value.Length != 0 &&
        (char.IsAsciiLetter(value[0]) || value[0] == '_') && value.All(ch => char.IsAsciiLetterOrDigit(ch) || ch == '_');

    /// <summary>Encodes punctuation without collisions in a generated identifier suffix.</summary>
    /// <param name="value">The original declaration identity.</param>
    /// <returns>The generated identifier suffix.</returns>
    private static string Identifier(string value) => string.Concat(value.Select(character => char.IsAsciiLetterOrDigit(character)
        ? character.ToString() : "_x" + ((int)character).ToString("x4", CultureInfo.InvariantCulture)));

    /// <summary>Quotes compact JSON and module paths as portable Java, Go and TypeScript source strings.</summary>
    /// <param name="value">The source string content.</param>
    /// <returns>The escaped source literal.</returns>
    private static string Quote(string value)
    {
        var result = new StringBuilder(value.Length + 2).Append('"');
        foreach (char character in value)
        {
            switch (character)
            {
                case '"': result.Append("\\\""); break;
                case '\\': result.Append("\\\\"); break;
                case '\n': result.Append("\\n"); break;
                case '\r': result.Append("\\r"); break;
                case '\t': result.Append("\\t"); break;
                default:
                    if (char.IsControl(character))
                        result.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
                    else
                        result.Append(character);
                    break;
            }
        }
        return result.Append('"').ToString();
    }
}
